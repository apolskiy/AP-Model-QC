"""One ticket file per filed finding, for submitting each to its vendor alone.

Created: 2026-10-15
Last updated: 2026-10-28

This file contains ``page_name`` and ``ticket_name``, which name an engine's
findings page and one finding's ticket file, ``write_tickets``, which writes a
ticket per filed finding and removes generated tickets no longer filed,
``drop_engine_output``, which removes the page and the directory of an engine
with nothing filed, and ``filing_sheet``, which returns the index a person files
from, and ``intake``, ``intake_engines`` and ``case_layer``, which it reads to
say where a vendor takes a report and which findings are one defect. A file
without the generated mark on its first line is never removed.

``tools.ticket_report`` calls it after building each engine's page, and
``tools.finding_evidence`` uses ``page_name`` to find the page it reads. The
files written are what a person submits to a vendor, one finding each, and the
sheet is where they start.

Design: ``docs/design/consumer_ci.md`` sections 9.5.5.2 and 9.5.5.10.
"""

import re
from pathlib import Path
from typing import Any, Final

GENERATED_MARK: Final[str] = (
    "<!-- Generated by tools/ticket_report.py. Regenerating replaces or removes this file. -->"
)
_CASE: Final[re.Pattern[str]] = re.compile(r"^MQC_[A-Z]{3}_[A-Z]{3,5}_(\d{6})_(\w+)$")


def page_name(engine: str) -> str:
    """Return the file an engine's findings page is written to.

    Args:
        engine (str): The engine.

    Returns:
        str: ``<engine>_findings.md``, a name no assistant loads as
        instructions (``consumer_ci.md`` section 9.5.5.5).
    """
    return f"{engine}_findings.md"


def ticket_name(case: str) -> str:
    """Return the file a finding's ticket is written to.

    Args:
        case (str): The case identifier, such as
            ``MQC_EVL_EVAL_134109_diagnoses_the_cause_and_not_only_the_outcome``.

    Returns:
        str: ``<number>_<behaviour>.md``.

    Raises:
        ValueError: When the identifier is not a case name.
    """
    matched = _CASE.match(case)
    if matched is None:
        raise ValueError(f"{case!r} is not a case identifier")
    return f"{matched.group(1)}_{matched.group(2)}.md"


def write_tickets(
    directory: Path, engine: str, sections: list[tuple[dict[str, Any], list[str]]]
) -> list[Path]:
    """Write one ticket per finding and remove generated tickets no longer filed.

    Args:
        directory (Path): The engine's ticket directory, created if absent.
        engine (str): The engine, named in each ticket's title.
        sections (list): Each filed finding with its section lines.

    Returns:
        list[Path]: The tickets written. A file whose first line is not
        :data:`GENERATED_MARK` is never removed, so a hand-written ticket
        survives regeneration.
    """
    directory.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for entry, lines in sections:
        path = directory / ticket_name(str(entry.get("case", "")))
        title = (f"# Finding against `{engine}`, model "
                 f"`{entry.get('observed_model', '')}`")
        path.write_text("\n".join([GENERATED_MARK, "", title, "", *lines]),
                        encoding="utf-8", newline="\n")
        written.append(path)
    for stale in sorted(directory.glob("*.md")):
        if stale in written:
            continue
        # READ, CLOSED, THEN REMOVED. Windows refuses to delete an open file.
        with stale.open(encoding="utf-8") as handle:
            generated = handle.readline().strip() == GENERATED_MARK
        if generated:
            stale.unlink()
    return written


def drop_engine_output(directory: Path, engine: str) -> list[Path]:
    """Remove an engine's generated page and its directory, where nothing is filed.

    **Called only for an engine with no filed finding** (``consumer_ci.md``
    section 9.5.5.11). The tickets directory is read as the list of what to
    file, so a page reading zero findings and an empty engine directory are
    output nothing produced a finding for.

    Args:
        directory (Path): The tickets directory holding the pages.
        engine (str): The engine whose output goes.

    Returns:
        list[Path]: What was removed, which is empty where both guards hold. A
        page is removed only where its first line is :data:`GENERATED_MARK`,
        and a directory only where it is empty, so a page written by hand and a
        directory still holding a ticket both survive.
    """
    removed: list[Path] = []
    page = directory / page_name(engine)
    if page.is_file():
        # READ, CLOSED, THEN REMOVED, as the ticket pruning does: Windows
        # refuses to delete a file that is still open.
        with page.open(encoding="utf-8") as handle:
            generated = handle.readline().strip() == GENERATED_MARK
        if generated:
            page.unlink()
            removed.append(page)
    tickets = directory / engine
    if tickets.is_dir() and not any(tickets.iterdir()):
        tickets.rmdir()
        removed.append(tickets)
    return removed


# WHERE EACH VENDOR TAKES A REPORT ABOUT ITS MODEL'S BEHAVIOUR, which is not a
# security intake: these are quality findings about output, and three of the
# four vendors put them outside their bounty programmes
# (``consumer_ci.md`` section 9.5.5.10). An engine whose intake is unknown
# carries the empty string and the sheet says so, because an omitted row reads
# as an engine with no findings.
_INTAKE: Final[dict[str, str]] = {
    "claude": (
        "Anthropic support, or modelbugbounty@anthropic.com for model "
        "behaviour. Out of scope for the HackerOne programme"
    ),
    "openai": (
        "OpenAI help centre, model behaviour feedback (help.openai.com). Out "
        "of scope for its bounty programmes"
    ),
    "grok": "safety@x.ai, which xAI names for model output issues. Out of scope for HackerOne",
    "gemini": "",
}

_SHEET_MARK: Final[str] = (
    "<!-- Generated by tools/ticket_report.py. Regenerating replaces this file. -->"
)


def intake(engine: str) -> str:
    """Return where this engine's vendor takes a report, or an empty string.

    Args:
        engine (str): The engine.

    Returns:
        str: The intake, empty where none is recorded and empty for an engine
        the registry does not name at all. :func:`intake_engines` separates
        those two, which the sheet cannot.
    """
    return _INTAKE.get(engine, "")


def intake_engines() -> frozenset[str]:
    """Return every engine the intake registry names.

    **Published so a case can compare it with the roster**, which an empty
    intake cannot be read as: gemini carries one deliberately and an engine
    nobody entered carries the same value (``consumer_ci.md`` section
    9.5.5.10).

    Returns:
        frozenset[str]: The engines named, whether or not their intake is known.
    """
    return frozenset(_INTAKE)


def case_layer(case: str) -> str:
    """Return the layer a case identifier names, which the group key needs.

    **The code alone is not a cause where the code is a symptom.**
    ``QC_LLM_INCONSISTENT`` says only that the answers disagreed, so an
    evaluator finding and a security finding carrying it are two defects
    (``consumer_ci.md`` section 9.5.5.10).

    Args:
        case (str): The case identifier.

    Returns:
        str: The layer token, such as ``EVAL`` or ``SEC``, or ``an unknown
        layer`` where the identifier is not one.
    """
    matched = _CASE.match(case)
    parts = case.split("_")
    if matched is None or len(parts) < 3:
        return "an unknown layer"
    return parts[2]


def filing_sheet(today: str, filed: dict[str, list[dict[str, Any]]]) -> str:
    """Return the index a person files the findings from.

    **An index and not a third copy of the evidence.** Each finding's ticket
    carries the prompt, every response and the rule; this says how many there
    are, where each vendor takes one, and which findings are one cause
    (``consumer_ci.md`` section 9.5.5.10).

    Args:
        today (str): The date to head the sheet with, ISO.
        filed (dict): Each engine's fileable findings, in register order.

    Returns:
        str: The sheet, as Markdown.
    """
    total = sum(len(entries) for entries in filed.values())
    counted = ", ".join(
        f"{engine} {len(filed.get(engine, []))}" for engine in sorted(filed)
    )
    lines = [
        _SHEET_MARK,
        "",
        f"# Filing sheet, {today}",
        "",
        f"**{total} finding(s) to file**, each reproduced on the latest replay: "
        f"{counted}.",
        "",
        "Each group below is one defect, so it is **one report**: a code "
        "observed on several cases of one engine is that engine's defect seen "
        "several ways. The file named under each finding carries the whole "
        "evidence, the request as sent, every recorded response unchanged, "
        "what a correct answer is, and a replay command needing no credential.",
        "",
        "**Not filed:** anything withdrawn as this instrument's own defect, and "
        "anything that stopped reproducing. Both wait in "
        "`config/findings/unconfirmed/<engine>.yaml` with the reason, and a "
        "dependent of a failed foundation is absent because its case skipped "
        "rather than failed.",
    ]
    for engine in sorted(filed):
        lines.extend(_engine_section(engine, filed[engine]))
    return "\n".join(lines) + "\n"


def _engine_section(engine: str, entries: list[dict[str, Any]]) -> list[str]:
    """Return one engine's section of the sheet: its intake and its reports.

    Args:
        engine (str): The engine.
        entries (list): Its fileable findings, in register order.

    Returns:
        list[str]: The lines, beginning with a blank one. **An engine with no
        finding keeps its heading**, an omitted section reading as an engine
        nobody measured.
    """
    where = intake(engine)
    lines = [
        "",
        f"## {engine}",
        "",
        f"**Where:** {where}." if where else
        "**Where:** not recorded. Confirm this vendor's intake for model "
        "behaviour before filing.",
        "",
    ]
    if not entries:
        return lines + ["No finding reproduces on the latest run."]

    grouped: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for entry in entries:
        grouped.setdefault(
            (str(entry.get("taxonomy_code", "")), case_layer(str(entry.get("case", "")))),
            [],
        ).append(entry)
    lines.append(f"{len(entries)} finding(s) in {len(grouped)} report(s).")
    for (code, layer), group in sorted(grouped.items()):
        lines.extend([
            "", f"### {code} in {layer}, {len(group)} finding(s), one report", "",
        ])
        lines.extend(_finding_line(engine, entry) for entry in group)
    return lines


def _finding_line(engine: str, entry: dict[str, Any]) -> str:
    """Return one finding's line: its case, its population and its evidence.

    Args:
        engine (str): The engine, for the evidence path.
        entry (dict): The register entry.

    Returns:
        str: The Markdown list item.
    """
    case = str(entry.get("case", ""))
    population = str(entry.get("observations") or "").strip()
    measured = f", {population}" if population else ", every observation"
    return (
        f"- `{case}`{measured}, model `{entry.get('observed_model', '')}`. "
        f"Evidence: `{engine}/{ticket_name(case)}`"
    )
