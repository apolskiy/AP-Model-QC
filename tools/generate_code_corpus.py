def build() -> str:
    """Return the task file's contents.

    **Separate from writing**, so ``115008`` can compare the shipped file to the
    same code path an author runs. A check that rebuilt the expected output
    separately would assert that two copies of one algorithm agree, which is
    not the claim being made.

    Returns:
        str: The complete file, ending in a newline.
    """
    parts = [_HEADER]
    for (comment, stem, prompt, constraint_id, constraint_text, kind,
         document_id, title, content, tags) in _tasks():
        parts.append(
            f"\n{comment}\n"
            f"- task_id: MQC_TASK_{stem}\n"
            f"  rubric_ids: ["
            + ", ".join(
                (f"MQC_RULE_{stem}",) + _ADDITIONAL_RULES.get(stem, ())
            )
            + "]\n"
            f"  user_prompt: |\n{prompt}\n"
            f"  constraints:\n"
            f"    - constraint_id: {constraint_id}\n"
            f"      text: {constraint_text}\n"
            f"      kind: {kind}\n"
            f"  context_documents:\n"
            f"    - document_id: {document_id}\n"
            f"      title: {title}\n"
            f"      content: |\n{content}\n"
            f"  tags: {tags}\n"
        )
    return "".join(parts)


def main() -> None:
    """Write the task file.

    Returns:
        None
    """
    _TARGET.write_text(build(), encoding="utf-8", newline="\n")
    print(f"{_TARGET.relative_to(_ROOT).as_posix()}: {len(_tasks())} tasks")


if __name__ == "__main__":
    main()
