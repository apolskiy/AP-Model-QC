"""Generate the code comprehension task file from the guarded excerpts.

Specified by ``docs/testing/model_evaluation_test_plan.md`` section 8.11.

**The excerpts are read, never retyped.** ``tests/fixtures/excerpts/`` holds
them and ``MQC_CAS_UNI_115100`` through ``115102`` guard them by parsing and
executing them. ``ContextDocument`` carries inline content and has no file
reference, so a task supplying an excerpt holds a second copy: generating that
copy from the fixture is what makes the two identical to begin with, and
``115005`` is what keeps them identical afterwards.

**This is the only way the task file is written.** ``115008`` compares the
shipped file to :func:`build` byte for byte, so a hand edit to it is reported
rather than silently lost at the next regeneration.

**Only the task file is generated.** The rule file beside it is hand-authored
and carries exemplars, reasoning and assertions that no generator produces, so
regeneration cannot clobber them.
"""

from pathlib import Path
from typing import Final

