_HEADER: Final[str] = '''# SPDX-FileCopyrightText: 2026 Aleksandr Polskiy
# SPDX-License-Identifier: MIT
# What the model is sent for the code comprehension family.
#
# GENERATED BY tools/generate_code_corpus.py. Do not edit this file by hand:
# MQC_CAS_UNI_115008 compares it to what the generator builds, and an edit here
# would be reported and then lost at the next regeneration.
#
# Specified by model_evaluation_test_plan.md sections 9.9 and 8.11.
#
# THE EXCERPTS ARE INLINED COPIES OF GUARDED FIXTURES. ContextDocument carries
# inline content and has no file reference, so these are a second copy of text
# that tests/fixtures/excerpts/ holds and 10401 to 10403 guard by parsing and
# executing it. Generating them from the fixtures makes the copies identical;
# MQC_CAS_UNI_115005 keeps them identical.
#
# MOST OF THIS FAMILY BRINGS NO REQUIREMENTS OF ITS OWN. Cases 30029 to 30037
# formulate GND_001, GND_002 and GND_004 in the code domain: a grounding
# requirement is domain-independent, and the point of a second formulation is
# that the behaviour survives a change of domain.
#
# CASES 30038 TO 30040 ARE THE EXCEPTION, added 2026-09-26 under MDL_DEF. They
# are not grounding: stating a source correctly and diagnosing why the source is
# wrong are different questions, and the settlement excerpt showed it. Its three
# asserted outcomes all follow from ONE cause, so a model listing them scored as
# though it had found the cause.
'''


def excerpt(name: str) -> str:
    """Return a guarded fixture indented for a YAML block scalar.

    Args:
        name (str): The fixture stem under ``tests/fixtures/excerpts``.

    Returns:
        str: The indented content. Blank lines are left empty rather than
        indented, so the file carries no trailing whitespace.
    """
    text = (_EXCERPTS / f"{name}.py.txt").read_text(encoding="utf-8")
    return "\n".join(
        _INDENT + line if line.strip() else "" for line in text.rstrip("\n").splitlines()
    )


