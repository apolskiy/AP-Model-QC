from decimal import Decimal
from pathlib import Path

import pytest

from cmn.case_steps import step
from cmn.grouping import story

from tests.cases.live_band_support import write_band_report
from tools.spend_remaining import main, remaining

pytestmark = pytest.mark.unit

_CEILING = "7.00"
_EXHAUSTED = "QC_HARNESS_BUDGET_EXHAUSTED"
_UNMET = "QC_HARNESS_DEPENDENCY_UNMET"


class TestMQCSpendRemaining:
    """A live band spends what the earlier live bands left of one ceiling."""

    @story("One ceiling for the whole ladder")
    def MQC_CAS_UNI_115841_the_remainder_is_the_ceiling_less_every_earlier_band(
        self, tmp_path: Path,
    ) -> None:
        """Two earlier bands at $1.2345 and $2.0000 leave $3.76 of $7.00, rounded down.

        Design: ``consumer_ci.md`` section 7.8.4.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        reports = tmp_path / "spent"
        write_band_report(reports, "judge_p0", "1.2345")
        write_band_report(reports, "judge_p1", "2.0000")
        output = tmp_path / "output.txt"

        step(1, "leave the whole ceiling to the first live band, which has no reports")
        assert remaining(Decimal(_CEILING), tmp_path / "absent", 0) == Decimal("7.00")

        step(2, "subtract every earlier band's total and round down to the cent")
        assert remaining(Decimal(_CEILING), reports, 2) == Decimal("3.76")

        step(3, "exit 0 and write the remainder for the band step to read")
        assert main(["--ceiling", _CEILING, "--reports", str(reports), "--earlier", "2",
                     "--output", str(output)]) == 0 and \
            output.read_text(encoding="utf-8") == "remaining=3.76\n", output.read_text(
                encoding="utf-8")

    @story("One ceiling for the whole ladder")
    def MQC_CAS_UNI_115842_an_exhausted_ceiling_refuses_the_band(self, tmp_path: Path) -> None:
        """A remainder of exactly zero refuses, as one below zero does.

        Design: ``consumer_ci.md`` section 7.8.4.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        exact = tmp_path / "exact"
        write_band_report(exact, "judge_p0", "3.5000")
        write_band_report(exact, "judge_p1", "3.5000")
        over = tmp_path / "over"
        write_band_report(over, "judge_p0", "7.0100")
        output = tmp_path / "output.txt"

        step(1, "refuse a remainder of exactly zero with the budget code")
        with pytest.raises(ValueError, match=_EXHAUSTED):
            remaining(Decimal(_CEILING), exact, 2)

        step(2, "refuse a remainder below zero with the budget code")
        with pytest.raises(ValueError, match=_EXHAUSTED):
            remaining(Decimal(_CEILING), over, 1)

        step(3, "exit 4 and write no remainder")
        assert main(["--ceiling", _CEILING, "--reports", str(exact), "--earlier", "2",
                     "--output", str(output)]) == 4 and not output.exists()

    @story("One ceiling for the whole ladder")
    def MQC_CAS_UNI_115843_a_spend_that_cannot_be_read_refuses_the_band(
        self, tmp_path: Path,
    ) -> None:
        """An unpriced total, an absent total and a missing report each refuse.

        Design: ``consumer_ci.md`` section 7.8.4.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        unpriced = tmp_path / "unpriced"
        write_band_report(unpriced, "judge_p0", "unpriced")
        unpublished = tmp_path / "unpublished"
        write_band_report(unpublished, "judge_p0", None)
        short = tmp_path / "short"
        write_band_report(short, "judge_p0", "0.5000")
        output = tmp_path / "output.txt"

        step(1, "refuse an earlier band whose total is unpriced")
        with pytest.raises(ValueError, match=_UNMET):
            remaining(Decimal(_CEILING), unpriced, 1)

        step(2, "refuse an earlier band that published no total")
        with pytest.raises(ValueError, match=_UNMET):
            remaining(Decimal(_CEILING), unpublished, 1)

        step(3, "refuse when fewer reports arrived than live bands ran before")
        with pytest.raises(ValueError, match=_UNMET):
            remaining(Decimal(_CEILING), short, 2)

        step(4, "exit 4 and write no remainder")
        assert main(["--ceiling", _CEILING, "--reports", str(short), "--earlier", "2",
                     "--output", str(output)]) == 4 and not output.exists()
