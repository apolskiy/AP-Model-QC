import json
from pathlib import Path

import pytest

from cmn.case_steps import step
from cmn.grouping import story

from tools.findings_run import models_by_case, results_directory

pytestmark = pytest.mark.unit

_CASE: str = "MQC_EVL_EVAL_134206_rounding_within_the_stated_ceiling_is_performed"


class TestMQCFindingsRunReadsItsOwnRun:
    """The served model a finding records comes from the run that recorded it."""

    @story("The served model")
    def MQC_CAS_UNI_115812_a_findings_run_reads_no_result_an_earlier_run_left(
        self, tmp_path: Path
    ) -> None:
        """A result left in the results directory by an earlier run is gone before the next.

        Design: ``consumer_ci.md`` section 9.3.1.

        Args:
            tmp_path (Path): The scratch directory a findings run would use.

        Returns:
            None
        """
        step(1, "leave a result an earlier run on gemini-3.8-flash published")
        stale = tmp_path / "allure"
        stale.mkdir()
        (stale / "earlier-result.json").write_text(
            json.dumps({
                "name": _CASE,
                "parameters": [{"name": "resolved_model", "value": "'gemini-3.8-flash'"}],
            }),
            encoding="utf-8",
        )
        assert models_by_case(stale) == {_CASE: "gemini-3.8-flash"}, (
            "the planted result was not read, so this case proves nothing"
        )

        step(2, "prepare the directory for the next run and read what it holds")
        results = results_directory(tmp_path)
        assert results.is_dir(), "the results directory was not created"
        assert not list(results.iterdir()), (
            "a result an earlier run published was still in the directory, so the "
            "next run would record the model that earlier run was served"
        )
        assert not models_by_case(results), "an emptied directory still names a model"
