"""Unit preconditions for whether a regression run says which judge graded it.

Created: 2026-10-21
Last updated: 2026-11-15

This file contains one case over the regression run and its callers: every
``live -> live`` band names the judge on its invocation and in its job name
and reads that judge's calibration record, no band selects calibration, and
each engine has one claude-judged caller passing it under a cadence that is
not the debug one.

**A second judge exists because gemini scored its own engine unchecked**, so
each engine and judge pair is a separate run and the names are what tell two
runs apart.

**A failure here is not a model finding.** The module carries no priority
marker, per the harness ``framework-rules.md`` section 3.3.

Specified by ``docs/design/consumer_ci.md`` sections 7.4.5, 7.7, 7.7.4 and
7.9.5. ``MQC_CAS_UNI_115777``, ``115844`` and ``115850`` are retired.
"""

