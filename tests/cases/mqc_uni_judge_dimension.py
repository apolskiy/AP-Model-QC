import pytest

from tests.cases.workflow_support import (
    WORKFLOWS as _WORKFLOWS,
    jobs as _jobs,
    load as _load,
    run_lines as _run_lines,
    repository_root as _repository_root,
    selects_a_graded_marker as _selects_a_graded_marker,
)

pytestmark = pytest.mark.unit

# THE LADDER ITSELF, which one caller per engine and judge pair invokes.
_LIVE = "evaluate-engine.yml"

# THE JUDGE DIMENSION. Rungs 2 and 3 name the judge and rung 1 does not, and a
# caller exists per engine and judge pair. Design `consumer_ci.md` section 7.7.
_JUDGE_INPUT = "judge"
_JUDGE_FLAG = "--judge-engine"

# THE EXPRESSION A NAME RESOLVES, rather than the word "judge", which rung 2
# carries whatever grades it.
_JUDGE_REFERENCE = "inputs.judge"

# THE DEBUG CADENCE, which is what makes a run uncounted. A claude-judged run is
# started by hand and is counted, so it never carries this. Section 7.7.4.
_ON_DEMAND = "-on-demand"

# THE ENGINES BOTH JUDGES SCORE, read from the roster rather than listed.
_ROSTERED_ENGINES = frozenset({"claude", "gemini", "grok", "openai"})

class TestMQCJudgeDimension:
    """A graded run names the judge that produced its scores."""

    def MQC_CAS_UNI_115777_a_rung_that_grades_without_naming_its_judge_is_reported(
        self,
    ) -> None:
        """Rungs 2 and 3 name the judge, rung 1 does not, and a caller exists per pair.

        **A second judge was added because gemini scored its own engine
        unchecked**, so each engine and judge pair is a separate run and the
        names carry the judge. A rung that grades without naming one takes the
        configured default, which makes two runs of this workflow
        indistinguishable in their results.

        **Rung 1 has no judge dimension**, at the project owner's reading: it
        replays both halves, so it measures our code, and the code reading a
        stored judgement does not vary with the engine that produced it.
        Naming a judge there would spend runner time re-establishing a
        property already established.

        **And a claude-judged caller is never a debug workflow.** The cadence
        in the filename is what `run_context` reads, and `on-demand` yields no
        verdict; these runs are started by hand and counted.

        Design: ``consumer_ci.md`` sections 7.7, 7.7.1 and 7.7.4.

        Returns:
            None
        """
        ladder = _load(_LIVE)
        jobs = _jobs(ladder)

        # 1. THE JUDGE IS AN INPUT, so a caller chooses it rather than editing.
        declared = (ladder.get(True) or ladder.get("on") or {})
        inputs = ((declared.get("workflow_call") or {}).get("inputs") or {})
        assert _JUDGE_INPUT in inputs, (
            f"the ladder declares no {_JUDGE_INPUT!r} input, so every run "
            f"grades with the configured default: {sorted(inputs)}"
        )

        # 2. THE GRADING RUNGS NAME IT AND RUNG 1 DOES NOT.
        for rung, grades in (("deterministic", False), ("judge", True),
                             ("model", True)):
            lines = _run_lines(jobs[rung], _repository_root())
            named = [line for line in lines if _JUDGE_FLAG in line]
            graded = [line for line in lines if _selects_a_graded_marker(line)]
            assert graded, f"rung {rung!r} makes no graded invocation to check"
            if grades:
                assert len(named) == len(graded), (
                    f"rung {rung!r} makes {len(graded)} graded invocation(s) "
                    f"and names {_JUDGE_FLAG} on {len(named)}, so a run of "
                    f"this ladder would grade with a judge nobody chose"
                )
            else:
                assert not named, (
                    f"rung {rung!r} names {_JUDGE_FLAG}, and it replays both "
                    f"halves: a second judge there re-establishes what the "
                    f"first already did (section 7.7.1)"
                )

        # 3. AND THE RUNG NAMES CARRY THE JUDGE, so two runs are told apart.
        # THE INTERPOLATION, NOT THE WORD. Rung 2 is called "the judge"
        # whatever grades it, so asserting the word "judge" appears in the
        # name passed with no judge in it: an injection removing the
        # interpolation went NOT CAUGHT on the first pass.
        for rung in ("judge", "model"):
            shown = str(jobs[rung].get("name", ""))
            assert _JUDGE_REFERENCE in shown, (
                f"rung {rung!r} is named {shown!r}, which does not resolve "
                f"the judge, so two runs of this ladder share a name"
            )

        # 4. ONE CLAUDE-JUDGED CALLER PER ENGINE, AND NONE OF THEM A DEBUG
        # WORKFLOW. The cadence is what decides whether the run counts.
        for engine in sorted(_ROSTERED_ENGINES):
            matches = sorted(
                _WORKFLOWS.glob(f"evaluate-{engine}-by-claude-*.yml")
            )
            assert len(matches) == 1, (
                f"{engine} has {len(matches)} claude-judged caller(s), and "
                f"both judges score every engine: {[found.name for found in matches]}"
            )
            caller = matches[0]
            assert not caller.stem.endswith(_ON_DEMAND), (
                f"{caller.name} carries the debug cadence, so its rows yield "
                f"no verdict; a run started by hand is still counted "
                f"(section 7.7.4)"
            )
            passed = [
                job.get("with", {}).get(_JUDGE_INPUT)
                for job in _jobs(_load(caller.name)).values()
            ]
            assert passed == ["claude"], (
                f"{caller.name} passes {_JUDGE_INPUT} as {passed}, so it would "
                f"grade with the default rather than with claude"
            )
