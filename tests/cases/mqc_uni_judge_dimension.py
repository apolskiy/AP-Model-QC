import pytest

from cmn.case_steps import step
from cmn.grouping import story

from tests.cases.live_band_support import (
    LIVE_BANDS,
    RECORD_PATH,
    REGRESSION_RUN,
    band_invocation,
    call_inputs,
    claude_judged_callers,
    flag_value,
    steps_running,
)
from tests.cases.workflow_support import jobs, load, repository_root

pytestmark = pytest.mark.unit

# THE JUDGE AS A BAND PASSES IT, and as a band job's name resolves it. The
# expression rather than the word "judge", which a job's own name might carry
# whatever grades it. Section 7.7.
_JUDGE_REFERENCE = "${{ inputs.judge }}"
_JUDGED_BY = f"judged by {_JUDGE_REFERENCE}"

# THE DEBUG CADENCE, which is what makes a run uncounted. A claude-judged run is
# started by hand and is counted, so it never carries this. Section 7.7.4.
_ON_DEMAND = "-on-demand"

# THE ENGINES BOTH JUDGES SCORE.
_ROSTERED_ENGINES = ("claude", "gemini", "grok", "openai")

# THE MARKER EXPRESSION EVERY BAND SELECTS, which names no calibration.
_BAND_MARKERS = "evaluator or tool or sec"


class TestMQCJudgeDimension:
    """A regression run names the judge that produced its scores, and reads its record."""

    @story("The regression run is the live runs")
    def MQC_CAS_UNI_115858_a_live_band_not_naming_its_judge_is_reported(self) -> None:
        """Every live band names its judge and reads its record; a caller per engine.

        **A claude-judged caller is never a debug workflow**, because the
        cadence in the filename is what ``run_context`` reads and
        ``on-demand`` yields no verdict.

        Design: ``consumer_ci.md`` sections 7.4.5, 7.7, 7.7.4 and 7.9.5.

        Returns:
            None
        """
        root = repository_root()
        regression = load(REGRESSION_RUN)
        defined = jobs(regression)
        unnamed: list[str] = []
        unread: list[str] = []
        unfetched: list[str] = []
        selecting: list[str] = []
        for name in LIVE_BANDS:
            job = defined.get(name, {})
            line = band_invocation(job, root)
            passed = flag_value(line, "--judge-engine")
            shown = str(job.get("name", ""))
            if passed != _JUDGE_REFERENCE or _JUDGED_BY not in shown:
                unnamed.append(f"{name}: passes {passed!r}, named {shown!r}")
            record = flag_value(line, "--calibration-record")
            if not record:
                unread.append(f"{name}: {line.strip()}")
            elif not [entry for entry in steps_running(job, f"FETCH_HEAD:{RECORD_PATH}")
                      if record in str(entry.get("run"))]:
                unfetched.append(f"{name} reads {record} and takes no record into it")
            if flag_value(line, "-m") != _BAND_MARKERS:
                selecting.append(f"{name}: {flag_value(line, '-m')!r}")
        callers = claude_judged_callers(_ROSTERED_ENGINES, _ON_DEMAND)

        step(1, "find the judge declared as a regression run input")
        assert "judge" in call_inputs(regression), sorted(call_inputs(regression))

        step(2, "find the judge named on every live band's invocation and job name")
        assert not unnamed, unnamed

        step(3, "find every live band naming a calibration record")
        assert not unread, unread

        step(4, "find each record taken from the default branch for the run's judge")
        assert not unfetched, unfetched

        step(5, f"find every live band selecting {_BAND_MARKERS!r} and no calibration")
        assert not selecting, selecting

        step(6, "find one counted claude-judged caller per engine")
        assert callers == {engine: ["claude"] for engine in _ROSTERED_ENGINES}, callers
