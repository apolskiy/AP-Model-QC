from types import SimpleNamespace

import pytest

from cmn.case_steps import step

from tests.cases.consistency_support import (
    assert_consistent_pass, measured, unmeasured_code,
)
from tests.cases.graded_support import judge_binding
from tests.cases.instrument_support import SimulatedGradedConfig

pytestmark = pytest.mark.unit


class TestMQCWithheldJudge:
    """With the judge off, nothing is judged and an unjudged case never passes."""

    def MQC_CAS_UNI_115772_a_withheld_judge_leaves_a_graded_case_unpassed(self) -> None:
        """The binding withholds the judge, and unjudged observations skip rather than pass.

        Design: ``consumer_ci.md`` section 6.4.2.

        Returns:
            None
        """
        step(1, "bind the judge with --judge-mode off")
        binding = judge_binding(SimulatedGradedConfig("", judge_mode="off"), "claude")
        assert binding.withheld and not binding.available, (
            "the judge was bound although the run withheld it"
        )

        step(2, "read the measured population of unjudged observations")
        unjudged = [
            SimpleNamespace(judge_skipped_reason="unjudged", passed=False,
                            taxonomy_codes=("QC_HARNESS_JUDGE_WITHHELD",))
            for _ in range(3)
        ]
        assert not measured(unjudged) and (
            unmeasured_code(unjudged) == "QC_HARNESS_JUDGE_WITHHELD"
        ), "an unjudged observation was counted as measured, or named another code"

        step(3, "conclude a case every observation of which was unjudged")
        with pytest.raises(pytest.skip.Exception, match="QC_HARNESS_JUDGE_WITHHELD"):
            assert_consistent_pass(unjudged)
