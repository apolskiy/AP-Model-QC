"""Unit precondition for a graded case run with the judge withheld, ``--judge-mode off``.

Created: 2026-10-21
Last updated: 2026-10-21

Its case checks ``tests.cases.graded_support.judge_binding`` and the consistency
readers in ``tests.cases.consistency_support``: with the judge off the binding
is withheld and reaches no judge, an unjudged observation leaves the measured
population and names ``QC_HARNESS_JUDGE_WITHHELD``, and a case every one of
whose observations was unjudged skips rather than passes.

A debug run uses this to check a case's screen and assertions before its judge
is involved, so a failure here would let an unjudged case read as a pass. It
runs in the ``unit`` gate ahead of every graded band, and a failure is an
instrument defect, not a model finding.

Specified by ``docs/design/consumer_ci.md`` section 6.4.2 and harness
``tier3_evaluation.md`` section 5A.5.3.
"""

