"""Unit preconditions for a replay case whose recording or judgement is missing.

Created: 2026-11-17
Last updated: 2026-11-17

This file contains ``TestMQCPartialRecording``, three cases on
``tests.cases.graded_support`` and ``conftest.py``. A case missing the
judgement of any observation skips whole once its observations and any
escalation have run, naming the judgement, whatever the others measured; a case
missing a recording skips at that dispatch, naming the recording; and the
conftest labels such a skip and makes the run exit 3.

A partially recorded case otherwise reports a finding on evidence that tests
nothing. A failure here is an instrument defect, not a model finding.

Specified by ``docs/design/consumer_ci.md`` section 9.4.5 and harness
``harness_test_taxonomy.md`` section 5.1.3.1.
"""

