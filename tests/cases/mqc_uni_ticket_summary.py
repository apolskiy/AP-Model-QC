import pytest

from cmn.case_steps import step
from cmn.grouping import story

from tools.ticket_files import filing_sheet
from tools.ticket_summary import judge_split, summary_lines

pytestmark = pytest.mark.unit

_PROMPT = "State EMEA revenue.\nRound it up within 5 percent."
_WARNED = ("A_X (QC_LLM_MATCH_MISCOMPUTED): asserted in 'rounding would exceed the "
           "limit.', corrected after it in 'it is actually below the limit'")


class TestMQCTicketSummary:
    """A ticket opens by quoting what a reader needs before the evidence."""

    @story("A ticket opens with a summary")
    def MQC_CAS_UNI_115827_a_warning_summary_quotes_the_prompt_and_corrections(
        self,
    ) -> None:
        """A warning lists only the responses that carried it, by their own words.

        Three responses, the first and third corrected and the second clean.

        Design: ``consumer_ci.md`` section 9.5.5.14.

        Returns:
            None
        """
        text = "\n".join(summary_lines(
            _PROMPT, ["first wrong then right", "clean answer", "third wrong then right"],
            [(0, True, _WARNED), (1, True, ""), (2, True, _WARNED)],
            [(True, 4.0, "capped"), (True, 5.0, "clean"), (True, 4.0, "capped")], warned=True))

        step(1, "read the prompt whole on one line, and two of three responses incorrect")
        assert ('*Prompt:* "State EMEA revenue. Round it up within 5 percent."' in text
                and "*Incorrect, 2 of 3:*" in text), text

        step(2, "read each corrected response by what it stated and what corrected it")
        assert ('- Response 1 of 3: stated "rounding would exceed the limit." '
                'Corrected later: "it is actually below the limit"') in text, text

        step(3, "read the warned responses listed and the clean one left out")
        assert "Response 3 of 3" in text and "Response 2 of 3" not in text, (
            f"a warning's summary listed a clean response or dropped a warned one: {text}")

        step(4, "read that no judgement disagrees with its checks")
        assert "*Judgements:* none disagree with the outcome." in text, text

    @story("A ticket opens with a summary")
    def MQC_CAS_UNI_115828_a_failure_summary_lists_all_and_a_disagreeing_judge(
        self,
    ) -> None:
        """A failed case lists every response, and a judge passing a failed check is quoted.

        A failed check the judge passed, a judged failure, and a pass.

        Design: ``consumer_ci.md`` section 9.5.5.14.

        Returns:
            None
        """
        text = "\n".join(summary_lines(
            _PROMPT, ["answer one", "answer two", "answer three"],
            [(0, False, "A_Y (QC_LLM_INSTRUCTION_DRIFT): required substring absent"),
             (1, True, ""), (2, True, "")],
            [(True, 5.0, "looks right"), (False, 2.0, "no comparison"), (True, 5.0, "fine")],
            warned=False))

        step(1, "read the failed check quoted with the response's opening")
        assert ('- Response 1 of 3: failed its checks: A_Y (QC_LLM_INSTRUCTION_DRIFT): '
                'required substring absent. Opens: "answer one"') in text, text

        step(2, "read the judged failure with its score and rationale")
        assert '- Response 2 of 3: the judge failed it, scoring 2. no comparison' in text, text

        step(3, "read the passing response listed too, the case having failed")
        assert ('*Incorrect, 2 of 3:*' in text
                and '- Response 3 of 3: passed. Opens: "answer three"' in text), text

        step(4, "read the judge that passed a response its checks failed")
        assert ("*Judgements disagreeing with the outcome:*" in text
                and "- Response 1: its checks failed and the judge passed it, scoring 5. "
                    "looks right" in text), text

    @story("A ticket opens with a summary")
    def MQC_CAS_UNI_115829_identical_responses_judged_apart_are_flagged(self) -> None:
        """Identical text on both sides of the threshold is the judge's doing, and is flagged.

        Design: ``consumer_ci.md`` section 9.5.5.14.

        Returns:
            None
        """
        judged = [(True, 4.0, "ok"), (True, 4.0, "ok"), (False, 2.0, "not ok")]
        split = judge_split(["same  answer", "other answer", "same answer\n"], judged)

        step(1, "flag responses 1 and 3, the same text up to whitespace, judged apart")
        assert split.startswith("responses 1 and 3 have the same text"), split

        step(2, "flag nothing where identical responses were judged alike")
        assert not judge_split(["same", "same"], [(True, 4.0, ""), (True, 5.0, "")])

        step(3, "carry the flag onto the ticket summary")
        text = "\n".join(summary_lines(_PROMPT, ["same", "same"], [(0, True, ""), (1, True, "")],
                                       [(True, 4.0, ""), (False, 2.0, "")], warned=False))
        assert "**Identical responses judged differently:** responses 1 and 2" in text, text

        step(4, "carry the flag onto the filing sheet")
        sheet = filing_sheet("2026-11-09", {"gemini": [{
            "case": "MQC_EVL_EVAL_134206_x", "observations": "1 of 2 passed",
            "observed_model": "gemini-4-argon", "judge_split": split}]})
        assert f"**Identical responses judged differently:** {split}" in sheet, sheet
