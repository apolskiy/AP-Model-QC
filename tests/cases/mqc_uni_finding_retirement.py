from datetime import date
from pathlib import Path

import pytest

from cmn.case_steps import step
from cmn.grouping import story

from tests.cases.retirement_support import (
    MIXED_REPORT,
    PASSED_CASE,
    SKIPPED_CASE,
    open_on_both,
)
from tools.findings import (
    RunContext,
    hold_unreproduced,
    parse_passed,
    resolve_upstream,
)

pytestmark = pytest.mark.unit


class TestMQCRetirementNeedsAPass:
    """A finding leaves the bug file only when its case was measured passing."""

    @story("A skip is not a pass")
    def MQC_CAS_UNI_115750_a_finding_whose_case_skipped_is_not_held(self, tmp_path: Path) -> None:
        """A skipped case keeps its finding; only a passing one is held.

        Design: ``consumer_ci.md`` section 9.4.7.1.

        Args:
            tmp_path (Path): Where the constructed report is written.

        Returns:
            None
        """
        report = tmp_path / "junit.xml"
        report.write_text(MIXED_REPORT, encoding="utf-8")
        passed = parse_passed(report)
        assert passed == frozenset({PASSED_CASE}), passed

        run = RunContext(
            engine="openai", mode="replay", models={}, expected={},
            today=date(2026, 10, 15), resolve=False, hold_unreproduced=True, passed=passed,
        )
        register = open_on_both()
        hold_unreproduced(register, {}, run)

        assert register[PASSED_CASE]["status"] == "not_reproduced"
        assert register[SKIPPED_CASE]["status"] == "open", (
            "a finding whose case was skipped, and so never measured, was held as "
            "no longer reproducing"
        )

    @story("Resolution credits a vendor only for what a run measured")
    def MQC_CAS_UNI_115793_a_finding_whose_case_skipped_is_not_resolved_upstream(
        self, tmp_path: Path
    ) -> None:
        """A skipped case keeps its finding; only a passing one is resolved upstream.

        **This is `115750`'s rule on the path that does the crediting.** A case
        absent from a run's failures was not necessarily measured: it may have
        skipped behind a failed foundation. Resolving it names a vendor fix on a
        run that measured nothing, which section 9.4.1 calls the error that most
        damages a published report.

        Design: ``consumer_ci.md`` section 9.4.9.

        Args:
            tmp_path (Path): Where the constructed report is written.

        Returns:
            None
        """
        report = tmp_path / "junit.xml"
        report.write_text(MIXED_REPORT, encoding="utf-8")
        run = RunContext(
            engine="openai", mode="live", models={"any": "gpt-test"}, expected={},
            today=date(2026, 10, 29), resolve=True, passed=parse_passed(report),
        )
        register = open_on_both()

        step(1, "resolve against a live run that measured one case and skipped the other")
        resolve_upstream(register, {}, run)
        assert register[PASSED_CASE]["status"] == "resolved_upstream", (
            "a finding whose case a live run measured as passing was not resolved"
        )

        step(2, "read the status of the case the run skipped")
        assert register[SKIPPED_CASE]["status"] == "open", (
            "a finding whose case was skipped, and so never measured, was credited "
            "to the vendor as a fix"
        )

    @story("A withdrawal is not reversed by a later run")
    def MQC_CAS_UNI_115794_a_withdrawn_finding_is_not_resolved_upstream(self) -> None:
        """A finding retracted as ours is never rewritten as the vendor's fix.

        A withdrawal is a conclusion this project reached about its own record,
        so resolving it claims a vendor corrected something we had already said
        was never theirs. A **held** finding stays resolvable: it is an absence
        of a measurement rather than a conclusion, and a live run measuring the
        case as passing is the evidence it was waiting for.

        Design: ``consumer_ci.md`` section 9.4.9.

        Returns:
            None
        """
        withdrawn = "MQC_EVL_EVAL_134109_diagnoses_the_cause_and_not_only_the_outcome"
        held = "MQC_EVL_EVAL_134110_reports_the_figure_it_measured"
        register = {
            withdrawn: {
                "case": withdrawn, "status": "withdrawn",
                "withdrawn_reason": "The assertion read a synonym list, not a figure.",
            },
            held: {
                "case": held, "status": "not_reproduced",
                "held_on": "2026-10-15", "held_reason": "Did not reproduce on a fresh run.",
            },
        }
        run = RunContext(
            engine="openai", mode="live", models={"any": "gpt-test"}, expected={},
            today=date(2026, 10, 29), resolve=True,
            passed=frozenset({withdrawn, held}),
        )

        step(1, "resolve against a live run that measured both as passing")
        resolve_upstream(register, {}, run)
        assert register[withdrawn]["status"] == "withdrawn", (
            "a finding withdrawn as ours was rewritten as the vendor's fix"
        )

        step(2, "read whether the withdrawal kept the reason it was withdrawn for")
        assert register[withdrawn]["withdrawn_reason"], "the withdrawal lost its reason"

        step(3, "read whether the held finding resolved on a live pass")
        assert register[held]["status"] == "resolved_upstream", (
            "a held finding a live run measured as passing was not resolved"
        )

        step(4, "read whether resolution kept how the finding came to be held")
        assert register[held]["held_reason"], "resolution dropped the hold's reason"

    @story("A held finding is held once")
    def MQC_CAS_UNI_115763_a_held_finding_keeps_its_date_and_reason_on_a_later_run(
        self,
    ) -> None:
        """Holding an entry already held changes nothing, so a written reason survives.

        Design: ``consumer_ci.md`` section 9.4.8.

        Returns:
            None
        """
        case = "MQC_EVL_EVAL_134109_diagnoses_the_cause_and_not_only_the_outcome"
        reason = "Did not reproduce after the case changed; written by hand."
        register = {
            case: {
                "case": case, "status": "not_reproduced", "observations": "1 of 5 passed",
                "held_on": "2026-10-15", "held_reason": reason,
            }
        }
        run = RunContext(
            engine="openai", mode="replay", models={}, expected={},
            today=date(2026, 10, 18), resolve=False, hold_unreproduced=True,
            passed=frozenset({case}),
        )
        step(1, "re-run the hold on an entry already held with a reason written by hand")
        lines = hold_unreproduced(register, {}, run)
        assert register[case]["held_reason"] == reason, (
            f"a later run wrote over the held reason: {register[case]['held_reason']!r}"
        )

        step(2, "read the date the entry was first held")
        assert register[case]["held_on"] == "2026-10-15", (
            f"a later run moved the date it was first held: {register[case]['held_on']!r}"
        )

        step(3, "read what the run reported about the entry")
        assert not lines, f"an entry already held was reported as newly held: {lines}"
