"""Unit preconditions for the ways a finding leaves the bug file.

Created: 2026-10-29
Last updated: 2026-10-29

This file contains four cases on retirement in ``tools/findings.py``: the two
paths that take a finding out of the bug file, and what each may read before it
does. ``TestMQCRetirementNeedsAPass`` checks that holding and resolving both
require the run to have measured the case as passing, that a hold already taken
keeps its date and reason, and that a withdrawal is never rewritten as a
vendor's fix.

**These run in the ``unit`` precondition gate.** Retirement decides what a
published report claims about a vendor, so these run before any graded case
produces a finding to retire. A failure is an instrument defect, **not a model
finding**: the run exits 3 and no graded case executes, and the module carries
no priority marker, per the harness ``framework-rules.md`` section 3.3.

Specified by ``docs/design/consumer_ci.md`` sections 9.4.7.1, 9.4.8 and 9.4.9.

**Retirement is one subject and came out of ``mqc_uni_ticket_report.py``** when
that module reached the 900-line runway ceiling, which is the split
``code-style.md`` section 5.1 asks for: the next subject added belongs in a
module named for it. The two directions are deliberately together here, because
the defect that prompted `115793` was resolution not carrying a rule holding
already had, and a reader comparing them needs both in view.

The report both skip cases read and the register they build sit in
``retirement_support.py``, which collection does not reach.
"""

