pytestmark = pytest.mark.unit


class TestMQCRetirementNeedsAPass:
    """A finding leaves the bug file only when its case was measured passing."""

    @story("Resolution credits a vendor only for what a run measured")
    def MQC_CAS_UNI_115793_a_finding_whose_case_skipped_is_not_resolved_upstream(
        self, tmp_path: Path
    ) -> None:
        """A skipped case keeps its finding; only a passing one is resolved upstream.

        A case absent from a run's failures was not necessarily measured: it may
        have skipped behind a failed foundation. Resolving it names a vendor fix
        on a run that measured nothing, which section 9.4.1 calls the error that
        most damages a published report.

        Design: ``consumer_ci.md`` section 9.4.9.

        Args:
            tmp_path (Path): Where the constructed report is written.

        Returns:
            None
        """
        report = tmp_path / "junit.xml"
        report.write_text(MIXED_REPORT, encoding="utf-8")
        run = RunContext(
            engine="openai", mode="live", models={"any": "gpt-test"}, expected={},
            today=date(2026, 10, 29), resolve=True, passed=parse_passed(report),
        )
        register = open_on_both()

        step(1, "resolve against a live run that measured one case and skipped the other")
        resolve_upstream(register, {}, run)
        assert register[PASSED_CASE]["status"] == "resolved_upstream", (
            "a finding whose case a live run measured as passing was not resolved"
        )

        step(2, "read the status of the case the run skipped")
        assert register[SKIPPED_CASE]["status"] == "open", (
            "a finding whose case was skipped, and so never measured, was credited "
            "to the vendor as a fix"
        )

    @story("A pass removes the finding")
    def MQC_CAS_UNI_115821_a_finding_whose_case_passed_on_replay_is_removed(
        self, tmp_path: Path
    ) -> None:
        """A replay run that measured the case passing removes its finding, and says so.

        Design: ``consumer_ci.md`` section 9.4.11.

        Args:
            tmp_path (Path): Where the constructed report is written.

        Returns:
            None
        """
        step(1, "merge a replay run that measured the case passing")
        merged, changes = merge(open_on_both(), {}, replay_run(tmp_path / "junit.xml"))
        assert PASSED_CASE not in merged, (
            f"a finding whose case the run measured passing was kept: "
            f"{merged.get(PASSED_CASE)}"
        )

        step(2, "read the change line the removal printed")
        assert f"REMOVED {PASSED_CASE}, it passed on 2026-11-06" in changes, (
            f"the removal printed no line naming the case and the date: {changes}"
        )

    @story("A skip is not a pass")
    def MQC_CAS_UNI_115822_a_finding_whose_case_skipped_is_kept(
        self, tmp_path: Path
    ) -> None:
        """A finding whose case the run skipped stays exactly as it was.

        Design: ``consumer_ci.md`` sections 9.4.7.1 and 9.4.11.

        Args:
            tmp_path (Path): Where the constructed report is written.

        Returns:
            None
        """
        step(1, "merge a replay run that skipped the case and read its finding")
        register = open_on_both()
        merged, _ = merge(register, {}, replay_run(tmp_path / "junit.xml"))
        assert merged.get(SKIPPED_CASE) == register[SKIPPED_CASE], (
            f"a finding whose case was skipped, and so never measured, was "
            f"removed or changed: {merged.get(SKIPPED_CASE)}"
        )

    @story("A change of severity is a new finding")
    def MQC_CAS_UNI_115823_a_failure_measured_passw_is_replaced_by_a_fresh_warning(
        self, tmp_path: Path
    ) -> None:
        """A failure entry the run measures as passw is replaced, and nothing carries over.

        Design: ``consumer_ci.md`` section 9.4.11.

        Args:
            tmp_path (Path): Where the constructed report is written.

        Returns:
            None
        """
        failure = {
            "case": PASSED_CASE, "taxonomy_code": "QC_LLM_MATCH_MISCOMPUTED",
            "observations": "2 of 5 passed", "observed_model": "gpt-old",
            "first_observed": "2026-10-20", "last_observed": "2026-10-20",
            "status": "open", "expected": "", "actual": "The failure as it read.",
            "reproduce": "", "ticket": "VENDOR-1",
        }
        warning = {
            "taxonomy_code": "QC_LLM_MATCH_MISCOMPUTED", "severity": "warning",
            "actual": "The warning as it reads.",
        }
        step(1, "merge a run that measured the failing case as passw")
        merged, changes = merge(
            {PASSED_CASE: failure}, {PASSED_CASE: warning},
            replay_run(tmp_path / "junit.xml"),
        )
        entry = merged[PASSED_CASE]
        carried = {
            field: entry.get(field) for field in ("first_observed", "observations",
                                                  "ticket", "actual", "observed_model")
            if entry.get(field) == failure[field]
        }
        assert entry.get("severity") == "warning" and not carried, (
            f"the warning entry kept what the failure claimed: {carried}, "
            f"severity {entry.get('severity')!r}"
        )

        step(2, "read the change line the replacement printed")
        assert any(line.startswith(f"REPLACED {PASSED_CASE}") for line in changes), (
            f"the replacement printed no REPLACED line: {changes}"
        )

    @story("Nothing is withdrawn or held")
    def MQC_CAS_UNI_115824_no_finding_is_withdrawn_held_or_written_to_a_holding_list(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """The hold flag is refused, and no retired status or holding list is written.

        Design: ``consumer_ci.md`` section 9.4.11.

        Args:
            tmp_path (Path): Where the register is written.
            monkeypatch (pytest.MonkeyPatch): Moves the working directory there.

        Returns:
            None
        """
        step(1, "pass the retired hold flag to the findings tool")
        # --resolve-from-live without --mode live returns before any suite runs,
        # so a tool still accepting the hold flag fails here without measuring.
        try:
            exit_code = findings_main(["--engine", "openai", "--as-of", "2026-11-06",
                                       "--hold-unreproduced", "--resolve-from-live"])
        except SystemExit as refused:
            exit_code = refused.code
        assert exit_code == 2, f"the hold flag was not refused by argparse: {exit_code}"

        step(2, "read whether a run can still be asked to hold")
        assert "hold_unreproduced" not in {field.name for field in fields(RunContext)}, (
            "RunContext still carries hold_unreproduced"
        )

        step(3, "merge a replay run and read every status it wrote")
        merged, _ = merge(open_on_both(), {}, replay_run(tmp_path / "junit.xml"))
        assert {entry.get("status") for entry in merged.values()} <= {
            "open", "resolved_upstream"
        }, f"a retired status was written: {merged}"

        step(4, "write a register holding an open and a resolved entry")
        monkeypatch.chdir(tmp_path)
        register_path("openai").parent.mkdir(parents=True)
        register = open_on_both()
        register[PASSED_CASE]["status"] = "resolved_upstream"
        write_register("openai", register, render)
        written = register_path("openai").read_text(encoding="utf-8")
        assert not (tmp_path / "config" / "findings" / "unconfirmed").exists() and all(
            case in written for case in register
        ), "an entry left the bug file for a holding list"
