"""Unit preconditions that the gates reading one numbered item accept the right figures there.

Created: 2026-11-05
Last updated: 2026-11-05

This file contains ``TestMQCListItemGates``, two cases that run shipped rules against
fixed numbered answers. ``115025`` checks the share gate of ``134203``, told how to
round, and of ``134207``, told nothing, each accepting the precisions its task allows
and refusing the share openai stated. ``115026`` checks the three gates of ``134402``
admit 100 and 50 percent with a judged match disclosed, and refuse a refusal, a
missing disclosure and a claimed named match.

**These run in the ``unit`` precondition gate**, ahead of the graded cases those rules
decide, so a model is never failed for an answer the rule was meant to accept. A failure
is an instrument defect, **not a model finding**: the run exits 3 and no graded case
executes, and the module carries no priority marker, per the harness
``framework-rules.md`` section 3.3.

Specified by ``docs/testing/model_evaluation_test_plan.md`` sections 9.4.2 and 9.8.2.3.
"""

