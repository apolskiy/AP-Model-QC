from typing import Final

import pytest

from cmn.case_steps import step
from cmn.grouping import story

from tests.cases.corpus_support import gate_held
from tests.cases.list_item_support import (
    match_answer as _match_answer,
    share_answer as _share_answer,
    shipped_rule as _rule,
)

pytestmark = pytest.mark.unit

_SHARE_GATE: Final[str] = "A_GND_SHARE_IS_TRUE"
_PERCENT_GATE: Final[str] = "A_MAT_OPEN_STATES_A_PERCENTAGE"
_DISCLOSURE_GATE: Final[str] = "A_MAT_OPEN_DECLARES_JUDGEMENT"
_NAMED_GATE: Final[str] = "A_MAT_OPEN_CLAIMS_NO_NAMED_MATCH"

_JUDGED: Final[str] = (
    "Judged equivalent rather than a named match: MySQL is equivalent to PostgreSQL."
)


class TestMQCListItemGates:
    """What a gate reading one numbered item accepts there, read against answers written for it."""

    @story("Falsehood")
    def MQC_CAS_UNI_115025_the_share_gates_read_the_precision_each_task_asks_for(
        self,
    ) -> None:
        """Told one decimal place, only 47.1 passes; told nothing, 47, 47.1 and 47.14 pass.

        Design: ``model_evaluation_test_plan.md`` section 9.4.2.

        Returns:
            None
        """
        instructed = _rule("MQC_RULE_gnd_no_falsehood")
        unrounded = _rule("MQC_RULE_gnd_no_falsehood_unrounded")

        step(1, "read the share each answer states through the instructed gate")
        verdicts = {
            share: gate_held(instructed, _SHARE_GATE, _share_answer(share))
            for share in ("47.1%", "47.1 percent", "47%", "47.14%", "47.2%", "47.0%", "47.10%")
        }
        assert verdicts == {
            "47.1%": True, "47.1 percent": True, "47%": False, "47.14%": False,
            "47.2%": False, "47.0%": False, "47.10%": False,
        }, f"the instructed gate read the shares wrongly: {verdicts}"

        step(2, "read the share each answer states through the uninstructed gate")
        verdicts = {
            share: gate_held(unrounded, _SHARE_GATE, _share_answer(share))
            for share in (
                "47%", "47.1%", "47.14%", "47.1396%", "about 47 percent",
                "47.2%", "47.16%", "47.0%", "48%",
            )
        }
        assert verdicts == {
            "47%": True, "47.1%": True, "47.14%": True, "47.1396%": True,
            "about 47 percent": True,
            "47.2%": False, "47.16%": False, "47.0%": False, "48%": False,
        }, f"the uninstructed gate read the shares wrongly: {verdicts}"

        step(3, "read openai's share, with item 4 giving the true one, through both gates")
        assert not gate_held(instructed, _SHARE_GATE, _share_answer("47.2%")) and not (
            gate_held(unrounded, _SHARE_GATE, _share_answer("47.2%"))
        ), "a gate read the true share in item 4 in place of the wrong one in item 3"

    @story("Open enumeration")
    def MQC_CAS_UNI_115026_the_open_enumeration_gates_pass_the_floor_and_refuse_zero(
        self,
    ) -> None:
        """100 and 50 percent pass with a judged match disclosed; a refusal or a named match fails.

        Design: ``model_evaluation_test_plan.md`` section 9.8.2.3.

        Returns:
            None
        """
        rule = _rule("MQC_RULE_mat_open_enumeration")

        step(1, "read each stated percentage through the item 1 gate")
        verdicts = {
            stated: gate_held(rule, _PERCENT_GATE, _match_answer(stated, _JUDGED))
            for stated in (
                "100%", "100 percent", "The candidate meets 100% of the requirement.",
                "50%", "50.0 percent", "0%", "33%", "The candidate does not meet it.",
            )
        }
        assert verdicts == {
            "100%": True, "100 percent": True,
            "The candidate meets 100% of the requirement.": True,
            "50%": True, "50.0 percent": True,
            "0%": False, "33%": False, "The candidate does not meet it.": False,
        }, f"the percentage gate read item 1 wrongly: {verdicts}"

        step(2, "read each item 2 through the disclosure gate")
        disclosures = {
            _JUDGED: True,
            "MySQL is judged similar to PostgreSQL.": True,
            "MySQL falls in the same category as PostgreSQL.": True,
            "Matched a named item.": False,
            "MySQL.": False,
        }
        verdicts = {
            text: gate_held(rule, _DISCLOSURE_GATE, _match_answer("100%", text))
            for text in disclosures
        }
        assert verdicts == disclosures, f"the disclosure gate read item 2 wrongly: {verdicts}"

        # A NEGATION IS THE PREMISE OF A JUDGED MATCH, and each of these carries
        # no other hedge, so only the negation can admit it.
        step(3, "read each item 2 through the named-match gate")
        claims = {
            "Redis is not listed in the summary, and MySQL is judged similar to PostgreSQL.":
                True,
            "Redis is not present. MySQL is judged similar to PostgreSQL.": True,
            "Redis is absent from the summary; MySQL is judged similar to PostgreSQL.": True,
            "PostgreSQL is not held by the candidate. MySQL is judged similar.": True,
            "PostgreSQL is listed as a match.": False,
            "Postgres is held by the candidate.": False,
            "The candidate holds Redis and matches it.": False,
        }
        verdicts = {
            text: gate_held(rule, _NAMED_GATE, _match_answer("100%", text)) for text in claims
        }
        assert verdicts == claims, f"the named-match gate read item 2 wrongly: {verdicts}"

        step(4, "read a disclosure made only in item 3 through the item 2 gate")
        assert not gate_held(
            rule, _DISCLOSURE_GATE,
            "1. 100%\n2. MySQL.\n3. MySQL is judged equivalent to PostgreSQL.\n",
        ), "the disclosure gate read item 3, so a disclosure out of place passed"
