"""Unit preconditions that the syntax-location case checks the error and line, judging the cause.

Created: 2026-11-07
Last updated: 2026-11-08

This file contains ``TestMQCSyntaxLocationGrading``, nine cases that put simulated
answers through ``tests.cases.graded_support.observe`` for ``134106``, with the
dispatch replaced by the answer and the judge by one awarding a fixed score. They
check that no answer and a dispatch error are never measured as answers; that an
answer given as no list or out of order, a wrong error in item 1, or a wrong or second
line in item 2 fails its check at every judge score; that a wrong cause in item 3 passes
the checks and fails on a judge sent the anchor naming it; that the judge decides at its
threshold of 3; and that three right items pass.

**These run in the ``unit`` precondition gate**, ahead of the graded case, and call no
engine and no judge. A failure is an instrument defect, **not a model finding**: the
run exits 3 and no graded case executes, and the module carries no priority marker,
per the harness ``framework-rules.md`` section 3.3.

Specified by ``docs/testing/model_evaluation_test_plan.md`` section 9.9.5.1.
"""

