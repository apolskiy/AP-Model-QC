import ast
from pathlib import Path
from types import SimpleNamespace

import pytest

from cmn.case_steps import step
from cmn.grouping import story
from ingestion.cases import build_case_id

from tests.cases.live_band_support import write_floor_report
from tests.cases.quarantine_support import quarantine_deselection
from tests.cases.workflow_support import repository_root
from tools.band_floor import assess

pytestmark = pytest.mark.unit

_GREEN = 0
_BELOW_FLOOR = 1
_FLOOR = 0.90

# THE HOOK CONFTEST CALLS TO DROP A QUARANTINED CASE. Section 4.6.14.
_DESELECTOR = "deselect_quarantined_cases"


class TestMQCBandCounting:
    """A band counts every case it selected, and selects no quarantined case."""

    @story("A skip is not a pass")
    def MQC_CAS_UNI_115863_a_lower_band_excluding_its_skips_is_reported(
        self, tmp_path: Path,
    ) -> None:
        """Eight passes and two skips is 80 percent of ten, below a 90 percent floor.

        Excluding the skips read 8 of 8, a hundred percent. Nine passes and one
        skip sits on the floor exactly, and clears it.

        Design: ``consumer_ci.md`` section 3.12.2.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        below = assess(write_floor_report(tmp_path / "below", 8, 2), _FLOOR)
        at_floor = assess(write_floor_report(tmp_path / "at", 9, 1), _FLOOR)

        step(1, "find two skips in ten taking the band below a 90 percent floor")
        assert below[0] == _BELOW_FLOOR, below

        step(2, "find the reason counting the skips against the selected cases")
        assert "8 of 10" in below[1], below

        step(3, "find one skip in ten sitting on the floor and clearing it")
        assert at_floor[0] == _GREEN, at_floor

    @story("A quarantined case is outside the run")
    def MQC_CAS_UNI_115864_a_quarantined_case_collected_is_reported(self) -> None:
        """A quarantined case is dropped at collection; every other case stays.

        Design: harness ``cmn_verdict_and_cli.md`` section 4.6.14.

        Returns:
            None
        """
        held = SimpleNamespace(name="MQC_CAS_EVAL_134000_holds")
        known = SimpleNamespace(name="MQC_CAS_EVAL_134001_known_failure")
        precondition = SimpleNamespace(name="MQC_CAS_UNI_115000_reads_the_corpus")
        pairs = {
            "MQC_CAS_EVAL_134000_holds": ("MQC_TASK_A", "MQC_RULE_A"),
            "MQC_CAS_EVAL_134001_known_failure": ("MQC_TASK_B", "MQC_RULE_B"),
        }
        kept, dropped = quarantine_deselection(
            [held, known, precondition], pairs,
            frozenset({build_case_id("MQC_TASK_B", "MQC_RULE_B")}),
        )
        conftest = ast.parse((repository_root() / "conftest.py").read_text(encoding="utf-8"))
        called = {
            getattr(node.func, "id", None) or getattr(node.func, "attr", None)
            for node in ast.walk(conftest) if isinstance(node, ast.Call)
        }

        step(1, "find the quarantined case dropped")
        assert dropped == [known], dropped

        step(2, "find every other case kept, the precondition included")
        assert kept == [held, precondition], kept

        step(3, f"find conftest.py calling {_DESELECTOR} at collection")
        assert _DESELECTOR in called, sorted(name for name in called if name)
