class TestMQCCalibrationRecord:
    """A judge is calibrated once, and every ladder it judges reads the record."""

    @story("Calibration is the judge's")
    def MQC_CAS_UNI_115845_a_judge_without_its_calibration_workflow_is_reported(
        self,
    ) -> None:
        """Each judge has a monthly, dispatchable caller; the run is live, on one platform.

        Design: ``consumer_ci.md`` section 7.4.5.

        Returns:
            None
        """
        judges = sorted({
            str((job.get("with") or {}).get("judge", ""))
            for caller in ladder_callers().values() for job in jobs(caller).values()
            if LADDER in str(job.get("uses") or "")
        } - {""})
        uncalled: list[str] = []
        for judge in judges:
            name = f"calibrate-{judge}.yml"
            if not (WORKFLOWS / name).is_file():
                uncalled.append(f"{name} is absent")
                continue
            caller = load(name)
            triggers = caller.get("on") or caller.get(True) or {}
            crons = [str(entry.get("cron", "")).split() for entry in triggers.get("schedule") or []]
            passes = [str((job.get("with") or {}).get("judge", "")) for job in jobs(caller).values()
                      if _CALIBRATE in str(job.get("uses") or "")]
            if len(crons) != 1 or crons[0][3:] != ["*", "*"] or not crons[0][2].isdigit() \
                    or "reason" not in dispatch_inputs(caller) or passes != [judge]:
                uncalled.append(f"{name}: crons {crons}, passes {passes}, "
                                f"inputs {sorted(dispatch_inputs(caller))}")
        calibrating = {
            name: job for name, job in jobs(load(_CALIBRATE)).items()
            if any(flag_value(line, "-m") == "calibration" for line in run_lines(job))
        } if (WORKFLOWS / _CALIBRATE).is_file() else {}
        lines = [line for job in calibrating.values() for line in run_lines(job)
                 if flag_value(line, "-m") == "calibration"]
        committed = [
            entry for job in calibrating.values()
            for entry in steps_running(job, f"git add {RECORD_PATH}")
            if "always()" in str(entry.get("if", "")) and "git push" in str(entry.get("run"))
        ]

        step(1, "find the ladders judged by at least one judge")
        assert judges, judges

        step(2, "find each judge's caller scheduled monthly, dispatchable with a reason")
        assert not uncalled, uncalled

        step(3, f"find one calibration job, in {_LIVE_ENVIRONMENT!r}, on {DEFAULT_OS}")
        assert len(calibrating) == 1 and all(
            job.get("environment") == _LIVE_ENVIRONMENT and job.get("runs-on") == DEFAULT_OS
            for job in calibrating.values()), calibrating

        step(4, "find it judging live with the judge named, capped, and writing the record")
        assert len(lines) == 1 and flag_value(lines[0], "--judge-mode") == "live" and \
            flag_value(lines[0], "--judge-engine") == "${{ inputs.judge }}" and \
            flag_value(lines[0], "--max-spend") and \
            flag_value(lines[0], "--record-calibration") == RECORD_PATH, lines

        step(5, "find the record committed whatever the families' outcome")
        assert len(committed) == 1, committed

    @story("Calibration is the judge's")
    def MQC_CAS_UNI_115846_the_samples_digest_moves_with_samples_and_not_line_endings(
        self, tmp_path: Path,
    ) -> None:
        """A changed sample or name moves the digest; CRLF line endings do not.

        Design: ``consumer_ci.md`` section 7.4.5.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        samples = tmp_path / "samples"
        samples.mkdir()
        (samples / "grounding.yaml").write_bytes(b"samples:\n  - id: a\n")
        first = calibration_support.samples_digest(samples)
        (samples / "grounding.yaml").write_bytes(b"samples:\r\n  - id: a\r\n")
        crlf = calibration_support.samples_digest(samples)
        (samples / "grounding.yaml").write_bytes(b"samples:\n  - id: b\n")
        edited = calibration_support.samples_digest(samples)
        (samples / "grounding.yaml").rename(samples / "premise.yaml")
        renamed = calibration_support.samples_digest(samples)

        step(1, "compute a digest from the shipped samples")
        assert calibration_support.samples_digest(), calibration_support.samples_digest()

        step(2, "keep the digest when only the line endings change")
        assert crlf == first, (first, crlf)

        step(3, "move the digest when a sample's content changes")
        assert edited != first, edited

        step(4, "move the digest when a sample file is renamed")
        assert renamed != edited, renamed

    @story("Calibration is the judge's")
    def MQC_CAS_UNI_115847_a_band_reading_a_calibration_record_rests_on_it(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path,
    ) -> None:
        """A session naming a record is wired without a calibration case; one naming none is not.

        Design: ``consumer_ci.md`` section 7.4.5.

        Args:
            monkeypatch (pytest.MonkeyPatch): Replaces the harness wiring with a recorder.
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        wired: list[int] = []
        monkeypatch.setattr(calibration_support, "rest_judged_cases_on_calibration",
                            lambda items, families: wired.append(len(items)) or 0)
        monkeypatch.setattr(calibration_support.suite_support, "judged_case_families",
                            lambda root: {})
        named = SimpleNamespace(getoption=lambda name, default=None: (
            "calibration/record.json" if name == "--calibration-record" else default))
        unnamed = SimpleNamespace(getoption=lambda name, default=None: default)

        calibration_support.rest_on_family_calibration([], tmp_path, named)
        named_calls = len(wired)
        calibration_support.rest_on_family_calibration([], tmp_path, unnamed)

        step(1, "wire a session naming a record although it collected no calibration case")
        assert named_calls == 1, wired

        step(2, "wire nothing in a session naming neither")
        assert len(wired) == 1, wired
