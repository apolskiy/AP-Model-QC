    @story("A missing artifact skips the cases using it")
    def MQC_CAS_UNI_115889_an_absent_precondition_record_is_declared_missing(
        self, tmp_path: Path,
    ) -> None:
        """The tool declares an absent record, and the band action passes the first declaration.

        Design: ``consumer_ci.md`` section 3.12.1.3.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        absent = tmp_path / "reports" / "preconditions.json"
        present = tmp_path / "preconditions.json"
        present.write_text("{}", encoding="utf-8")
        declared = tmp_path / "declared.txt"
        undeclared = tmp_path / "undeclared.txt"
        statuses = (
            _declare(["--record", str(absent), "--output", str(declared)]),
            _declare(["--record", str(present), "--output", str(undeclared)]),
        )
        action = yaml.safe_load(
            (repository_root() / ".github" / "actions" / "band" / "action.yml").read_text(
                encoding="utf-8")
        )
        entries = (action.get("runs") or {}).get("steps") or []
        order = [
            "record" if entry.get("id") == _RECORD_STEP
            and _RECORD_TOOL in str(entry.get("run"))
            and _FIRST_DECLARATION in str(entry.get("if"))
            else "pytest" if str((entry.get("env") or {}).get(_DECLARED_ENV)) == _DECLARED
            and "pytest" in str(entry.get("run"))
            else "other"
            for entry in entries
        ]

        step(1, "find the absent record declared missing, naming its path")
        assert statuses[0] == 0 and declared.exists() and declared.read_text(encoding="utf-8") == (
            f"missing=precondition_record={absent}\n"
        ), (statuses, declared.read_text(encoding="utf-8") if declared.exists() else None)

        step(2, "find nothing declared for a record that is present")
        assert statuses[1] == 0 and not undeclared.exists(), (
            statuses, undeclared.read_text(encoding="utf-8") if undeclared.exists() else None)

        step(3, "find the band action declaring the record before pytest, where none was")
        assert [kind for kind in order if kind != "other"] == ["record", "pytest"], order

    @story("A missing artifact skips the cases using it")
    def MQC_CAS_UNI_115890_a_band_missing_its_precondition_record_skips_every_case(
        self, tmp_path: Path,
    ) -> None:
        """A band run with its record absent and declared missing skips everything, exit 3.

        Design: ``consumer_ci.md`` section 3.12.1.3.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        absent = tmp_path / "reports" / "preconditions.json"
        status, _, outcomes = run_child_band(
            tmp_path, "0",
            ["--priority", "0", "--preconditions-record", str(absent),
             "--missing-artifact", f"precondition_record={absent}"],
        )

        step(1, "find the band exiting 3 with every case it selected skipped")
        assert status == 3 and outcomes and set(outcomes) == {"skipped"}, (status, outcomes)
