    @story("A scheduled evaluation skips a month already measured")
    def MQC_CAS_UNI_115833_an_unreadable_history_refuses(self, tmp_path: Path) -> None:
        """A history that cannot be read exits 4 and writes no decision to evaluate.

        Design: ``consumer_ci.md`` section 4.18.3.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        output = tmp_path / "output.txt"
        summary = tmp_path / "summary.md"
        argv = ["--engine", "gemini", "--repository", "o/r", "--current-run", "14",
                "--output", str(output), "--summary", str(summary)]

        def unreadable(repository: str, engine: str, since: date) -> tuple[list, dict]:
            raise ValueError(f"QC_HARNESS_DEPENDENCY_UNMET: no history for {repository}")

        def measured(_repository: str, _engine: str, _since: date) -> tuple[list, dict]:
            return _RUNS, {**_UNMEASURED, **_MEASURED}

        step(1, "exit 4 when the history cannot be read")
        assert main(argv, fetch_history=unreadable, today=_TODAY) == 4

        step(2, "write no decision to evaluate")
        assert not output.exists() or "evaluate=true" not in output.read_text(encoding="utf-8")

        step(3, "write evaluate=false with the reason when a run already measured")
        assert main(argv, fetch_history=measured, today=_TODAY) == 0 and \
            "evaluate=false" in output.read_text(encoding="utf-8"), output.read_text(
                encoding="utf-8")

        step(4, "say on the run summary that the month was skipped, and why")
        written = summary.read_text(encoding="utf-8")
        assert "skipped" in written and "run 11" in written, written

    @story("Each engine is evaluated monthly and asks first")
    def MQC_CAS_UNI_115834_each_scheduled_caller_fires_monthly_and_asks_first(self) -> None:
        """A monthly cron on a day of its own, and a decision gating the run on a schedule.

        Design: ``consumer_ci.md`` section 4.18.3.

        Returns:
            None
        """
        rostered = sorted(load_engines(packaged_roster_path()))
        days: list[str] = []
        problems: list[str] = []
        for engine in rostered:
            loaded = load(f"evaluate-{engine}-scheduled.yml")
            triggers = loaded.get("on") or loaded.get(True) or {}
            crons = [str(entry.get("cron", "")).split() for entry in triggers.get("schedule") or []]
            if len(crons) != 1 or len(crons[0]) != 5 or not crons[0][2].isdigit() \
                    or crons[0][3:] != ["*", "*"]:
                problems.append(f"{engine}: not one monthly cron: {crons}")
            else:
                days.append(crons[0][2])
            defined = jobs(loaded)
            decide = defined.get("decide", {})
            regression = defined.get("regression", {})
            if "github.event_name == 'schedule'" not in str(decide.get("if", "")) or \
                    "tools.recent_evaluation" not in " ".join(run_lines(decide, _ROOT)):
                problems.append(f"{engine}: no decision asked only on a schedule")
            if "needs.decide.outputs.evaluate" not in str(regression.get("if", "")):
                problems.append(f"{engine}: the regression run does not read the decision")

        step(1, "find a monthly cron and a decision gating the regression run for every engine")
        assert not problems, problems

        step(2, "find each engine on a day of its own")
        assert len(set(days)) == len(rostered), days

    @story("Each engine is evaluated monthly and asks first")
    def MQC_CAS_UNI_115835_the_probe_fires_weekly_and_dispatches_declared_inputs(
        self,
    ) -> None:
        """A weekly cron, the scheduled caller as target, and only inputs that caller declares.

        Design: ``consumer_ci.md`` sections 4.18.3 and 4.23.

        Returns:
            None
        """
        probe = load("probe-model-version.yml")
        triggers = probe.get("on") or probe.get(True) or {}
        crons = [str(entry.get("cron", "")).split() for entry in triggers.get("schedule") or []]
        dispatch = " ".join(run_lines(jobs(probe)["dispatch"], _ROOT))
        fields = set(re.findall(r"--field\s+([a-z_]+)=", dispatch))
        undeclared = {}
        for engine in sorted(load_engines(packaged_roster_path())):
            caller = load(f"evaluate-{engine}-scheduled.yml")
            declared = set(((caller.get("on") or caller.get(True) or {})
                            .get("workflow_dispatch") or {}).get("inputs") or {})
            if fields - declared:
                undeclared[engine] = sorted(fields - declared)

        step(1, "find one weekly cron, on a single weekday")
        assert len(crons) == 1 and len(crons[0]) == 5 and crons[0][2:4] == ["*", "*"] \
            and re.fullmatch(r"[0-6]", crons[0][4]), crons

        step(2, "find the dispatch naming the scheduled caller")
        assert "evaluate-${engine}-scheduled.yml" in dispatch, dispatch

        step(3, "find every dispatched field declared by every caller")
        assert fields and not undeclared, (fields, undeclared)

    @story("Each engine is evaluated monthly and asks first")
    def MQC_CAS_UNI_115836_the_probe_alone_reads_keys_from_an_environment_of_its_own(
        self,
    ) -> None:
        """The probe's keys come from ``version_probe``, and no other job names it.

        Design: ``consumer_ci.md`` section 4.23.6.

        Returns:
            None
        """
        probe = jobs(load("probe-model-version.yml"))["probe"]
        elsewhere: list[str] = []
        for workflow in sorted(WORKFLOWS.glob("*.yml")):
            for name, job in jobs(load(workflow.name)).items():
                if workflow.name == "probe-model-version.yml" and name == "probe":
                    continue
                if job.get("environment") == _PROBE_ENVIRONMENT:
                    elsewhere.append(f"{workflow.name} job {name!r}")
        spending = [line for line in run_lines(probe, _ROOT)
                    if "pytest" in line or "--mode live" in line]

        step(1, f"find the probe job in the {_PROBE_ENVIRONMENT!r} environment")
        assert probe.get("environment") == _PROBE_ENVIRONMENT, probe.get("environment")

        step(2, "find no other job naming that environment")
        assert not elsewhere, elsewhere

        step(3, "find the probe running no test")
        assert not spending, spending

    @story("Each engine is evaluated monthly and asks first")
    def MQC_CAS_UNI_115848_a_scheduled_run_with_the_wrong_judge_is_reported(
        self,
    ) -> None:
        """Each scheduled regression run passes the judge section 4.18.2 gives its engine.

        Design: ``consumer_ci.md`` section 4.18.2.

        Returns:
            None
        """
        passed = {
            engine: [str((job.get("with") or {}).get("judge", ""))
                     for job in jobs(load(f"evaluate-{engine}-scheduled.yml")).values()
                     if "evaluate-engine.yml" in str(job.get("uses") or "")]
            for engine in sorted(load_engines(packaged_roster_path()))
        }

        step(1, "find every rostered engine with a judge assigned")
        assert set(passed) == set(_SCHEDULED_JUDGE), sorted(passed)

        step(2, "find each scheduled regression run passing its engine's judge")
        assert passed == {engine: [judge] for engine, judge in _SCHEDULED_JUDGE.items()}, passed
