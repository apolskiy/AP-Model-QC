from pathlib import Path
from typing import Any

import allure
import pytest

from tools.ticket_report import _input_block, recorded_request

pytestmark = pytest.mark.unit

_TASK: dict[str, Any] = {
    "user_prompt": "A prompt the corpus declares.",
    "system_instruction": "An instruction the corpus declares.",
}
_REQUEST: dict[str, Any] = {
    "model": "claude-opus-5-5",
    "messages": [{"role": "user", "content": "A prompt the provider received."}],
}


class TestMQCTicketInput:
    """The ticket shows the call that was made, or says it cannot."""

    @allure.story("Input is the recorded request")
    def MQC_CAS_UNI_115733_a_ticket_input_is_the_recorded_request_not_the_corpus(
        self, tmp_path: Path
    ) -> None:
        """The recording wins over the corpus, and its absence is stated.

        Design: ``consumer_ci.md`` sections 9.5.3 and 9.5.3.1.

        Returns:
            None
        """
        # THE RECORDING IS PREFERRED, and the corpus text does not appear at
        # all: showing both would let a reader cite whichever they read first.
        block = "\n".join(_input_block(_TASK, _REQUEST, "claude"))
        assert "A prompt the provider received." in block, block
        assert "A prompt the corpus declares." not in block, (
            "the corpus prompt appeared beside the recorded one, so a reader "
            "can quote text the provider never received"
        )
        assert "claude-opus-5-5" in block, (
            "the model identity is absent, and it is the first thing a vendor "
            "checks"
        )

        # AND IT CARRIES A RUNNABLE REPRODUCTION rather than a payload to
        # assemble, which is the whole of section 9.5.3.1.
        assert "import anthropic" in block and "client.messages.create(" in block, (
            "the ticket offers no runnable call, so reproducing the finding "
            "means rebuilding the request by hand"
        )
        assert "ANTHROPIC_API_KEY" in block, (
            "the reproduction does not say which variable to set"
        )

        # WITHOUT A RECORDING IT SAYS SO. A reconstruction labelled as the
        # request is the defect section 9.5.3 removes, so the fallback is
        # marked rather than presented as the call.
        fallback = "\n".join(_input_block(_TASK, None, "claude"))
        assert "predates the stored request" in fallback, (
            "the corpus was presented as the call, so a vendor would be shown "
            "text the provider may never have received"
        )
        assert "A prompt the corpus declares." in fallback, (
            "the fallback shows nothing at all, which is less useful than "
            "showing the corpus and saying what it is"
        )

        # AND THE READER FOR IT ANSWERS HONESTLY ON AN EMPTY STORE, rather
        # than raising, because a pair with no recording is an ordinary state.
        assert recorded_request(tmp_path, "claude", "MQC_TASK_x", "MQC_RULE_x") is None
