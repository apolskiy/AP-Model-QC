    @story("The regression run is the live runs")
    def MQC_CAS_UNI_115856_a_regression_run_holding_a_replay_is_reported(self) -> None:
        """A regression run is its checks and three live bands, and nothing replays.

        Design: ``consumer_ci.md`` sections 7.8.1, 7.8.5 and 7.9.2.

        Returns:
            None
        """
        root = repository_root()
        regression = jobs(load(REGRESSION_RUN))
        missing = [name for name in REGRESSION_JOBS if name not in regression]
        retired = [name for name in regression if name.startswith(RETIRED_JOB_PREFIXES)]
        unbanded: list[str] = []
        moded: list[str] = []
        named: list[str] = []
        unpaired: list[str] = []
        for position, name in enumerate(_STAGE["jobs"]):
            job = regression.get(name, {})
            if tuple(band_inputs(job).get(key) for key in ("band", "priority", "blocking")) \
                    != BANDS[position]:
                unbanded.append(f"{name}: {band_inputs(job)}")
            line = band_invocation(job, root)
            if (flag_value(line, "--mode"), flag_value(line, "--judge-mode")) != (
                    _STAGE["mode"], _STAGE["judge_mode"]):
                moded.append(f"{name}: {line.strip()}")
            if not str(job.get("name", "")).startswith(
                    f"{_STAGE['name']}, {BANDS[position][0]}"):
                named.append(f"{name}: {job.get('name')!r}")
            if pair_mismatch(job, _STAGE, position):
                unpaired.append(f"{name}: {pair_mismatch(job, _STAGE, position)}")
        replaying = replaying_invocations(regression, root)
        unguarded = live_jobs_off_their_environment(root)

        step(1, f"find every job a regression run holds: {REGRESSION_JOBS}")
        assert not missing, missing

        step(2, "find no job of a retired replay stage")
        assert not retired, retired

        step(3, "find each live band calling the band definition at its band and floor")
        assert not unbanded, unbanded

        step(4, "find each live band invocation running the candidate and the judge live")
        assert not moded, moded

        step(5, "find each live band named for its pair and engine, then its band")
        assert not named, named

        step(6, "find each live band's report stem and carried outcomes named for its pair")
        assert not unpaired, unpaired

        step(7, "find no regression run invocation naming replay as a mode")
        assert not replaying, replaying

        step(8, f"find every job running a case live naming the {_LIVE_ENVIRONMENT!r} "
                f"environment, the debug workflow's {DEBUG_LIVE!r} job naming "
                f"{DEBUG_ENVIRONMENT!r}")
        assert not unguarded, unguarded

    @story("The regression run is the live runs")
    def MQC_CAS_UNI_115857_a_live_band_out_of_order_is_reported(self) -> None:
        """The P0 band waits on both checks; each later band on the band before it.

        Design: ``consumer_ci.md`` sections 7.8.2 and 7.9.2.

        Returns:
            None
        """
        regression = jobs(load(REGRESSION_RUN))
        checks = {PRECONDITIONS_JOB, CALIBRATION_JOB}
        first, *later = LIVE_BANDS
        opening = regression.get(first, {})
        unopened = [] if checks <= set(needs(opening)) and not opening.get("if") else [
            f"{first}: needs {needs(opening)}, if {opening.get('if')!r}"
        ]
        unchained: list[str] = []
        uncarried: list[str] = []
        for before, name in zip(LIVE_BANDS, later):
            job = regression.get(name, {})
            if not {before} | checks <= set(needs(job)) or str(job.get("if", "")) != _CHAINED:
                unchained.append(f"{name}: needs {needs(job)}, if {job.get('if')!r}")
            uploaded = [
                str((entry.get("with") or {}).get("name", ""))
                for entry in regression.get(before, {}).get("steps") or []
                if "upload-artifact" in str(entry.get("uses", ""))
            ]
            downloaded = [
                str((entry.get("with") or {}).get("name", ""))
                for entry in job.get("steps") or []
                if "download-artifact" in str(entry.get("uses", ""))
            ]
            if not any(artifact.startswith("carry-") and artifact in downloaded
                       for artifact in uploaded):
                uncarried.append(f"{name} takes nothing {before} carried: {downloaded}")

        step(1, f"find {first} needing the preconditions and the calibration check")
        assert not unopened, unopened

        step(2, "find each later band needing the band before it and running unless "
                "the preconditions or the calibration check failed")
        assert not unchained, unchained

        step(3, "find each later band taking the outcomes the band before it carried")
        assert not uncarried, uncarried

    @story("A live run takes one platform")
    def MQC_CAS_UNI_115839_a_regression_job_off_the_chosen_platform_is_reported(self) -> None:
        """Every job running the suite runs on the ``os`` input, which every caller offers.

        Design: ``consumer_ci.md`` section 7.8.3.

        Returns:
            None
        """
        regression = load(REGRESSION_RUN)
        declared = call_inputs(regression).get("os") or {}
        installing = [
            name for name, job in jobs(regression).items()
            if any("ap-harness-qc" in line for line in run_lines(job))
        ]
        elsewhere = [name for name in installing
                     if str(jobs(regression)[name].get("runs-on", "")) != _CHOSEN_OS]
        unoffered: list[str] = []
        for filename, caller in sorted(regression_callers().items()):
            offered = dispatch_inputs(caller).get("os") or {}
            passes = [str((job.get("with") or {}).get("os", "")) for job in jobs(caller).values()
                      if REGRESSION_RUN in str(job.get("uses") or "")]
            if offered.get("type") != "choice" or tuple(offered.get("options") or ()) != \
                    OFFERED_OS or offered.get("default") != DEFAULT_OS or \
                    not all("inputs.os" in value for value in passes):
                unoffered.append(f"{filename}: offers {offered}, passes {passes}")

        step(1, f"find the regression run declaring an os input defaulting to {DEFAULT_OS}")
        assert declared.get("default") == DEFAULT_OS, declared

        step(2, "find every job installing the harness on the chosen platform")
        assert installing and not elsewhere, (installing, elsewhere)

        step(3, "find every caller offering the two platforms and passing the choice")
        assert regression_callers() and not unoffered, unoffered

    @story("One ceiling for the whole regression run")
    def MQC_CAS_UNI_115840_a_live_band_spending_the_whole_input_is_reported(self) -> None:
        """Every live band spends the remainder the earlier live bands left, never the input.

        Design: ``consumer_ci.md`` section 7.8.4.

        Returns:
            None
        """
        regression = jobs(load(REGRESSION_RUN))
        uncounted: list[str] = []
        whole: list[str] = []
        unpublished: list[str] = []
        for position, name in enumerate(LIVE_BANDS):
            job = regression.get(name, {})
            counted = [
                entry for entry in steps_running(job, _SPEND_TOOL)
                if entry.get("id") == "spend"
                and flag_value(str(entry.get("run")), "--earlier") == str(position)
                and flag_value(str(entry.get("run")), "--ceiling") == "${{ inputs.max_spend }}"
            ]
            if len(counted) != 1:
                uncounted.append(f"{name}: {[entry.get('run') for entry in counted]}")
            if _REMAINDER not in band_inputs(job).get("max_spend", ""):
                whole.append(f"{name}: {band_inputs(job).get('max_spend')!r}")
            published = [
                entry for entry in job.get("steps") or []
                if "upload-artifact" in str(entry.get("uses", ""))
                and str((entry.get("with") or {}).get("name", "")).startswith("spend-")
            ]
            if not published:
                unpublished.append(name)

        step(1, "find each live band counting the live bands before it against the ceiling")
        assert not uncounted, uncounted

        step(2, "find each live band spending the remainder rather than the input")
        assert not whole, whole

        step(3, "find each live band publishing its report for the bands after it")
        assert not unpublished, unpublished

    @story("A missing spend report skips the band's cases")
    def MQC_CAS_UNI_115881_a_declared_spend_report_reaches_every_band_and_its_cases(
        self,
    ) -> None:
        """Each live band passes the declaration on, as --missing-artifact, to a skipping hook.

        Design: ``consumer_ci.md`` section 7.8.4.

        Returns:
            None
        """
        regression = jobs(load(REGRESSION_RUN))
        unpassed = [
            f"{name}: {band_inputs(regression.get(name, {})).get(_DECLARED_INPUT)!r}"
            for name in LIVE_BANDS
            if _DECLARED_OUTPUT not in band_inputs(regression.get(name, {})).get(
                _DECLARED_INPUT, "")
        ]
        action = yaml.safe_load(
            (repository_root() / ".github" / "actions" / "band" / "action.yml").read_text(
                encoding="utf-8")
        )
        running = [
            entry for entry in (action.get("runs") or {}).get("steps") or []
            if "pytest" in str(entry.get("run") or "")
        ]
        undeclared = _DECLARED_INPUT not in (action.get("inputs") or {}) or not any(
            str((entry.get("env") or {}).get(_DECLARED_ENV)) ==
            f"${{{{ inputs.{_DECLARED_INPUT} }}}}"
            and _DECLARED_FLAG in str(entry.get("run")) for entry in running
        )
        hooked = top_level_calls(repository_root() / "conftest.py", _DECLARED_FIXTURE)

        step(1, "find each live band passing the spend step's declaration to the band")
        assert not unpassed, unpassed

        step(2, "find the band action passing a set declaration to pytest as --missing-artifact")
        assert not undeclared, [entry.get("run") for entry in running]

        step(3, "find the conftest's autouse fixture setting up the run's provenance, "
                "then skipping the cases a declaration covers")
        assert {"getfixturevalue", "enforce_dependencies", "skip_declared_missing"} <= hooked, \
            sorted(hooked)
