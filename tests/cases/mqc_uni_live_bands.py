    @story("The ladder is banded as the gate is")
    def MQC_CAS_UNI_115837_a_ladder_rung_not_banded_as_the_gate_is_reported(self) -> None:
        """Each rung is three band jobs with the rung's modes, named rung and engine first.

        Design: ``consumer_ci.md`` sections 7.8.1 and 7.8.5.

        Returns:
            None
        """
        root = repository_root()
        ladder = jobs(load(LADDER))
        missing = [name for rung in RUNGS.values() for name in rung["jobs"]
                   if name not in ladder]
        unbanded: list[str] = []
        moded: list[str] = []
        named: list[str] = []
        for rung in RUNGS.values():
            for name, expected in zip(rung["jobs"], BANDS):
                job = ladder.get(name, {})
                passed = band_inputs(job)
                if tuple(passed.get(key) for key in ("band", "priority", "blocking")) != expected:
                    unbanded.append(f"{name}: {passed}")
                line = band_invocation(job, root)
                if (flag_value(line, "--mode"), flag_value(line, "--judge-mode")) != (
                        rung["mode"], rung["judge_mode"]):
                    moded.append(f"{name}: {line.strip()}")
                if not str(job.get("name", "")).startswith(f"{rung['name']}, {expected[0]}"):
                    named.append(f"{name}: {job.get('name')!r}")
        unguarded = [
            f"{workflow.name}:{name}"
            for workflow in sorted(WORKFLOWS.glob("*.yml"))
            for name, job in jobs(load(workflow.name)).items()
            if any(flag_value(line, "--mode") == "live"
                   or flag_value(line, "--judge-mode") == "live"
                   for line in run_lines(job, root))
            and job.get("environment") != _LIVE_ENVIRONMENT
        ]

        step(1, "find all nine band jobs in the ladder")
        assert not missing, missing

        step(2, "find each band job calling the band definition at its band and floor")
        assert not unbanded, unbanded

        step(3, "find each band invocation passing its rung's candidate and judge modes")
        assert not moded, moded

        step(4, "find each band job named for its rung and engine, then its band")
        assert not named, named

        step(5, f"find every job running a case live naming the {_LIVE_ENVIRONMENT!r} environment")
        assert not unguarded, unguarded

    @story("The ladder is banded as the gate is")
    def MQC_CAS_UNI_115838_a_rung_that_runs_past_a_red_rung_below_is_reported(
        self,
    ) -> None:
        """Bands chain within a rung; the first band of a rung needs every band below.

        Design: ``consumer_ci.md`` section 7.8.2.

        Returns:
            None
        """
        ladder = jobs(load(LADDER))
        unchained: list[str] = []
        uncarried: list[str] = []
        unstopped: list[str] = []
        below: tuple[str, ...] = ()
        for rung in RUNGS.values():
            first, *later = rung["jobs"]
            job = ladder.get(first, {})
            if not set(below) | {"preconditions"} <= set(needs(job)) or job.get("if"):
                unstopped.append(f"{first}: needs {needs(job)}, if {job.get('if')!r}")
            for before, name in zip(rung["jobs"], later):
                job = ladder.get(name, {})
                if not {before, "preconditions"} <= set(needs(job)) or \
                        str(job.get("if", "")) != _CHAINED:
                    unchained.append(f"{name}: needs {needs(job)}, if {job.get('if')!r}")
                uploaded = [
                    str((entry.get("with") or {}).get("name", ""))
                    for entry in ladder.get(before, {}).get("steps") or []
                    if "upload-artifact" in str(entry.get("uses", ""))
                ]
                downloaded = [
                    str((entry.get("with") or {}).get("name", ""))
                    for entry in job.get("steps") or []
                    if "download-artifact" in str(entry.get("uses", ""))
                ]
                if not any(name_ and name_.startswith("carry-") and name_ in downloaded
                           for name_ in uploaded):
                    uncarried.append(f"{name} takes nothing {before} carried: {downloaded}")
            below = rung["jobs"]

        step(1, "find each later band needing the band before it and running unless the "
                "preconditions failed")
        assert not unchained, unchained

        step(2, "find each later band taking the outcomes the band before it carried")
        assert not uncarried, uncarried

        step(3, "find the first band of each rung needing every band of the rung below")
        assert not unstopped, unstopped

    @story("A live run takes one platform")
    def MQC_CAS_UNI_115839_a_ladder_job_off_the_chosen_platform_is_reported(self) -> None:
        """Every job running the suite runs on the ``os`` input, which every caller offers.

        Design: ``consumer_ci.md`` section 7.8.3.

        Returns:
            None
        """
        ladder = load(LADDER)
        declared = call_inputs(ladder).get("os") or {}
        installing = [
            name for name, job in jobs(ladder).items()
            if any("ap-harness-qc" in line for line in run_lines(job))
        ]
        elsewhere = [name for name in installing
                     if str(jobs(ladder)[name].get("runs-on", "")) != _CHOSEN_OS]
        unoffered: list[str] = []
        for filename, caller in sorted(ladder_callers().items()):
            offered = dispatch_inputs(caller).get("os") or {}
            passes = [str((job.get("with") or {}).get("os", "")) for job in jobs(caller).values()
                      if LADDER in str(job.get("uses") or "")]
            if offered.get("type") != "choice" or tuple(offered.get("options") or ()) != \
                    OFFERED_OS or offered.get("default") != DEFAULT_OS or \
                    not all("inputs.os" in value for value in passes):
                unoffered.append(f"{filename}: offers {offered}, passes {passes}")

        step(1, f"find the ladder declaring an os input defaulting to {DEFAULT_OS}")
        assert declared.get("default") == DEFAULT_OS, declared

        step(2, "find every job installing the harness on the chosen platform")
        assert installing and not elsewhere, (installing, elsewhere)

        step(3, "find every caller offering the two platforms and passing the choice")
        assert ladder_callers() and not unoffered, unoffered

    @story("One ceiling for the whole ladder")
    def MQC_CAS_UNI_115840_a_live_band_spending_the_whole_input_is_reported(self) -> None:
        """Every live band spends the remainder the earlier live bands left, never the input.

        Design: ``consumer_ci.md`` section 7.8.4.

        Returns:
            None
        """
        ladder = jobs(load(LADDER))
        uncounted: list[str] = []
        whole: list[str] = []
        unpublished: list[str] = []
        for position, name in enumerate(LIVE_BANDS):
            job = ladder.get(name, {})
            counted = [
                entry for entry in steps_running(job, _SPEND_TOOL)
                if entry.get("id") == "spend"
                and flag_value(str(entry.get("run")), "--earlier") == str(position)
                and flag_value(str(entry.get("run")), "--ceiling") == "${{ inputs.max_spend }}"
            ]
            if len(counted) != 1:
                uncounted.append(f"{name}: {[entry.get('run') for entry in counted]}")
            if _REMAINDER not in band_inputs(job).get("max_spend", ""):
                whole.append(f"{name}: {band_inputs(job).get('max_spend')!r}")
            published = [
                entry for entry in job.get("steps") or []
                if "upload-artifact" in str(entry.get("uses", ""))
                and str((entry.get("with") or {}).get("name", "")).startswith("spend-")
            ]
            if not published:
                unpublished.append(name)

        step(1, "find each live band counting the live bands before it against the ceiling")
        assert not uncounted, uncounted

        step(2, "find each live band spending the remainder rather than the input")
        assert not whole, whole

        step(3, "find each live band publishing its report for the bands after it")
        assert not unpublished, unpublished

    @story("Calibration is the judge's")
    def MQC_CAS_UNI_115844_a_live_band_without_the_calibration_record_is_reported(
        self,
    ) -> None:
        """Every judged band reads its judge's record, and no band selects calibration.

        Design: ``consumer_ci.md`` section 7.4.5.

        Returns:
            None
        """
        root = repository_root()
        ladder = jobs(load(LADDER))
        unread: list[str] = []
        unfetched: list[str] = []
        for name in LIVE_BANDS:
            job = ladder.get(name, {})
            named = flag_value(band_invocation(job, root), "--calibration-record")
            if not named:
                unread.append(f"{name}: {band_invocation(job, root).strip()}")
                continue
            fetched = [
                entry for entry in steps_running(job, f"FETCH_HEAD:{RECORD_PATH}")
                if named in str(entry.get("run"))
            ]
            if not fetched:
                unfetched.append(f"{name} reads {named} and takes no record into it")
        replayed = [
            name for name in RUNGS["deterministic"]["jobs"]
            if flag_value(band_invocation(ladder.get(name, {}), root), "--calibration-record")
        ]
        selecting = [
            name for rung in RUNGS.values() for name in rung["jobs"]
            if flag_value(band_invocation(ladder.get(name, {}), root), "-m") != _BAND_MARKERS
        ]

        step(1, "find every live band naming a calibration record")
        assert not unread, unread

        step(2, "find each record taken from the default branch for the ladder's judge")
        assert not unfetched, unfetched

        step(3, "find no replayed band naming a record")
        assert not replayed, replayed

        step(4, f"find every band selecting {_BAND_MARKERS!r} and no calibration")
        assert not selecting, selecting
