    @story("A quarantined foundation is set aside")
    def MQC_CAS_UNI_115870_a_quarantined_foundation_is_set_aside_for_every_band(
        self,
    ) -> None:
        """Every held case's number is set aside, whether or not this band dropped it.

        Design: ``consumer_ci.md`` section 4.14.2.

        Returns:
            None
        """
        numbers = held_case_numbers(_PAIRS, frozenset({_FOUNDATION_CASE}))
        calls = top_level_calls(
            repository_root() / "tests/cases/quarantine_support.py",
            "deselect_quarantined_cases",
        )

        step(1, "find the held case's number among the set-aside foundations")
        assert numbers == frozenset({_FOUNDATION}), numbers

        step(2, "find collection setting the held cases aside outside the drop branch")
        assert {"set_aside_foundations", "held_case_numbers"} <= calls, sorted(calls)

    @story("A dependent that passed raises a question")
    def MQC_CAS_UNI_115871_a_dependent_passing_on_a_quarantined_foundation_is_reported(
        self,
    ) -> None:
        """Only a call-phase pass resting on a set-aside foundation is reported.

        Design: ``consumer_ci.md`` section 4.14.2.

        Returns:
            None
        """
        reset_dependency_state()
        clear_foundation_questions()
        set_aside_foundations([_FOUNDATION])
        resting = dependent_item(_DEPENDENT_NAME, _FOUNDATION)
        note_foundation_question(resting, SimpleNamespace(when="call", passed=True))
        note_foundation_question(resting, SimpleNamespace(when="call", passed=False))
        note_foundation_question(resting, SimpleNamespace(when="setup", passed=True))
        note_foundation_question(
            dependent_item("MQC_EVL_SEC_154105_elsewhere", "154101"),
            SimpleNamespace(when="call", passed=True),
        )
        questions = foundation_questions()
        clear_foundation_questions()
        reset_dependency_state()
        hooks = called_names(repository_root() / "conftest.py")

        step(1, "find one question, about the passing dependent and its foundation")
        assert questions == [
            f"Investigate the foundation: {_DEPENDENT_NAME} passed while its "
            f"foundation {_FOUNDATION} is quarantined"
        ], questions

        step(2, "find the session noting each report and printing the questions")
        assert {"note_foundation_question", "foundation_questions"} <= hooks, sorted(hooks)

    @story("The tool offers, and the default is no")
    def MQC_CAS_UNI_115872_the_tool_adds_no_dependent_unless_asked(self) -> None:
        """Without ``--with-dependents`` the tool lists a dependent left in and adds nothing.

        Design: ``consumer_ci.md`` section 4.14.2.

        Returns:
            None
        """
        added, listed = plan_dependents([_ENTRY], _PAIRS, _GRAPH, frozenset())
        parsed = build_parser().parse_args(["--engine", "gemini", "--as-of", "2026-11-16"])
        graph = declared_dependents(repository_root() / "tests" / "cases")

        step(1, "find no entry added")
        assert not added, added

        step(2, "find the dependent left in listed as running and counting")
        assert (
            len(listed) == 1 and _DEPENDENT_NAME in listed[0]
            and "runs and counts" in listed[0]
        ), listed

        step(3, "find the flag empty unless given")
        assert parsed.with_dependents == [], parsed.with_dependents

        step(4, "find the suite's declared dependents read from the case modules")
        assert any(
            name.startswith("MQC_") for name in graph.get("134000", [])
        ), sorted(graph)

    @story("The tool quarantines what it is asked to")
    def MQC_CAS_UNI_115873_the_tool_quarantines_the_dependents_it_is_asked_for(
        self,
    ) -> None:
        """A named foundation's dependent is added with its ticket, dates and flag.

        Design: ``consumer_ci.md`` section 4.14.2.

        Returns:
            None
        """
        added, listed = plan_dependents([_ENTRY], _PAIRS, _GRAPH, frozenset({_FOUNDATION}))
        already = QuarantineEntry(
            case_id=_DEPENDENT_CASE, reason="own failure", quarantined_on=_HELD_ON,
            ticket="MQC-42",
        )
        again, _ = plan_dependents(
            [_ENTRY, already], _PAIRS, _GRAPH, frozenset({_FOUNDATION})
        )

        step(1, "find one entry added, for the dependent")
        assert [entry.case_id for entry in added] == [_DEPENDENT_CASE], added

        step(2, "find it carrying the foundation's ticket, dates, model and flag")
        entry = added[0]
        assert (
            entry.ticket, entry.quarantined_on, entry.originally_quarantined_on,
            entry.observed_model, entry.ends_on_model_change,
        ) == ("MQC-41", _HELD_ON, _FIRST_HELD, "model-under-test", False), entry

        step(3, "find its reason naming the foundation and no release copied")
        assert (entry.reason, entry.release_accepted_in) == (
            f"its foundation {_FOUNDATION} is quarantined", ""
        ), entry

        step(4, "find nothing listed and an already quarantined dependent not added twice")
        assert not listed and not again, (listed, again)

    @story("No skip releases a blocking band")
    def MQC_CAS_UNI_115874_a_blocking_band_skip_is_never_released(
        self, tmp_path: Path,
    ) -> None:
        """A skip blocks its band, and the band check reads no release decision.

        Design: ``consumer_ci.md`` section 3.12.5.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        report = tmp_path / "band.xml"
        report.write_text(
            "<testsuite>"
            + '<testcase name="MQC_EVL_SEC_154000_alpha"/>' * 10
            + '<testcase name="MQC_EVL_SEC_154099_parked">'
              '<skipped message="QC_HARNESS_QUARANTINED: parked"/></testcase>'
            + "</testsuite>",
            encoding="utf-8",
        )
        code, message = assess_blocking(report, frozenset({"154099"}))
        parameters = inspect.signature(assess_blocking).parameters
        named = called_names(repository_root() / "tools/band_floor.py")

        step(1, "find a quarantined skip blocking the band")
        assert code != 0, message

        step(2, "find the band check taking no release decision")
        assert "dispensed" not in parameters, list(parameters)
        assert "released_by_dispensation" not in named, "the band check reads a release"
