"""Unit precondition for the creation and update dates every module docstring here carries.

Created: 2026-10-21
Last updated: 2026-10-30

The case here runs the harness's ``cmn.file_dates.file_date_problems`` against
this repository: every Python file's docstring carries ``Created:`` and
``Last updated:`` under its purpose line, each a real date in order and none in
the future, and a file edited since its last commit has its date moved on. A
planted undated module confirms the check reports what it should before the
repository is read.

It runs in the ``unit`` gate ahead of every graded band, so a file added without
its dates, or edited without running the harness's ``tools/refresh_file_dates.py``
with ``--root``, fails the build naming the file. A failure here is an
instrument defect, not a model finding.

Specified by the harness ``.claude/rules/code-style.md`` section 3.1.2.
"""

# ------------------------------------------------------------- cases in here
# Generated by `tools/refresh_case_summaries.py`.
#
# TestMQCFileDates
#   115773  a_file_date_line_missing_or_stale_is_reported
# ------------------------------------------------------------ end of cases

from pathlib import Path

import pytest

from cmn.case_steps import step
from cmn.file_dates import file_date_problems
from cmn.project_clock import project_today

from tests.cases.graded_support import repository_root

pytestmark = pytest.mark.unit


class TestMQCFileDates:
    """Every module here says when it was created and last updated."""

    def MQC_CAS_UNI_115773_a_file_date_line_missing_or_stale_is_reported(
        self, tmp_path: Path
    ) -> None:
        """An undated module is reported, and this repository's files carry their dates.

        Design: harness ``code-style.md`` section 3.1.2.

        Returns:
            None
        """
        today = project_today()
        (tmp_path / "undated.py").write_text(
            '"""A planted module.\n\nWhat it holds.\n"""\n', encoding="utf-8"
        )

        step(1, "plant a module without its date lines")
        planted = file_date_problems(tmp_path, today)
        assert planted == [
            f"undated.py: the module docstring carries no '{label}:' line in its place, "
            f"the purpose line, a blank line, then Created and Last updated"
            for label in ("Created", "Last updated")
        ], f"an undated module was not reported for both lines: {planted}"

        step(2, "read this repository's own files")
        own = file_date_problems(repository_root(), today)
        assert not own, f"{len(own)} file date problem(s):\n  " + "\n  ".join(own[:12])
