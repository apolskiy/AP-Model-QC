from pathlib import Path
from typing import Final

import pytest

from cmn.grouping import DECLARATION, grouping_problems, load_grouping
from cmn.workflow_standards import report_publication_gaps

pytestmark = pytest.mark.unit

_ROOT: Final[Path] = Path(__file__).resolve().parents[2]

# THE EPIC THIS REPOSITORY PUBLISHES UNDER, which is the one thing about the
# grouping that must differ from the harness's.
_EPIC: Final[str] = "AP-Model-QC"


class TestMQCGroupingDeclaration:
    """Every collected module declares the capability it measures."""

    def MQC_CAS_UNI_430000_every_case_module_declares_its_capability(self) -> None:
        """The declaration agrees with this repository's test tree, both ways.

        Twenty-seven of this repository's thirty-nine modules named a
        capability by hand and twelve named none, so a report grouped two
        thirds of the suite and attributed the rest to nothing.

        Design: the harness ``harness_test_taxonomy.md`` section 16.3.

        Returns:
            None
        """
        reported = grouping_problems(_ROOT)
        assert not reported, (
            f"{len(reported)} disagreement(s) between {DECLARATION} and this "
            f"repository, so a published result groups under nothing or the map "
            f"names a module that is gone: {reported}"
        )


class TestMQCGroupingEpic:
    """The epic is this repository's own, not the harness's."""

    def MQC_CAS_UNI_430001_the_declared_epic_is_this_repositorys_own(self) -> None:
        """The epic names this repository, which is what separates two result sets.

        A collector reading both repositories tells them apart by the epic, so
        the two declarations carrying one value would make every result
        ambiguous about which suite produced it. The harness compares each
        against its own distribution name, which is what stops them drifting
        into agreement.

        Design: the harness ``harness_test_taxonomy.md`` section 16.5.

        Returns:
            None
        """
        declared = load_grouping(_ROOT).epic
        assert declared == _EPIC, (
            f"{DECLARATION} declares the epic {declared!r} rather than {_EPIC!r}, so "
            f"this repository's results are attributed to another suite"
        )


class TestMQCGroupingPublication:
    """The report is rendered and published, not only uploaded raw."""

    def MQC_CAS_UNI_430002_the_report_publishes_where_no_proposal_reaches(self) -> None:
        """One workflow renders the report and deploys it, and a pull request cannot.

        **Four targets gate on every push**, each in its own workflow, so a
        publishing job inside them would be four deploys racing and the site
        would hold whichever finished last. The publisher is its own workflow,
        triggered by their completion on the default branch.

        Design: the harness ``harness_ci_pipeline.md`` section 7.4.

        Returns:
            None
        """
        gaps = report_publication_gaps(_ROOT)
        assert not gaps, (
            f"{len(gaps)} gap(s) between this repository's workflows and what "
            f"section 7.4 states, so the readiness view is stale, absent, or a "
            f"proposal's: {gaps}"
        )
