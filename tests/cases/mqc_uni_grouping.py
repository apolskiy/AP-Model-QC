"""Unit preconditions for the grouping tree this repository's results are read by.

Created: 2026-10-24
Last updated: 2026-10-24

This file contains three cases, each calling a harness implementation over
this repository. ``TestMQCGroupingDeclaration`` checks that every collected
case module declares the capability it measures and that the declaration names
no module this repository does not hold; ``TestMQCGroupingEpic`` that the epic
is this repository's own rather than the harness's; and
``TestMQCGroupingPublication`` that the report is rendered and published from a
workflow no proposal can reach.

**These run in the ``unit`` precondition gate**, ahead of every graded band. A
failure is an instrument defect, **not a model finding**: the run exits 3 and
no graded case executes, so the module carries no priority marker, per the
harness ``framework-rules.md`` section 3.3.

**The harness cases prove the readers non-vacuous.** ``MQC_CMN_UNI_420000`` to
``420005`` plant a repository whose declaration is wrong in each of the ways
these readers report. This caller asserts the state of this repository, which
is the half the harness cannot see.

**Why it matters here more than there.** The harness publishes instrument
health; this repository publishes what a model is actually worth, grouped by
capability. A module that declares none would put graded results under no
capability at all, which is the one branch of the tree a reader of a readiness
report came for.

Specified by the harness ``harness_test_taxonomy.md`` section 16 and
``docs/design/consumer_ci.md`` section 4.22.
"""

