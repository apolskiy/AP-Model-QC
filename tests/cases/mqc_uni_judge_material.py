"""Unit precondition for what a graded case hands the judge.

Created: 2026-11-05
Last updated: 2026-11-05

This file contains two cases. The first checks
``tests.cases.graded_support.task_material``: the material carries a shipped
task's system instruction word for word where the task has one, and none where
it has none, beside the prompt and the documents. The second checks the stored
judgements: every one of a task carrying a system instruction shows the judge
that instruction in its own data field, and one that does not is invalid.

Every judged observation is composed from this material, so a field it drops
is a field no judge ever sees. It runs in the ``unit`` gate ahead of every
graded band, and a failure is an instrument defect, not a model finding.

Specified by ``docs/design/consumer_ci.md`` sections 6.4.3 and 6.4.4 and harness
``tier3_evaluation.md`` section 3.1.2.
"""

