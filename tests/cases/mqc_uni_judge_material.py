from typing import Final

import pytest

from cmn.case_steps import step

from tests.cases.graded_support import shipped_corpus, task_material
from tests.cases.judgement_store_support import judgements_without_instruction

pytestmark = pytest.mark.unit

_INSTRUCTED: Final[str] = "MQC_TASK_sec_direct_override"
_UNINSTRUCTED: Final[str] = "MQC_TASK_gnd_no_falsehood_unrounded"


class TestMQCJudgeMaterial:
    """What the judge is given about the task a response answered."""

    def MQC_CAS_UNI_115803_the_judge_is_given_the_system_instruction_the_candidate_was(
        self,
    ) -> None:
        """A shipped system instruction reaches the judge's material word for word.

        Design: consumer_ci.md section 6.4.3.

        Returns:
            None
        """
        tasks, _ = shipped_corpus()
        by_id = {task.task_id: task for task in tasks}
        instructed = by_id[_INSTRUCTED]
        uninstructed = by_id[_UNINSTRUCTED]

        step(1, "the chosen shipped task carries a system instruction")
        assert instructed.system_instruction, f"{_INSTRUCTED} carries no system instruction"

        step(2, "its material carries that instruction word for word")
        material = task_material(instructed, "A response.")
        assert material.system_instruction == instructed.system_instruction, (
            "the judge's material drops the system instruction the candidate was given"
        )

        step(3, "a task without one hands the judge none")
        assert (
            uninstructed.system_instruction,
            task_material(uninstructed, "A response.").system_instruction,
        ) == (None, None), "a task without a system instruction hands the judge one"

    def MQC_CAS_UNI_115804_a_judgement_not_shown_the_system_instruction_is_invalid(
        self,
    ) -> None:
        """Every stored judgement of an instructed task shows the judge its instruction.

        Design: consumer_ci.md section 6.4.4.

        Returns:
            None
        """
        judged, invalid = judgements_without_instruction()

        step(1, "the store holds judgements of tasks carrying a system instruction")
        assert judged, "no stored judgement of an instructed task, so nothing was checked"

        step(2, "each one's judge prompt carries that instruction in its own data field")
        assert not invalid, (
            f"{len(invalid)} of {judged} stored judgements of instructed tasks were "
            f"made without the system instruction and are invalid: {invalid[:5]}"
        )
