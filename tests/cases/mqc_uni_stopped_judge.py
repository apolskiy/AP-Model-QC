from types import SimpleNamespace
from typing import Any

import pytest

from cmn.case_steps import step

from tests.cases import graded_support
from tests.cases.consistency_support import assert_consistent_pass, unmeasured_code
from tests.cases.graded_support import case_for, judge_stopped, observe, observe_repeatedly
from tests.cases.instrument_support import SimulatedGradedConfig, dispatch_outcome

pytestmark = pytest.mark.unit

_TASK: str = "MQC_TASK_gnd_tolerance_permitted"
_RULE: str = "MQC_RULE_gnd_tolerance_permitted"
_REJECTED: str = "QC_HARNESS_REQUEST_REJECTED"


class TestMQCStoppedJudge:
    """A judge that stopped answering is reported as itself, and costs no candidate call."""

    def MQC_CAS_UNI_115814_a_stopped_judge_skips_a_judged_case_before_its_dispatch(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """A judged case skips with the judge's code and dispatches nothing.

        Design: ``consumer_ci.md`` section 6.4.5.

        Args:
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.

        Returns:
            None
        """
        recorded: list[Any] = []
        monkeypatch.setattr(
            graded_support, "_channel",
            lambda *args, **kwargs: SimpleNamespace(
                stopped=_REJECTED, engine="claude", invoke=None, args=(args, kwargs)),
        )
        monkeypatch.setattr(
            graded_support, "record_observation",
            lambda observation, *rest: recorded.append((observation, rest)),
        )

        def dispatched(*args: Any, **kwargs: Any) -> Any:
            """Refuse a dispatch, which a stopped judge must prevent.

            Args:
                *args (Any): Unused.
                **kwargs (Any): Unused.

            Returns:
                Any: Never returns.

            Raises:
                LookupError: Always, naming the dispatch.
            """
            raise LookupError(f"dispatched with {len(args) + len(kwargs)} arguments")

        monkeypatch.setattr(graded_support, "dispatch_case", dispatched)

        step(1, "ask whether the judge has stopped")
        judged = SimulatedGradedConfig("claude")
        assert judge_stopped(judged, "gemini") == _REJECTED, (
            "a stopped judge channel was reported as answering"
        )

        step(2, "observe a judged case whose judge has stopped")
        with pytest.raises(pytest.skip.Exception, match=_REJECTED):
            observe(judged, _TASK, _RULE)

        step(3, "read what the skip recorded")
        assert [
            (entry[0].skip_reason, entry[0].taxonomy_code) for entry in recorded
        ] == [("environmental", _REJECTED)], (
            f"recorded {recorded}, not one environmental skip carrying the judge's code"
        )

        step(4, "ask with the judge withheld")
        withheld = SimulatedGradedConfig("", judge_mode="off")
        assert judge_stopped(withheld, "gemini") is None, (
            "a withheld judge was reported as stopped"
        )

        step(5, "observe the same case with the judge withheld")
        with pytest.raises(LookupError, match="dispatched"):
            observe(withheld, _TASK, _RULE)

        step(6, "observe a rule carrying no rubric")
        shipped = case_for(_TASK, _RULE)
        monkeypatch.setattr(
            graded_support, "case_for",
            lambda task_id, rule_id: SimpleNamespace(
                case_id=shipped.case_id, task_id=task_id, rule_id=rule_id,
                golden_rules=SimpleNamespace(rubric=None)),
        )
        with pytest.raises(LookupError, match="dispatched"):
            observe(judged, _TASK, _RULE)

    def MQC_CAS_UNI_115815_an_unjudged_observation_earns_nothing_and_keeps_its_code(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """Unjudged observations draw no escalation and report the judge's code.

        Design: ``consumer_ci.md`` section 6.4.5.

        Args:
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.

        Returns:
            None
        """
        recorded: list[Any] = []
        unjudged = SimpleNamespace(
            case_id="x", passed=False, judge_skipped_reason="judgement_unavailable",
            taxonomy_codes=("QC_LLM_ASSERTION_FAILED", _REJECTED),
            assertion_results=(), judgement=None,
        )
        monkeypatch.setattr(
            graded_support, "_channel",
            lambda *args, **kwargs: SimpleNamespace(
                stopped=None, engine="claude", invoke=None, args=(args, kwargs)),
        )
        monkeypatch.setattr(
            graded_support, "dispatch_case",
            lambda *args, **kwargs: dispatch_outcome("gemini-4-argon", mode="replay"),
        )
        monkeypatch.setattr(
            graded_support, "evaluate_observation", lambda *args, **kwargs: unjudged
        )
        monkeypatch.setattr(
            graded_support, "record_observation",
            lambda observation, *rest: recorded.append(observation),
        )
        monkeypatch.setattr(
            graded_support, "record_observation_step", lambda *args, **kwargs: None
        )
        monkeypatch.setattr(
            graded_support, "record_remaining_steps", lambda *args, **kwargs: None
        )

        step(1, "observe three times with every judgement unavailable")
        results = observe_repeatedly(SimulatedGradedConfig("claude", 3), _TASK, _RULE)
        assert len(results) == 3, (
            f"{len(results)} observations taken, so unjudged observations were "
            f"counted as failures and earned further dispatches"
        )

        step(2, "read the code each observation recorded")
        assert {observation.taxonomy_code for observation in recorded} == {_REJECTED}, (
            f"recorded {sorted({obs.taxonomy_code for obs in recorded})}, not the "
            f"judge's own code"
        )

        step(3, "conclude the case")
        assert unmeasured_code(results) == _REJECTED, (
            f"the case concluded with {unmeasured_code(results)}, not the judge's code"
        )
        with pytest.raises(pytest.skip.Exception, match=_REJECTED):
            assert_consistent_pass(results)
