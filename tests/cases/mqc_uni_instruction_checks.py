import allure
import pytest

from evaluation.assertions import run_assertions
from tests.cases.graded_support import case_for

pytestmark = pytest.mark.unit

_WITHIN = "* The login page was restyled. The help link points to the new documentation."
_TWELVE = "* Twelve words exactly sit here and nothing more is said in it."
_THIRTEEN = "* The login page was restyled, and the help link points to new documentation."


class TestMQCInstructionChecks:
    """A word ceiling stated per sentence is checked per sentence."""

    @allure.story("Twelve words a sentence")
    def MQC_CAS_UNI_115749_a_two_sentence_bullet_under_the_ceiling_passes_word_check(
        self,
    ) -> None:
        """Two short sentences on one bullet pass; one thirteen-word sentence fails.

        Design: ``model_evaluation_test_plan.md`` section 9.3.3.

        Returns:
            None
        """
        for task, rule, check in (
            ("MQC_TASK_ins_quantities", "MQC_RULE_ins_word_ceiling", "A_INS_WORD_CEILING"),
            ("MQC_TASK_ins_combined", "MQC_RULE_ins_combined", "A_INS_COMBINED_WORDS"),
        ):
            assertions = [item for item in case_for(task, rule).golden_rules.assertions
                          if item.assertion_id == check]
            assert len(assertions) == 1, f"{check} not found once in {rule}"

            def held(text: str, chosen: list = assertions) -> bool:
                return all(result.passed for result in run_assertions(chosen, text))

            assert held(_WITHIN), f"{check} refuses two short sentences on one bullet"
            assert held(_TWELVE), f"{check} refuses a sentence of exactly twelve words"
            assert not held(_THIRTEEN), f"{check} accepts a thirteen-word sentence"
