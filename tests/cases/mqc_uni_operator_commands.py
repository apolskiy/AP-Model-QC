class TestMQCOperatorCommands:
    """That a command the runbook gives resolves against the pinned harness."""

    @story("The failure lister")
    def MQC_CAS_UNI_115791_the_harness_failure_lister_is_reachable_from_this_repository(
        self, tmp_path: Path
    ) -> None:
        """The harness entry point imports here and reads a planted report.

        Asserts that ``cmn.junit_outcomes`` is importable from this
        repository, that it separates the planted failure from the planted
        error, and that its command line returns zero on a readable report.
        **It asserts reachability, not behaviour**: what the tool does is
        ``MQC_CMN_UNI_112432``'s subject, and restating it here would be a
        second copy of that judgement.

        Args:
            tmp_path (Path): pytest's per-test directory, which is where the
                report is planted rather than anywhere in the repository
                (harness `code-style.md` section 8.0).

        Returns:
            None
        """
        report = tmp_path / "planted.xml"
        report.write_text(_REPORT, encoding=_ENCODING, newline="\n")

        failed, broken = outcomes(report)
        assert failed == ["pkg.mod.TestOne MQC_CAS_UNI_999001_fails"], (
            "QC_HARNESS_ASSERTION_FAILED: the harness lister reached from here "
            f"should name the failing case alone, got {failed}"
        )
        assert broken == ["pkg.mod.TestOne MQC_CAS_UNI_999002_breaks"], (
            "QC_HARNESS_ASSERTION_FAILED: the erroring case is named apart, "
            f"got {broken}"
        )
        assert main([str(report)]) == 0, (
            "QC_HARNESS_ASSERTION_FAILED: the command line the runbook gives "
            "returns zero on a report it could read"
        )
