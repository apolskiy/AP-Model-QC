    @story("The test case, step by step")
    def MQC_CAS_UNI_115805_a_ticket_states_the_test_case_step_by_step(self) -> None:
        """A ticket says what is sent, how often, what each response is held to and what passes.

        Design: ``consumer_ci.md`` section 9.5.5.13.

        Returns:
            None
        """
        task_id, rule_id = _DIAGNOSTICS
        task = load_tasks(ROOT)[task_id]
        rules = case_for(task_id, rule_id).golden_rules
        request = recorded_request(ROOT, "openai", task_id, rule_id)

        step(1, "state the steps of a case carrying a system instruction, a document and tools")
        steps = "\n".join(case_steps(task, rules, request, 5))
        assert f"One request is sent to `{request['model']}`" in steps, steps
        assert "a system instruction" in steps and "the document `DOC_status_runbook`" in steps, (
            f"the steps do not name what the request carries: {steps}"
        )
        assert "`lookup_service_status`" in steps and "`ping_host`" in steps, (
            f"the steps do not name the tools offered: {steps}"
        )
        assert "sent 5 times" in steps, f"the steps do not say how often: {steps}"
        assert all(line in steps for line in rule_lines(rules, task)), (
            f"the steps do not state the rule each response is held to: {steps}"
        )
        assert "passes only when every response" in steps, (
            f"the steps do not say what passing takes: {steps}"
        )

        step(7, "read the steps' place in a generated section")
        _, _, section = instructed_section("openai")
        assert section.index("**Problem:**") < section.index(
            "**The test case, step by step**") < section.index("**Request as sent**"), (
            "the steps are not between the problem and the request"
        )

    @story("The system instruction first")
    def MQC_CAS_UNI_115806_a_ticket_shows_the_system_instruction_first(self) -> None:
        """On every engine, the request as sent opens with the system instruction, word for word.

        Design: ``consumer_ci.md`` section 9.5.5.13.

        Returns:
            None
        """
        step(1, "generate a section for an instructed case on each engine")
        sections = {engine: instructed_section(engine) for engine in ("claude", "gemini",
                                                                       "grok", "openai")}
        assert all(case for case, _, _ in sections.values()), (
            f"an engine holds no recorded instructed case: "
            f"{[engine for engine, found in sections.items() if not found[0]]}"
        )

        step(2, "read the turn the request as sent opens with")
        misplaced = []
        for engine, (case, instruction, section) in sections.items():
            sent = section.split("**Request as sent**", 1)[1].split("**Responses", 1)[0]
            first_line = instruction.splitlines()[0]
            if not (sent.find("*System*") >= 0 and sent.find("*System*") < sent.find("*User*")
                    and sent.find(first_line) < sent.find("*User*")):
                misplaced.append(f"{engine} {case}")
        assert not misplaced, (
            f"the system instruction is absent or not first in the request as sent: {misplaced}"
        )

    @story("Reproduce without this repository")
    def MQC_CAS_UNI_115807_a_ticket_reproduces_without_the_repository(self) -> None:
        """The recorded body as request.json, posted from bash and PowerShell; gemini's SDK call.

        Design: ``consumer_ci.md`` section 9.5.5.13.

        Returns:
            None
        """
        pairs = case_rules_from_suite(ROOT)
        task_id, rule_id = _DIAGNOSTICS
        step(1, "reproduce a recorded call on each engine whose recording is its wire body")
        for engine in _WIRE_ENGINES:
            request = recorded_request(ROOT, engine, task_id, rule_id)
            block = "\n".join(reproduce_outside(engine, request, 3, 5))
            body = block.split("```json\n", 1)[1].split("\n```", 1)[0]
            assert json.loads(body) == request, f"{engine}'s request.json is not the recording"
            assert "--data-binary @request.json" in block and (
                '--data-binary "@request.json"' in block and "curl.exe " in block
            ), f"{engine} does not post request.json from both shells: {block}"
            assert "<<" not in block, f"{engine}'s reproduction carries a here-document"
            assert "Send it 5 times. The problem appeared on 3 of 5" in block, (
                f"{engine} does not say how often to send it: {block}"
            )
            # COPIED, KEY PASTED, RUN: the commands carry `<key>`, a line says
            # what replaces it, and nothing reads a variable the reader must set.
            adapter = adapter_for(engine)
            assert f"In each reply read {adapter.reproduction_reply_fields()}" in block and (
                "client." in block and _REPLACE_KEY in block and 'api_key="<key>"' in block
                and f"${adapter.API_KEY_ENV}" not in block
            ), (
                f"{engine} names no reply field, omits the SDK call, or is not a "
                f"command to paste a key into: {block}"
            )

        step(16, "reproduce gemini's recorded call, which has no REST form")
        block = "\n".join(reproduce_outside(
            "gemini", recorded_request(ROOT, "gemini", task_id, rule_id), 1, 3))
        assert "```json" not in block and "curl" not in block, (
            "gemini offers a curl although its recording is not the wire body"
        )
        assert "no REST form" in block and "client.models.generate_content(" in block, (
            f"gemini's reproduction does not say why it is the SDK call, or omits it: {block}"
        )
        # THE CAVEAT FOLLOWS THE COUNT: 1 of 3 may not show on one send, and 3
        # of 3 showed on every send, so it carries none.
        every = "\n".join(reproduce_outside(
            "gemini", recorded_request(ROOT, "gemini", task_id, rule_id), 3, 3))
        assert "Send it 3 times" in block and "`response.text`" in block and (
            _REPLACE_KEY in block and 'genai.Client(api_key="<key>")' in block
            and "may not show it" in block and "appeared on 3 of 3 attempts." in every
            and "may not show it" not in every
        ), (block, every)
        assert pairs, "the suite pairs no case with a task, so nothing was checked"

