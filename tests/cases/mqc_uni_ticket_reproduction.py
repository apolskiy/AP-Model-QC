    @story("One measured population")
    def MQC_CAS_UNI_115811_a_ticket_states_the_population_it_quotes(self) -> None:
        """The problem, the Population row and the filing sheet count the responses quoted.

        Design: ``consumer_ci.md`` section 9.5.5.13.

        Returns:
            None
        """
        step(1, "generate a section whose register entry states a population never measured")
        case, _, _ = instructed_section("openai")
        assert case, "no instructed case is recorded on openai, so nothing was checked"
        entry = {"case": case, "taxonomy_code": "QC_LLM_INSTRUCTION_VIOLATION",
                 "observed_model": "a-served-model-2026-01-01",
                 "observations": "17 of 23 passed"}
        section = "\n".join(finding_section(
            ROOT, "openai", entry, case_rules_from_suite(ROOT), load_tasks(ROOT)))
        sheet = filing_sheet("2026-11-05", {"openai": [entry]})
        assert "17 of 23" not in section and "17 of 23" not in sheet, (
            "the ticket or the filing sheet states the register's population"
        )

        step(3, "read the population against the responses quoted")
        quoted = re.search(r"The problem appeared on (\d+) of (\d+) attempts", section)
        stated = re.search(r"\| Population \| (\d+) of (\d+) passed \|", section)
        assert quoted and stated, f"the responses or the Population row give no count: {section}"
        failed, recorded = int(quoted.group(1)), int(quoted.group(2))
        passed, measured = int(stated.group(1)), int(stated.group(2))
        assert measured <= recorded and measured - passed == failed, (
            f"the Population row says {passed} of {measured} passed, and the "
            f"responses show {failed} of {recorded} failing"
        )
        assert f"{passed} of {measured} passed" in sheet, (
            f"the filing sheet does not state the measured population: {sheet}"
        )

        step(6, "say the failure was intermittent only where it was")
        intermittent = "some attempts and not others" in section
        assert intermittent == (0 < passed < measured), (
            f"the problem {'says' if intermittent else 'does not say'} the failure was "
            f"intermittent, with {passed} of {measured} passing"
        )
        task = load_tasks(ROOT)[_DIAGNOSTICS[0]]
        every = _issue_sentence({"taxonomy_code": "QC_LLM_TOOL_VIOLATION"}, task, (0, 5))
        some = _issue_sentence({"taxonomy_code": "QC_LLM_TOOL_VIOLATION"}, task, (3, 5))
        assert "some attempts" not in every and "(3 of 5 passed)" in some, (
            f"a failure on every attempt is called intermittent, or a partial one is "
            f"not: {every!r} / {some!r}"
        )
