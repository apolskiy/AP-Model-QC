"""Unit preconditions for a ticket that a vendor can reproduce without this repository.

Created: 2026-11-05
Last updated: 2026-11-06

This file contains ``TestMQCTicketReproduction``, five cases on
``tools/ticket_reproduction.py``, ``tools/ticket_responses.py`` and the
section ``tools/ticket_report.py`` assembles from them. They check a ticket
states its test case step by step, shows the system instruction before every
other turn, reproduces the recorded call without this repository from a
``request.json`` file in bash and PowerShell, reproduces the case live through
this repository, and places the judge's response in the body where the judge
decided the finding and in the appendix otherwise.

**These run in the ``unit`` precondition gate.** A ticket a vendor cannot
reproduce is closed as not a bug, so one that fails here sends a claim this
suite cannot support. A failure is an instrument defect, **not a model
finding**, and the module carries no priority marker, per the harness
``framework-rules.md`` section 3.3.

Specified by ``docs/design/consumer_ci.md`` section 9.5.5.13.
"""

