    @story("Where the judge's response goes")
    def MQC_CAS_UNI_115809_a_judge_that_decided_the_finding_is_in_the_body(self) -> None:
        """The judge's score and rationale stand in the body where it decided, else in the appendix.

        Design: ``consumer_ci.md`` section 9.5.5.13.

        Returns:
            None
        """
        step(1, "quote two responses the checks passed, the judge failing the first")
        body, appendix = responses_block(
            "openai", ["first answer", "second answer"], [(0, True, ""), (1, True, "")],
            [(False, 1.0, "FIRST RATIONALE"), (True, 4.0, "SECOND RATIONALE")],
            ["FIRST PROMPT", "SECOND PROMPT"],
        )
        shown, extra = "\n".join(body), "\n".join(appendix)
        assert "FIRST RATIONALE" in shown and "SECOND RATIONALE" in shown, (
            "the judge decided the finding and its rationale is not under the responses"
        )
        assert "PROMPT" not in shown and "Judge prompt, response 1 of 2" in extra, (
            "a judge prompt is in the body, or missing from the appendix"
        )
        assert "RATIONALE" not in extra, "the deciding judge's rationale is repeated"

        step(4, "quote a response its checks failed beside one the judge passed")
        body, appendix = responses_block(
            "openai", ["first answer", "second answer"],
            [(0, False, "A_X: matched"), (1, True, "")],
            [None, (True, 4.0, "SECOND RATIONALE")], ["", "SECOND PROMPT"],
        )
        shown, extra = "\n".join(body), "\n".join(appendix)
        assert "SECOND RATIONALE" not in shown and "in the appendix" in shown, (
            "the checks decided the finding and the judge's rationale is in the body"
        )
        assert "SECOND RATIONALE" in extra and "Judge prompt, response 2 of 2" in extra, (
            f"the judge's response or prompt is missing from the appendix: {extra}"
        )

        step(6, "quote responses no judge scored")
        assert not responses_block("openai", ["only"], [(0, False, "A_X: matched")])[1], (
            "an appendix was written where no judge scored anything"
        )

