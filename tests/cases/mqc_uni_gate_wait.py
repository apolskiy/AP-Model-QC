from tests.cases.live_band_support import REGRESSION_RUN

pytestmark = pytest.mark.unit


class TestMQCGateWait:
    """A regression run waits for its own commit's gate, and the gate never stops it."""

    @story("A regression run waits for its engine's gate")
    def MQC_CAS_UNI_115892_a_regression_run_waits_while_its_commits_gate_runs(self) -> None:
        """Queued, then in progress, then concluded: it waits twice and returns the conclusion.

        Design: ``consumer_ci.md`` section 7.9.6.

        Returns:
            None
        """
        result, asked, waited = simulated_wait([
            [gate_run("queued")],
            [gate_run("in_progress")],
            [gate_run("completed", "success")],
        ])

        step(1, "find the wait checking three times, at its commit, and waiting two intervals")
        assert (asked, waited) == ([COMMIT] * 3, 2 * INTERVAL_SEC), (asked, waited)

        step(2, "find it returning the gate's conclusion")
        assert result.conclusion == "success", result

    @story("A regression run waits for its engine's gate")
    def MQC_CAS_UNI_115893_a_gate_of_another_commit_or_engine_does_not_hold_it(self) -> None:
        """A running gate of a newer commit or of another engine leaves it unheld.

        Design: ``consumer_ci.md`` section 7.9.6.

        Returns:
            None
        """
        result, asked, waited = simulated_wait([[
            gate_run("in_progress", commit=OTHER_COMMIT),
            gate_run("in_progress", workflow="gate-gemini.yml"),
            gate_run("completed", "failure"),
        ]])

        step(1, "find the wait returning at once with its own gate's conclusion")
        assert (len(asked), waited, result.conclusion) == (1, 0.0, "failure"), (
            asked, waited, result)

    @story("A regression run waits for its engine's gate")
    def MQC_CAS_UNI_115894_an_unfinished_gate_ends_the_wait_at_thirty_minutes(self) -> None:
        """A gate never concluding, or never listed, ends the wait at thirty minutes, not before.

        Design: ``consumer_ci.md`` section 7.9.6.

        Returns:
            None
        """
        running, _, running_waited = simulated_wait([[gate_run("in_progress")]])
        absent, _, absent_waited = simulated_wait([[]])
        late, _, late_waited = simulated_wait(
            [*[[gate_run("in_progress")]] * 60, [gate_run("completed", "success")]])

        step(1, "find a gate in progress throughout ending the wait at thirty minutes")
        assert (running.conclusion, running_waited) == ("unfinished", TIMEOUT_SEC), (
            running, running_waited)

        step(2, "find a gate never listed ending it at thirty minutes too")
        assert (absent.conclusion, absent_waited) == ("absent", TIMEOUT_SEC), (
            absent, absent_waited)

        step(3, "find a gate concluding at thirty minutes still read, not cut off before")
        assert (late.conclusion, late_waited) == ("success", TIMEOUT_SEC), (late, late_waited)

    @story("A regression run waits for its engine's gate")
    def MQC_CAS_UNI_115895_a_red_or_cancelled_gate_is_noted_and_never_stops_it(
        self, tmp_path: Path,
    ) -> None:
        """A failed or cancelled gate exits 0, and its conclusion reaches the output and summary.

        Design: ``consumer_ci.md`` section 7.9.6.

        Args:
            tmp_path (Path): Where each run's output and summary are written.

        Returns:
            None
        """
        wrong: dict[str, object] = {}
        for conclusion in ("failure", "cancelled"):
            directory = tmp_path / conclusion
            directory.mkdir()
            status, output, summary = run_tool(directory, [gate_run("completed", conclusion)])
            if not (
                status == 0
                and f"gate_conclusion={conclusion}" in output.splitlines()
                and f"gate-{ENGINE}.yml" in summary and conclusion in summary
            ):
                wrong[conclusion] = (status, output, summary)

        step(1, "find each conclusion exiting 0 and named in the output and the summary")
        assert not wrong, wrong

    @story("A regression run waits for its engine's gate")
    def MQC_CAS_UNI_115896_the_regression_run_waits_for_its_gate_before_resolving(
        self,
    ) -> None:
        """``resolve`` waits on its engine's gate at ``github.sha`` for thirty minutes first.

        Design: ``consumer_ci.md`` section 7.9.6.

        Returns:
            None
        """
        steps = resolve_steps(REGRESSION_RUN)
        waits, pins = step_index(steps, WAIT_TOOL), step_index(steps, PIN_TOOL)
        command = str(steps[waits].get("run", "")) if waits >= 0 else ""

        step(1, "find resolve waiting before it resolves the harness")
        assert 0 <= waits < pins, (waits, pins)

        step(2, "find the wait naming the engine's gate, this commit and thirty minutes")
        assert all(
            part in command for part in (
                '--workflow "gate-${{ inputs.engine }}.yml"',
                '--commit "${{ github.sha }}"',
                "--timeout-minutes 30",
            )
        ), command

        step(3, "find no job or step condition reading the gate's conclusion")
        assert not [line for line in conditions(REGRESSION_RUN) if "gate_conclusion" in line]
