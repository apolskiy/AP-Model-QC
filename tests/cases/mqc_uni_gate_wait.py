"""Unit preconditions for the wait a regression run makes for its engine's gate.

Created: 2026-11-18
Last updated: 2026-11-18

This file contains ``TestMQCGateWait``, five cases over ``tools/gate_wait.py``
and the ``resolve`` job of ``evaluate-engine.yml``. A regression run waits
while its engine's gate at the commit it measures is queued, in progress or not
yet listed, for at most thirty minutes, and then proceeds whatever the gate
concluded, naming the conclusion; a gate of another commit or another engine
does not hold it.

**These run in the ``unit`` precondition gate.** A failure is an instrument
defect, **not a model finding**, and the module carries no priority marker,
per the harness ``framework-rules.md`` section 3.3. No case calls the GitHub
API: the runs and the clock are injected.

Specified by ``docs/design/consumer_ci.md`` section 7.9.6.
"""

