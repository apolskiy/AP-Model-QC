import allure
import pytest

from tests.cases.graded_support import case_for, repository_root
from tests.cases.suite_support import case_rules_from_suite
from tests.cases.priority_support import inventoried_priorities, marked_priorities

pytestmark = pytest.mark.unit


class TestMQCPriorityAgreement:
    """The band a case runs in is the band it is budgeted and filed under."""

    @allure.story("One priority, stated three times")
    def MQC_CAS_UNI_115747_a_priority_disagreeing_across_its_sources_is_reported(
        self,
    ) -> None:
        """Marker, rule and inventory row name one level and one condition.

        Design: ``model_evaluation_test_plan.md`` section 8.1.2.

        Returns:
            None
        """
        rows = inventoried_priorities()
        pairs = case_rules_from_suite(repository_root())
        problems: list[str] = []
        compared = 0
        for number, (name, marked) in sorted(marked_priorities().items()):
            task, rule = pairs.get(name, ("", ""))
            if not task:
                continue
            compared += 1
            rules = case_for(task, rule).golden_rules
            row = rows.get(number)
            if row is None:
                problems.append(f"{number} has no inventory row with a priority")
                continue
            level, condition = row
            if not marked == rules.priority == level:
                problems.append(
                    f"{number}: marker P{marked}, rule P{rules.priority}, row P{level}"
                )
            if condition not in rules.priority_conditions:
                problems.append(
                    f"{number}: row names {condition}, rule names {list(rules.priority_conditions)}"
                )

        assert compared, "no graded case was compared, so nothing is checked"
        assert not problems, "; ".join(problems)
