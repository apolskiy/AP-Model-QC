# WHICH LAYER EACH RULE FILE GRADES. The layer decides nothing about the
# measurement ceiling, which reaches every layer, and it is passed so a
# candidate built here is the candidate the suite would build rather than a
# shape that happens to satisfy the predicate.
_LAYER_BY_FILE: dict[str, str] = {"security": "SEC", "tool_compliance": "TOOL"}

pytestmark = pytest.mark.unit


class TestMQCPriorityAgreement:
    """The band a case runs in is the band it is budgeted and filed under."""

    @story("One priority, stated four times")
    def MQC_CAS_UNI_115747_a_priority_disagreeing_across_its_sources_is_reported(
        self,
    ) -> None:
        """Marker, rule, inventory row and vector table name one level and one condition.

        **The vector table joined the comparison on 2026-10-28.** Section
        9.10.2 states a priority beside each vector, and re-pricing sixteen
        cases would have left it stale with nothing reporting it, which is the
        defect section 8.1.2 was written for one case at a time.

        Design: ``model_evaluation_test_plan.md`` section 8.1.2.

        Returns:
            None
        """
        rows = inventoried_priorities()
        pairs = case_rules_from_suite(repository_root())
        problems: list[str] = vector_table_disagreements()
        compared = 0
        for number, (name, marked) in sorted(marked_priorities().items()):
            task, rule = pairs.get(name, ("", ""))
            if not task:
                continue
            compared += 1
            rules = case_for(task, rule).golden_rules
            row = rows.get(number)
            if row is None:
                problems.append(f"{number} has no inventory row with a priority")
                continue
            level, condition = row
            if not marked == rules.priority == level:
                problems.append(
                    f"{number}: marker P{marked}, rule P{rules.priority}, row P{level}"
                )
            if condition not in rules.priority_conditions:
                problems.append(
                    f"{number}: row names {condition}, rule names {list(rules.priority_conditions)}"
                )

        assert compared, "no graded case was compared, so nothing is checked"
        assert not problems, "; ".join(problems)


class TestMQCMeasurementCeiling:
    """Whether a run can block on a number the judge produced."""

    @story("A judged outcome does not block")
    def MQC_CAS_UNI_115784_a_shipped_rule_claiming_p0_or_p1_with_a_rubric_is_reported(
        self,
    ) -> None:
        """No shipped rule claims P0 or P1 while a rubric can decide its outcome.

        **The whole corpus is read, not the security family.** Sixteen of the
        twenty one rules this found were ``MQC_SEC_`` and five were ``EVAL``,
        and the exemption security carries is from the distribution ceilings
        rather than from the scale.

        Design: ``model_evaluation_test_plan.md`` section 8.1.3 and harness
        ``harness_test_taxonomy.md`` section 4.1.2.1.

        Returns:
            None
        """
        breaches: list[str] = []
        checked = 0
        for source in sorted((repository_root() / "data" / "rules").glob("*.yaml")):
            layer = _LAYER_BY_FILE.get(source.stem, "EVAL")
            for rule in load_rule_sets_from_yaml(source):
                checked += 1
                candidate = DemotionCandidate(
                    case_id=rule.rule_id,
                    layer=layer,
                    assigned_priority=rule.priority,
                    matched_conditions=list(rule.priority_conditions),
                )
                if exceeds_measurement_ceiling(
                    candidate, rubric_decides=rule.rubric is not None
                ):
                    breaches.append(f"{rule.rule_id} at P{rule.priority} in {source.name}")

        assert checked, "no rule was read, so nothing is checked"
        assert not breaches, (
            f"{len(breaches)} rule(s) carry a rubric at P0 or P1, so a judge "
            f"score at the threshold can block a run: {sorted(breaches)}. Price "
            f"each at P2 and add P2_RUBRIC_THRESHOLD beside the severity "
            f"condition it keeps"
        )

        # THE CASE IS NOT VACUOUS, which it would be if no shipped rule carried
        # a rubric at all. Twenty one did when this was written and the whole
        # point is that they moved to P2 rather than that the predicate never
        # fires.
        demotable = [
            rule
            for source in sorted((repository_root() / "data" / "rules").glob("*.yaml"))
            for rule in load_rule_sets_from_yaml(source)
            if rule.rubric is not None
        ]
        assert demotable, (
            "no shipped rule carries a rubric, so the ceiling is satisfied by "
            "an empty population and this case asserts nothing"
        )
