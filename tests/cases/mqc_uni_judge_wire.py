import pytest

from cmn.case_steps import step
from cmn.grouping import story

from tests.cases.graded_support import judge_binding
from tests.cases.instrument_support import SimulatedGradedConfig

pytestmark = pytest.mark.unit


class TestMQCJudgeWireAttempts:
    """The judge that graded hands the report its HTTP attempts."""

    @story("Judge attempts reach the report")
    def MQC_CAS_UNI_115906_a_judge_binding_dropping_its_wire_attempts_is_reported(
        self,
    ) -> None:
        """A bound judge's ``wire_attempts`` reads its own channel; a withheld one has none.

        Design: ``consumer_ci.md`` section 4.13.2.

        Returns:
            None
        """
        step(1, "bind the configured judge and read its wire_attempts")
        binding = judge_binding(SimulatedGradedConfig(""), "gemini")
        taker = binding.wire_attempts
        assert taker is not None, "the bound judge hands the report no wire attempts"

        step(2, "read whether it is the take_wire_attempts of the channel that grades")
        owner = getattr(binding.invoke, "__self__", None)
        assert (getattr(taker, "__self__", None) is owner, getattr(taker, "__name__", "")) == (
            True, "take_wire_attempts"), (owner, taker)

        step(3, "take the attempts of a judge that has not been asked")
        assert taker() == (), taker()

        step(4, "bind a withheld judge and read its wire_attempts")
        withheld = judge_binding(SimulatedGradedConfig("", judge_mode="off"), "gemini")
        assert withheld.wire_attempts is None, withheld.wire_attempts
