from pathlib import Path

import allure
import pytest

from cmn.document_citations import duplicate_sections, unresolved_citations
from cmn.document_standards import changelog_problems

pytestmark = pytest.mark.unit

_ROOT = Path(__file__).resolve().parents[2]


class TestMQCDocumentCitations:
    """The harness's citation checks, run against this repository."""

    @allure.story("A citation resolves or it is not a citation")
    def MQC_CAS_UNI_115734_an_unresolved_or_duplicated_citation_is_reported(
        self,
    ) -> None:
        """Every citation here resolves, and no section is numbered twice.

        **The reader is proved non-vacuous by the harness case**, which builds
        a tree carrying both defects and confirms each is reported. This caller
        asserts the state of this repository, which is the half the harness
        cannot see: it owns no case data and a check here reading a file the
        harness owns would be the same violation in reverse.

        Returns:
            None
        """
        unresolved = unresolved_citations(_ROOT)
        assert not unresolved, (
            f"{len(unresolved)} citation(s) resolve to nothing, so a reader is "
            f"sent somewhere and finds nothing: {unresolved}"
        )

        duplicated = duplicate_sections(_ROOT)
        assert not duplicated, (
            f"{len(duplicated)} document(s) number a section twice, so two "
            f"citations of one number mean different things: {duplicated}"
        )

    @allure.story("A README change carries a changelog entry")
    def MQC_CAS_UNI_115735_a_readme_without_a_changelog_is_reported(self) -> None:
        """This repository holds a changelog beside its README.

        **It did not until 2026-10-12**, while its README figures moved
        repeatedly: the recorded-response count, the finding totals and the
        precondition count. Each is a fact about a measurement, and the record
        of when it changed was `CLAUDE_LOG.md` alone, which is a narrative
        rather than a version history.

        Design: the harness ``code-style.md`` section 7.4.

        Returns:
            None
        """
        reported = changelog_problems(_ROOT)
        assert not reported, (
            f"the README has no changelog beside it, so a figure that moves "
            f"there leaves no record of when it moved or why: {reported}"
        )
