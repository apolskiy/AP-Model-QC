from pathlib import Path

import pytest

from cmn.grouping import story

from cmn.document_standards import (
    _collisions,
    documents_stating_an_inventory,
    duplicate_case_bindings,
    duplicate_inventory_bindings,
    inventory_count_problems,
)

pytestmark = pytest.mark.unit


class TestMQCStatedInventory:
    """This repository's design states an inventory its own rows support."""

    @story("A stated total is derived data")
    def MQC_CAS_UNI_115723_a_stated_inventory_disagreeing_with_rows_is_reported(
        self,
    ) -> None:
        """The same comparison the harness makes, against this repository.

        **This closes the open question `consumer_ci.md` section 4 recorded.**
        The harness had `MQC_CMN_UNI_112203` and this repository had no
        equivalent, so its stated figure drifted to 52 against 48 rows: five
        cases were added with the count incremented and no row written, and
        nothing compared the two.

        **One implementation, two callers**, which is the arrangement every
        other shared standard here uses: a copy would drift toward whichever
        repository was edited less often.

        Returns:
            None
        """
        design_dir = Path(__file__).resolve().parents[2] / "docs" / "design"
        stating = documents_stating_an_inventory(design_dir)
        assert stating, (
            "no design here states an inventory, so this check would report "
            "agreement having read nothing"
        )

        problems = inventory_count_problems(design_dir)
        assert not problems, (
            f"{len(problems)} design(s) state an inventory their own rows "
            f"contradict: " + "; ".join(problems)
        )


class TestMQCIdentifierBinding:
    """An identifier is assigned once here, in the register and in the suite."""

    @story("A per-row check cannot see a relationship between two rows")
    def MQC_CAS_UNI_115732_an_identifier_bound_twice_is_reported(self) -> None:
        """Five identifiers were bound twice here for a week.

        **Every per-row check passed while they were.** Each is keyed on a row
        or a callable, and the defect is a relationship between two of them:
        the inventory check found both rows, the trace check found both names
        valid, and the count check saw a row count that had genuinely grown.

        **The harness had `MQC_CMN_UNI_112226` and this repository had
        nothing**, in either direction, which is the asymmetry that let the
        collisions accumulate. The reader is shared now and called with each
        root.

        Design: ``consumer_ci.md`` section 4.

        Returns:
            None
        """
        root = Path(__file__).resolve().parents[2]

        inventory = duplicate_inventory_bindings(root / "docs" / "design")
        assert not inventory, (
            "an identifier is assigned once and never reused, so two live rows "
            "for one identifier rebind it to different behaviour: "
            + "; ".join(inventory)
        )

        suite = duplicate_case_bindings(root)
        assert not suite, (
            "two collected cases carry one identifier, so stored history "
            "resolves it to whichever behaviour a reader guesses: "
            + "; ".join(suite)
        )

        # NOT VACUOUS: the reader finds a collision this case plants, so a
        # passing run means it read the register and the suite rather than
        # finding neither.
        planted = {"115999": ["one", "two"], "115998": ["only"]}
        assert _collisions(planted) == [
            "115999 is bound to one and two"
        ], _collisions(planted)
