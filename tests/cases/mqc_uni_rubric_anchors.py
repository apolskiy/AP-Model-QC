import pytest

from cmn.case_steps import step
from cmn.grouping import story

from tests.cases.rubric_anchor_support import floor_rubric, judge_prompt

pytestmark = pytest.mark.unit


class TestMQCRubricAnchors:
    """Each level of the floor rubric tells the judge what the owner ruled it means."""

    @story("Level 3, a mismatch without its reason")
    def MQC_CAS_UNI_115027_the_floor_judge_scores_a_bare_mismatch_at_three(self) -> None:
        """Level 3 tells the judge a mismatch stated without explaining why scores there.

        Design: ``model_evaluation_test_plan.md`` section 9.13.1.

        Returns:
            None
        """
        case, criterion = floor_rubric()
        level_three = criterion.anchors[3].description

        step(1, "read level 3 of the floor rubric")
        assert "a mismatch without explaining why" in level_three, (
            f"level 3 does not place a mismatch stated without its reason: {level_three!r}"
        )

        step(2, "build the judge prompt for a bare mismatch")
        prompt = judge_prompt(case, "The candidate does not meet the 9 year requirement.")
        assert level_three in prompt, "the judge is not given level 3 as the rubric states it"

    @story("Level 3, the reason without concluding a mismatch")
    def MQC_CAS_UNI_115028_the_floor_judge_scores_an_unconcluded_reason_at_three(
        self,
    ) -> None:
        """Level 3 tells the judge an insufficiency not concluded as a mismatch scores there.

        Design: ``model_evaluation_test_plan.md`` section 9.13.1.

        Returns:
            None
        """
        case, criterion = floor_rubric()
        level_three = criterion.anchors[3].description

        step(1, "read level 3 of the floor rubric")
        assert "insufficient without stating that, as it stands, it is a mismatch" in (
            level_three
        ), f"level 3 does not place an insufficiency left unconcluded: {level_three!r}"

        step(2, "build the judge prompt for the reason without the conclusion")
        prompt = judge_prompt(
            case, "The summary states 8+ years, which includes exactly 8, so it does not "
                  "establish whether the 9 years are met.")
        assert level_three in prompt, "the judge is not given level 3 as the rubric states it"

    @story("Levels 1 and 5")
    def MQC_CAS_UNI_115029_a_claimed_match_scores_one_and_level_five_asks_nothing(
        self,
    ) -> None:
        """Only a claimed match scores 1; the reason with the mismatch scores 5, asking nothing.

        Design: ``model_evaluation_test_plan.md`` section 9.13.1.

        Returns:
            None
        """
        case, criterion = floor_rubric()
        lowest, highest = criterion.anchors[1], criterion.anchors[5]

        step(1, "read level 1 of the floor rubric")
        assert "matches" in lowest.description and "mismatch" not in lowest.description, (
            f"level 1 places a stated mismatch beside a claimed match: {lowest.description!r}"
        )
        assert "not met" not in (lowest.exemplar or ""), (
            f"level 1's exemplar states a mismatch: {lowest.exemplar!r}"
        )

        step(3, "read level 5 of the floor rubric")
        assert "8+ includes exactly 8" in highest.description and (
            "it is a mismatch" in highest.description
        ), f"level 5 does not require the reason and the mismatch: {highest.description!r}"
        asked = [word for word in ("ask", "supply", "please")
                 if word in f"{highest.description} {highest.exemplar}".lower()]
        assert not asked, (
            f"level 5 requires a request the prompt never makes, naming {asked}"
        )

        step(5, "build the judge prompt for an answer at level 5")
        prompt = judge_prompt(
            case, "The summary states 8+ years, which includes exactly 8, so it does not "
                  "establish the 9 years required. On the summary as given, it is a mismatch.")
        assert lowest.description in prompt and highest.description in prompt, (
            "the judge is not given levels 1 and 5 as the rubric states them"
        )

    @story("The prompt the model receives")
    def MQC_CAS_UNI_115030_the_floor_prompt_asks_where_and_why_the_summary_falls_short(
        self,
    ) -> None:
        """The model is asked where and why the summary falls short of a positive match.

        Design: ``model_evaluation_test_plan.md`` section 9.13.1.

        Returns:
            None
        """
        case, _ = floor_rubric()
        sent = " ".join(case.task.user_prompt.split())

        step(1, "read the prompt the floor task sends")
        assert "either way" not in sent and "rather than assuming" not in sent, (
            f"the prompt tells the model to withhold a verdict: {sent!r}"
        )

        step(2, "the prompt asks where and why the summary falls short of a positive match")
        assert "state explicitly where and why it cannot establish the requirement" in sent, (
            f"the prompt does not ask where and why the summary falls short: {sent!r}"
        )
        assert "inadequate or incomplete to make a positive match" in sent, (
            f"the prompt does not frame the shortfall against a positive match: {sent!r}"
        )
        assert "mismatch" not in sent and "does not match" not in sent, (
            f"the prompt names the verdict the model is meant to reach: {sent!r}"
        )
