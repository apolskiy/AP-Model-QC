import re

import pytest

from cmn.case_steps import step
from cmn.grouping import story

from tests.cases.graded_support import shipped_cases

pytestmark = pytest.mark.unit

_ASKS: dict[str, re.Pattern[str]] = {
    "numbered": re.compile(r"(?i)\bnumbered list\b"),
    "bulleted": re.compile(r"(?i)\bbulleted list\b"),
}
# A PROMPT'S ITEM opens a line with its number and a period or parenthesis, so
# a wrapped line opening on a figure such as "10, 90 and 50" is not one.
_PROMPT_ITEM = re.compile(r"^[ \t]*\d+[.)][ \t]", re.MULTILINE)


class TestMQCDeclaredLists:
    """A prompt asking for a list is graded by a rule declaring that list."""

    @story("A list asked for and a list declared")
    def MQC_CAS_UNI_115023_a_prompt_asking_for_a_list_no_rule_declares_is_reported(
        self,
    ) -> None:
        """Every list-asking task has a declaring rule, at the prompt's own count.

        Design: ``model_evaluation_test_plan.md`` section 9.15.3.

        Returns:
            None
        """
        step(1, "collect every task whose prompt asks for a list, with the rules grading it")
        asking: dict[str, tuple[str, str, list]] = {}
        for case in shipped_cases().values():
            prompt = case.task.user_prompt
            style = next((name for name, pattern in _ASKS.items() if pattern.search(prompt)), None)
            if style is None:
                continue
            entry = asking.setdefault(case.task.task_id, (style, prompt, []))
            entry[2].append(case.golden_rules)
        # NOT VACUOUS: the corpus asks for numbered and bulleted lists both, and
        # a check finding neither would pass by having nothing to check.
        assert {style for style, _, _ in asking.values()} == set(_ASKS), sorted(asking)

        step(2, "read whether a rule declares each list, in the style and count asked for")
        problems = []
        for task_id, (style, prompt, rules) in sorted(asking.items()):
            declared = [
                rule.answer_list for rule in rules
                if getattr(rule, "answer_list", None) is not None
            ]
            if not any(declaration.style == style for declaration in declared):
                problems.append(f"{task_id} asks for a {style} list and no rule declares one")
                continue
            items = len(_PROMPT_ITEM.findall(prompt))
            problems.extend(
                f"{task_id} numbers {items} items and a rule declares count "
                f"{declaration.count}"
                for declaration in declared
                if style == "numbered" and declaration.count != items
            )
        assert not problems, f"{len(problems)} list(s) undeclared or miscounted: {problems}"
