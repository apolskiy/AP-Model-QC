"""Unit precondition for a prompt asking for a list against the rules grading it.

Created: 2026-11-04
Last updated: 2026-11-05

This file contains ``TestMQCDeclaredLists``, one case over every shipped task
whose prompt asks for a numbered or bulleted list. It checks that a rule
grading the task declares that list, in the style the prompt names, and that a
numbered declaration's count equals the numbered lines of the prompt.

**The prompt and the declaration state one fact twice.** The prompt tells the
model how many items to write and the declaration tells the harness how many
to expect, and a count that drifts from the prompt makes the list check fail a
correct answer, silently and on every engine. The harness ``framework-rules.md``
section 4.2 governs the shape, the copies being compared by a case.

**It runs in the ``unit`` precondition gate**, ahead of the graded cases. A
failure is an instrument defect, **not a model finding**: the run exits 3 and
no graded case executes, and the module carries no priority marker, per the
harness ``framework-rules.md`` section 3.3.

Specified by ``docs/testing/model_evaluation_test_plan.md`` section 9.15.3.
"""

