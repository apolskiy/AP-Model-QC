# THE ROOT, which is as far up as a case reads (``code-style.md`` section 8.0).
_ROOT: Path = Path(__file__).resolve().parents[2]

_PROBE_WORKFLOW: str = "probe-model-version.yml"

# WHAT A GATED CONDITION READS. The resolver publishes `green` and every job
# that spends, or causes spending, reads it from the job it needs.
_GREEN: str = "needs.resolve.outputs.green"

# A VALUE SUBSTITUTED AT RUNTIME, in either of the two spellings a workflow
# uses: a shell variable the dispatch loop sets, or an Actions expression.
_INTERPOLATION: re.Pattern = re.compile(r"\$\{[^}]|\$\{\{")

# HOW THE DISPATCH ASKS WHETHER A WORKFLOW IS ENABLED, the state an active one
# reports, and the calibration caller a changed judge engine has. Section 4.23.3.
_STATE_READ: str = "/actions/workflows/"
_STATE_FIELD: str = r"--jq \.state"
_ACTIVE: str = '= "active"'
# WHAT A CHANGED ENGINE DISPATCHES: its regression run and, where it judges, its
# calibration. The dispatch itself, not the filename, since the state read
# names the file too.
_DISPATCHED: tuple[str, ...] = ("evaluate-${engine}-scheduled.yml", "calibrate-${engine}.yml")


class TestMQCVersionProbeShape:
    """Whether the probe this repository has is the one that was wanted."""

    def MQC_CAS_UNI_115789_the_probe_resolves_a_green_harness_before_it_dispatches(
        self,
    ) -> None:
        """The probe gates on the pairing and dispatches a caller that exists.

        **Both halves of the owner's ruling.** "Probe needs to live with the
        model and use green harness" names a location and a precondition, and
        the location alone is not the ruling: a probe here that dispatched on a
        version comparison alone would spend a live regression run's quota against a
        harness nothing had verified.

        **The retired harness probe failed the second half of this case too.**
        It dispatched ``evaluate-live-weekly.yml`` with
        ``--repo "${{ github.repository }}"``, which named the harness, whose
        graded markers collect nothing: a sweep over zero cases per engine. It
        also enumerated three engines while ``grok`` had been rostered since
        2026-10-04, so a quarter of the roster was unwatched.

        **The roster is the enumeration, not a list in this case.** An engine
        added to ``config/engines.yaml`` must gain a scheduled caller, and reading
        the roster is what makes that a failure here rather than a gap nobody
        notices until a version moves.

        Design: ``consumer_ci.md`` sections 4.23.2 and 4.23.3.

        Returns:
            None
        """
        definition = jobs(load(_PROBE_WORKFLOW))

        assert "resolve" in definition, (
            "the probe declares no resolve job, so nothing establishes that "
            "the harness it is about to spend against was verified"
        )
        resolver = " ".join(run_lines(definition["resolve"], _ROOT))
        assert "tools.harness_pin" in resolver, (
            "the probe's resolve job does not run the pairing resolver, so "
            f"its green output states nothing: {resolver!r}"
        )

        for name in ("probe", "dispatch"):
            assert name in definition, f"the probe declares no {name!r} job"
            assert "resolve" in needs(definition[name]), (
                f"the {name!r} job does not need the resolve job, so the "
                "pairing cannot gate it"
            )
            condition = str(definition[name].get("if") or "")
            assert _GREEN in condition, (
                f"the {name!r} job's condition does not read the resolved "
                f"pairing, so it would run against an unverified harness: "
                f"{condition!r}"
            )

        dispatch = " ".join(run_lines(definition["dispatch"], _ROOT))
        assert "github.repository" in dispatch, (
            "the dispatch does not name this repository, and the retired "
            f"harness probe dispatched into one holding no cases: {dispatch!r}"
        )
        # THE CALLER IS NAMED BY THE ENGINE, not written as one filename. A
        # single literal would dispatch the same regression run whichever engine moved,
        # which is what the retired harness probe did.
        #
        # THE DISPATCHED ARGUMENT, not the command text. Asserting that the
        # word "engine" appears anywhere in the job passes on the retired
        # shape, because the loop that reads the changed engines names the
        # variable too; the first pass of this case asserted exactly that and
        # the injection went NOT CAUGHT.
        dispatched = re.search(r"gh\s+workflow\s+run\s+\"?([^\s\"]+)", dispatch)
        assert dispatched, (
            f"the dispatch job runs no workflow dispatch at all: {dispatch!r}"
        )
        target = dispatched.group(1)
        assert target.endswith("-scheduled.yml"), (
            f"the dispatch does not name a scheduled caller: {target!r}"
        )
        assert _INTERPOLATION.search(target), (
            "the dispatched caller is a single literal, so a version move at "
            f"one provider would reach whichever regression run is named here rather "
            f"than its own: {target!r}"
        )

        rostered = sorted(load_engines(packaged_roster_path()))
        missing = [
            engine
            for engine in rostered
            if not (
                _ROOT / ".github" / "workflows" / f"evaluate-{engine}-scheduled.yml"
            ).is_file()
        ]
        assert not missing, (
            "rostered engine(s) have no scheduled caller for the probe to "
            f"dispatch, so a version move there would fail the step: {missing}"
        )


    @story("A disabled workflow is an opt-out")
    def MQC_CAS_UNI_115849_a_probe_dispatching_without_reading_the_state_is_reported(
        self,
    ) -> None:
        """The dispatch reads each workflow's state first, and dispatches the calibration too.

        **A disabled workflow is the owner's opt-out**, and ``gh workflow run``
        refuses one with HTTP 422, which failed the probe for a decision the
        owner made. Design: ``consumer_ci.md`` section 4.23.3.

        Returns:
            None
        """
        dispatch = " ".join(run_lines(jobs(load(_PROBE_WORKFLOW))["dispatch"], _ROOT))
        # EACH DISPATCH AGAINST ITS OWN READ AND ITS OWN GUARD. Checked across
        # the job, the calibration's read and guard covered for a regression run
        # dispatch that read nothing: both injections went NOT CAUGHT.
        dispatched = re.findall(r'gh workflow run "([^"]+)"', dispatch)
        unread: list[str] = []
        unguarded: list[str] = []
        for target in dispatched:
            position = dispatch.find(f'gh workflow run "{target}"')
            read = re.search(
                rf'(\w+)="\$\(gh api "[^"]*{_STATE_READ}{re.escape(target)}" {_STATE_FIELD}',
                dispatch,
            )
            if read is None or read.start() > position:
                unread.append(target)
            elif f'[ "${{{read.group(1)}}}" {_ACTIVE} ]' not in dispatch[read.end():position]:
                unguarded.append(target)

        step(1, "find the changed engine's regression run and calibration dispatched")
        assert sorted(dispatched) == sorted(_DISPATCHED), dispatched

        step(2, "find each workflow's state read before it is dispatched")
        assert not unread, unread

        step(3, "find each dispatch made only where its own workflow is active")
        assert not unguarded, unguarded


class TestMQCDispatchGating:
    """Any job here that makes another workflow spend reaches a green harness."""

    def MQC_CAS_UNI_115790_a_dispatching_job_reading_no_green_pairing_is_reported(
        self,
    ) -> None:
        """Every dispatching job in this repository is gated on the pairing.

        **The counterpart to the case above, asking the opposite question.**
        That one reads the probe and asserts it is the file that was wanted;
        this reads every workflow here and reports any job that dispatches a
        spending workflow without reading a green pairing, **including one
        written later**.

        **This repository is the root that has a pairing to read.** The checker
        is the harness's and ``MQC_CMN_UNI_112192`` calls it with the harness
        root, where it reports nothing because the harness holds no pin of its
        own.

        Design: harness ``harness_ci_pipeline.md`` section 8.9.

        Returns:
            None
        """
        reported = ungated_dispatches(_ROOT)
        assert not reported, (
            "job(s) would dispatch a workflow that spends without reading a "
            "green pairing from a job they need, so a live regression run could run "
            "against a harness nothing verified: " + "; ".join(reported)
        )
