"""Unit preconditions on the support code that calibrates the judge, one family at a time.

Created: 2026-11-10
Last updated: 2026-11-13

This file contains ``TestMQCCalibrationSupport``, twelve cases on
``tests/cases/calibration_support.py`` and the samples it reads. They check
that the calibration channel is built from a plan that records and reuses
nothing, that a judge which stops answering skips the family with its code,
that calibration is collected only where a run asks for it live, that a
family's judged cases rest on its calibration case, that both judge channels
spend against the run's ceiling, that a run publishes its spend by role after
its last case, that our checks agree with every sample with the judge
withheld, that a sample the judge disagrees with is listed by its mistake,
that a family without samples does not pass, that a disagreeing sample fails
with the harness code, and that every sample answers a shipped case of its
family.

**These run in the ``unit`` precondition gate**, ahead of the calibration
cases they support, and call no provider: a stand-in judge answers in place of
the live channel, or none is asked. A failure is an instrument defect, **not a
model finding**, and the module carries no priority marker, per the harness
``framework-rules.md`` section 3.3.

Specified by ``docs/design/consumer_ci.md`` sections 7.4.1 to 7.4.4.
"""

