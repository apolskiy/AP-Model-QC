_FAMILY = "ambiguity_discrimination"
# A FAMILY WITH NO SAMPLE FILE: its rules carry no rubric, so nothing judges it.
_UNCALIBRATED_FAMILY = "tool_compliance"
_CALIBRATION_IDS = tuple(f"MQC_EVL_CAL_{174607 + index}" for index in range(6))
