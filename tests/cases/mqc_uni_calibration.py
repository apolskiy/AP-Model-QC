    @story("The channel records nothing and reads nothing back")
    def MQC_CAS_UNI_115034_the_calibration_channel_records_and_reuses_nothing(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """The plan is live with no fixture root, and it is the plan the channel is built from.

        Design: ``consumer_ci.md`` section 7.4.1.

        Args:
            monkeypatch (pytest.MonkeyPatch): Replaces the channel builder.

        Returns:
            None
        """
        plan = calibration_plan()
        assert plan.mode == "live"
        assert plan.fixture_root is None
        assert not plan.record and not plan.fill_gaps

        built: list[dict[str, Any]] = []

        def _builder(roster: Any, engine: Any, **options: Any) -> object:
            built.append({"roster": roster, "engine": engine, **options})
            return object()

        monkeypatch.setattr(calibration_support, "judge_channel_from_roster", _builder)
        calibration_support.calibration_channel.cache_clear()
        try:
            calibration_support.calibration_channel("gemini", False)
        finally:
            calibration_support.calibration_channel.cache_clear()

        assert len(built) == 1
        assert built[0]["engine"] == "gemini"
        assert built[0]["plan"] == plan

    @story("A judge that stops answering")
    def MQC_CAS_UNI_115035_a_judge_that_stops_answering_skips_the_family(self) -> None:
        """A harness code skips the case naming it; any other error is reported, never passed.

        Design: ``consumer_ci.md`` section 7.4.1.

        Returns:
            None
        """
        stopped = StoppedJudge("QC_HARNESS_RATE_LIMIT: the judge could not be reached")
        with pytest.raises(pytest.skip.Exception, match="QC_HARNESS_RATE_LIMIT"):
            calibrate_family(_FAMILY, stand_in_binding(stopped))
        assert len(stopped.calls) == 1

        # A REPLY THAT IS NOT A JUDGEMENT measures nothing, so every sample
        # reaching it is reported as unjudged rather than agreeing.
        broken = StoppedJudge("the reply carried no scores")
        failures = calibration_failures(calibrate_family(_FAMILY, stand_in_binding(broken)))
        samples = calibration_samples(_FAMILY)
        assert len(broken.calls) == len(samples)
        assert len(failures) == len(samples) and all(
            "was not judged" in failure for failure in failures
        ), failures

    @story("Collected only where a run asks for it, under a live judge")
    def MQC_CAS_UNI_115037_calibration_is_collected_only_when_asked_for_live(
        self,
    ) -> None:
        """The graded selection collects no calibration case; asking for it needs a live judge.

        Collects in a separate pytest process with ``--collect-only``, which
        calls no judge. Design: ``consumer_ci.md`` section 7.4.1.

        Returns:
            None
        """
        # AN EMPTY EXPRESSION SELECTS EVERYTHING, so only the harness hook
        # keeps the cases out of it, which the graded selection alone would not
        # show: the cases carry no graded marker for it to miss.
        for markexpr in ("", "evaluator or tool or sec"):
            status, output = collect_calibration(
                markexpr, "--mode", "replay", "--judge-mode", "live"
            )
            collected = [case for case in _CALIBRATION_IDS if case in output]
            assert not collected, (
                f"-m {markexpr!r} collected calibration cases {collected}, so a gate "
                f"or any band of a regression run would call a live judge: exit {status}"
            )

        status, output = collect_calibration(_ASKS_FOR_CALIBRATION, "--mode", "replay")
        assert status != 0 and "QC_HARNESS_PARSER_ERROR" in output, (
            f"asking for calibration under a replayed judge was not refused: exit {status}"
        )

        status, output = collect_calibration(
            _ASKS_FOR_CALIBRATION, "--mode", "replay", "--judge-mode", "live"
        )
        assert status == 0, f"replay -> live asking for calibration did not collect: exit {status}"
        assert all(case in output for case in _CALIBRATION_IDS), (
            "replay -> live asking for calibration did not collect all six cases"
        )

    @story("A family's judged cases rest on its calibration")
    def MQC_CAS_UNI_115038_a_judged_case_rests_on_its_family_calibration_case(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """A judged case depends on its family's collected calibration case, and nothing else does.

        Design: ``consumer_ci.md`` section 7.4.2.

        Args:
            monkeypatch (pytest.MonkeyPatch): Makes building the mapping fail,
                to show a run collecting no calibration case never builds it.

        Returns:
            None
        """
        root = repository_root()
        rules = {rules.rule_id: rules for rules in shipped_corpus()[1]}
        suite = case_rules_from_suite(root)
        judged = sorted(
            name for name, (_, rule_id) in suite.items()
            if rules[rule_id].rubric is not None and rules[rule_id].families
            and rules[rule_id].families[0] == _FAMILY
        )
        unjudged = sorted(
            name for name, (_, rule_id) in suite.items() if rules[rule_id].rubric is None
        )
        assert judged and unjudged, "the corpus has no judged or no unjudged case to wire"

        # 1. THE MAPPING NAMES THE CALIBRATION CASE AND EVERY JUDGED CASE, and
        # no case a judge never reads.
        families = judged_case_families(root)
        assert families.get(_FAMILY_CALIBRATION) == _FAMILY
        assert all(families.get(name) == _FAMILY for name in judged), (
            f"judged {_FAMILY} cases missing from the mapping: "
            f"{[name for name in judged if name not in families]}"
        )
        assert not [name for name in unjudged if name in families], (
            "a case graded by assertion alone was mapped to a family"
        )

        # 2. THE COLLECTED JUDGED CASE RESTS ON THE CALIBRATION CASE.
        items = [
            CollectedCase(judged[0], "evaluator"),
            CollectedCase(unjudged[0], "evaluator"),
            CollectedCase(_FAMILY_CALIBRATION, "calibration"),
        ]
        reset_dependency_state()
        try:
            assert rest_on_family_calibration(items, root) == 1
            assert declared_dependencies(items[0]) == ["174607"]
            assert not declared_dependencies(items[1])
            assert items[2].get_closest_marker("base") is not None

            # 3. A RUN COLLECTING NO CALIBRATION CASE NEVER BUILDS THE MAPPING.
            def _refused(root_given: Any) -> dict[str, str]:
                raise LookupError(f"the mapping was built for {root_given}")

            monkeypatch.setattr(suite_support, "judged_case_families", _refused)
            alone = [CollectedCase(judged[0], "evaluator")]
            assert rest_on_family_calibration(alone, root) == 0
            assert not declared_dependencies(alone[0])
        finally:
            reset_dependency_state()

        # 4. AND THE COLLECTION HOOK WIRES IT, after every selector and before
        # the cascade is ordered.
        calls = collection_calls(root)
        assert "rest_on_family_calibration" in calls, (
            "conftest.py's collection hook does not wire judged cases to calibration"
        )
        wired = calls.index("rest_on_family_calibration")
        assert calls.index("select_named_tests") < wired < calls.index(
            "arrange_dependencies"
        ), f"the wiring runs out of order: {calls}"

    @story("The judge spends against the run's ceiling")
    def MQC_CAS_UNI_115039_both_judge_channels_spend_against_the_run_ceiling(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """The graded and calibration channels carry the run's session as their budget.

        Design: ``consumer_ci.md`` section 7.4.3.

        Args:
            monkeypatch (pytest.MonkeyPatch): Replaces both channel builders.

        Returns:
            None
        """
        plans = built_plans(monkeypatch)
        config = SimulatedGradedConfig("claude", judge_mode="live", max_spend=_CEILING)
        session = dispatch_session(config)
        assert session.max_spend == _CEILING

        judge_binding(config, "gemini")
        calibration_support.calibration_channel.cache_clear()
        try:
            calibration_support.calibration_channel("claude", False, "gemini", _CEILING)
        finally:
            calibration_support.calibration_channel.cache_clear()

        assert len(plans) == 2, f"{len(plans)} channels were built, not the graded and calibration"
        for which, plan in zip(("graded", "calibration"), plans):
            assert plan.budget is session, (
                f"the {which} judge channel spends against "
                f"{plan.budget!r}, not the run's session, so --max-spend does not count it"
            )

    @story("Both judge channels spend against the run's ceiling")
    def MQC_CAS_UNI_115041_a_run_publishes_its_spend_by_role_after_its_last_case(
        self, tmp_path: Any
    ) -> None:
        """A run writes its spend by role to JUnit and to the Allure environment file.

        Design: ``consumer_ci.md`` section 7.4.4.

        Args:
            tmp_path (Any): pytest's temporary directory, for the child's artifacts.

        Returns:
            None
        """
        published = publish_one_precondition(tmp_path, "1.5")
        spend = {
            "candidate_spend_usd": "0.0000", "judge_spend_usd": "0.0000",
            "total_spend_usd": "0.0000", "max_spend_usd": "1.5000",
            "unpriced_models": "none",
        }

        assert published.status == 0, published.output[-2000:]
        junit = {name: value for name, value in published.junit.items() if name in
                 {f"mqc.{field}" for field in spend}}
        assert junit == {f"mqc.{name}": value for name, value in spend.items()}, junit
        names = [name for name, _ in published.environment]
        assert names[-len(spend):] == list(spend), names
        assert dict(published.environment[-len(spend):]) == spend, published.environment
        assert "engine" in names[:-len(spend)], (
            f"the provenance was not written ahead of the spend: {names}"
        )

        # AFTER THE LAST CASE. A run that spends nothing publishes the same
        # figures either side of the yield, so the order is read from source.
        calls = collection_calls(repository_root(), "fixture_mqc_run_provenance")
        assert "yield" in calls and "publish_run_spend" in calls, calls
        assert calls.index("yield") < calls.index("dispatch_session") \
            < calls.index("publish_run_spend"), calls

    @story("Our checks agree with every sample")
    def MQC_CAS_UNI_115042_every_sample_agrees_with_our_checks_without_a_judge(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """Every sample's failed checks are exactly what it names, read with no judge asked.

        A sample our checks disagree with is a defective sample, found here at
        no judge spend rather than in judge calibration. Design: ``consumer_ci.md``
        section 7.4.1.1.

        Args:
            monkeypatch (pytest.MonkeyPatch): Substitutes misdeclared samples.

        Returns:
            None
        """
        samples = every_calibration_sample()
        assert sum(len(entries) for entries in samples.values()) > 0, "no sample was read"
        disagreements = checks_disagreements()
        assert not disagreements, (
            f"{len(disagreements)} sample(s) disagree with our checks: "
            + "; ".join(disagreements)
        )

        # A SAMPLE DECLARED WRONGLY EITHER WAY IS REPORTED, so the agreement
        # above is a comparison and not an empty list.
        monkeypatch.setattr(
            calibration_support, "every_calibration_sample", misdeclared_samples
        )
        reported = sorted(line.split(" ", 1)[0] for line in checks_disagreements())
        assert reported == ["CLEAN_BUT_ALTERED", "NAMES_A_HELD_CHECK"], reported

    @story("A judge disagreeing with a sample")
    def MQC_CAS_UNI_115043_a_sample_the_judge_disagrees_with_is_listed_by_its_mistake(
        self,
    ) -> None:
        """A judge clearing every flawed sample, or marking down every clean one, lists each.

        Design: ``consumer_ci.md`` section 7.4.1.

        Returns:
            None
        """
        samples = calibration_samples(_FAMILY)
        flawed = {sample.sample_id: sample for sample in samples if sample.flawed}
        clean = [sample.sample_id for sample in samples if not sample.flawed]
        assert flawed and clean, f"{_FAMILY} holds no flawed or no clean sample"

        # A JUDGE AGREEING WITH EVERY SAMPLE passes the family.
        agreeing = StandInJudge(
            lambda sample_id: _MARKS_DOWN if sample_id in flawed else _CLEARS
        )
        outcomes = calibrate_family(_FAMILY, stand_in_binding(agreeing))
        assert len(agreeing.calls) == len(samples)
        assert not calibration_failures(outcomes)

        # A JUDGE CLEARING EVERYTHING misses each stated mistake, by name.
        missed = calibration_failures(
            calibrate_family(_FAMILY, stand_in_binding(StandInJudge(lambda _: _CLEARS)))
        )
        assert len(missed) == len(flawed), missed
        for sample_id, sample in flawed.items():
            assert any(
                line.startswith(sample_id) and sample.mistake in line for line in missed
            ), f"{sample_id} was not listed with its mistake: {missed}"

        # A JUDGE MARKING DOWN EVERYTHING marks down each clean sample.
        marked = calibration_failures(
            calibrate_family(_FAMILY, stand_in_binding(StandInJudge(lambda _: _MARKS_DOWN)))
        )
        assert sorted(line.split(" ", 1)[0] for line in marked) == sorted(clean), marked

    @story("A family with nothing to calibrate")
    def MQC_CAS_UNI_115044_a_family_without_calibration_samples_does_not_pass(
        self,
    ) -> None:
        """A family with no sample file asks the judge nothing and reports a failure.

        Design: ``consumer_ci.md`` section 7.4.1.

        Returns:
            None
        """
        judge = StandInJudge(lambda _: _CLEARS)
        outcomes = calibrate_family(_UNCALIBRATED_FAMILY, stand_in_binding(judge))

        assert not judge.calls and not outcomes
        failures = calibration_failures(outcomes)
        assert len(failures) == 1 and "no calibration sample" in failures[0], failures

    @story("A disagreeing sample fails with the harness code")
    def MQC_CAS_UNI_115045_a_disagreeing_sample_fails_with_the_uncalibrated_code(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """A family with a disagreeing sample fails with QC_HARNESS_JUDGE_UNCALIBRATED, naming it.

        Design: ``consumer_ci.md`` section 7.4.2.

        Args:
            monkeypatch (pytest.MonkeyPatch): Answers the live calibration.

        Returns:
            None
        """
        outcomes = calibrate_family(
            _FAMILY, stand_in_binding(StandInJudge(lambda _: _CLEARS))
        )
        failures = calibration_failures(outcomes)
        assert failures, "the stand-in disagreed with nothing"
        monkeypatch.setattr(
            calibration_support, "calibrate_family_live", lambda config, family: outcomes
        )

        with pytest.raises(AssertionError) as raised:
            assert_calibrated(None, _FAMILY)
        message = str(raised.value)
        assert message.startswith("QC_HARNESS_JUDGE_UNCALIBRATED: "), message[:120]
        assert all(failure in message for failure in failures)

