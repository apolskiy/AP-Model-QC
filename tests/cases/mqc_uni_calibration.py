from typing import Any

import pytest

from cmn.grouping import story

from tests.cases import calibration_support
from tests.cases.calibration_support import (
    calibrate_family,
    calibration_failures,
    calibration_plan,
    family_rubric_cases,
)
from tests.cases.calibration_unit_support import (
    StandInJudge,
    StoppedJudge,
    collect_calibration,
    rubric_exemplars,
)

pytestmark = pytest.mark.unit

_FAMILY = "ambiguity_discrimination"
_UNCALIBRATED_FAMILY = "tool_compliance"
_CALIBRATION_IDS = tuple(f"MQC_EVL_EVAL_1346{index:02d}" for index in range(7))


class TestMQCCalibrationSupport:
    """A family's exemplars reach the judge alone, and only a judge in tolerance passes."""

    @story("One family's exemplars, and no other's")
    def MQC_CAS_UNI_115032_calibration_sends_every_exemplar_of_its_family_only(
        self,
    ) -> None:
        """Every exemplar of the family's rubrics is sent once, and nothing else is.

        Design: ``consumer_ci.md`` section 7.4.1.

        Returns:
            None
        """
        cases = family_rubric_cases(_FAMILY)
        assert cases, f"no shipped case of {_FAMILY} carries a rubric"
        assert all(case.golden_rules.families[0] == _FAMILY for case in cases)

        judge = StandInJudge(lambda level: level)
        calibrated = calibrate_family(_FAMILY, judge, judge_engine="stand-in")

        expected = rubric_exemplars(cases)
        assert len(judge.calls) == len(expected), (
            f"{len(judge.calls)} requests for {len(expected)} exemplars"
        )
        sent = sorted(
            (entry.case_id, entry.result.criterion_id, entry.result.intended_level)
            for entry in calibrated
        )
        assert sent == sorted(expected)
        for call in judge.calls:
            assert any(
                call.case_id.startswith(f"calibration.{case.case_id}.") for case in cases
            ), f"{call.case_id} is not a calibration request for a case of {_FAMILY}"
        assert not calibration_failures(calibrated)

    @story("An exemplar the judge places two levels away")
    def MQC_CAS_UNI_115033_an_exemplar_two_levels_off_is_listed_by_case_and_level(
        self,
    ) -> None:
        """A judge awarding 5 to every level 1 exemplar fails each of them, by name.

        Design: ``consumer_ci.md`` section 7.4.1.

        Returns:
            None
        """
        judge = StandInJudge(lambda level: 5 if level == 1 else level)
        failures = calibration_failures(
            calibrate_family(_FAMILY, judge, judge_engine="stand-in")
        )

        expected = [
            f"{case_id} {criterion_id} level 1 scored 5"
            for case_id, criterion_id, level in rubric_exemplars(
                family_rubric_cases(_FAMILY)
            )
            if level == 1
        ]
        assert expected, "the family carries no level 1 exemplar to misplace"
        assert sorted(failures) == sorted(expected)

    @story("The channel records nothing and reads nothing back")
    def MQC_CAS_UNI_115034_the_calibration_channel_records_and_reuses_nothing(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """The plan is live with no fixture root, and it is the plan the channel is built from.

        Design: ``consumer_ci.md`` section 7.4.1.

        Args:
            monkeypatch (pytest.MonkeyPatch): Replaces the channel builder.

        Returns:
            None
        """
        plan = calibration_plan()
        assert plan.mode == "live"
        assert plan.fixture_root is None
        assert not plan.record and not plan.fill_gaps

        built: list[dict[str, Any]] = []

        def _builder(roster: Any, engine: Any, **options: Any) -> object:
            built.append({"roster": roster, "engine": engine, **options})
            return object()

        monkeypatch.setattr(calibration_support, "judge_channel_from_roster", _builder)
        calibration_support.calibration_channel.cache_clear()
        try:
            calibration_support.calibration_channel("gemini", False)
        finally:
            calibration_support.calibration_channel.cache_clear()

        assert len(built) == 1
        assert built[0]["engine"] == "gemini"
        assert built[0]["plan"] == plan

    @story("A judge that stops answering")
    def MQC_CAS_UNI_115035_a_judge_that_stops_answering_skips_the_family(self) -> None:
        """A harness code skips the case naming it; any other error is not swallowed.

        Design: ``consumer_ci.md`` section 7.4.1.

        Returns:
            None
        """
        stopped = StoppedJudge("QC_HARNESS_RATE_LIMIT: the judge could not be reached")
        with pytest.raises(pytest.skip.Exception, match="QC_HARNESS_RATE_LIMIT"):
            calibrate_family(_FAMILY, stopped, judge_engine="stand-in")
        assert len(stopped.calls) == 1

        broken = StoppedJudge("the reply carried no scores")
        with pytest.raises(ValueError, match="no scores"):
            calibrate_family(_FAMILY, broken, judge_engine="stand-in")

    @story("A family with nothing to calibrate")
    def MQC_CAS_UNI_115036_a_family_that_sent_no_exemplar_does_not_pass(self) -> None:
        """A family whose rules carry no exemplar sends nothing and reports a failure.

        Design: ``consumer_ci.md`` section 7.4.1.

        Returns:
            None
        """
        judge = StandInJudge(lambda level: level)
        calibrated = calibrate_family(_UNCALIBRATED_FAMILY, judge, judge_engine="stand-in")

        assert not judge.calls and not calibrated
        failures = calibration_failures(calibrated)
        assert len(failures) == 1 and "no exemplar" in failures[0]

    @story("Collected only where a run asks for it, under a live judge")
    def MQC_CAS_UNI_115037_calibration_is_collected_only_when_asked_for_live(
        self,
    ) -> None:
        """The graded selection collects no calibration case; asking for it needs a live judge.

        Collects in a separate pytest process with ``--collect-only``, which
        calls no judge. Design: ``consumer_ci.md`` section 7.4.1.

        Returns:
            None
        """
        status, output = collect_calibration("evaluator or tool or sec", "--mode", "replay")
        collected = [case for case in _CALIBRATION_IDS if case in output]
        assert not collected, (
            f"the graded selection collected calibration cases {collected}, so a gate "
            f"or rung 1 or 3 would call a live judge: exit {status}"
        )

        status, output = collect_calibration("calibration", "--mode", "replay")
        assert status != 0 and "QC_HARNESS_PARSER_ERROR" in output, (
            f"asking for calibration under a replayed judge was not refused: exit {status}"
        )

        status, output = collect_calibration(
            "calibration", "--mode", "replay", "--judge-mode", "live"
        )
        assert status == 0, f"asking for calibration live did not collect: exit {status}"
        assert all(case in output for case in _CALIBRATION_IDS), (
            "asking for calibration under a live judge did not collect all seven cases"
        )
