import subprocess
import sys
from pathlib import Path

import pytest

from cmn.grouping import story

pytestmark = pytest.mark.unit

_ROOT = Path(__file__).resolve().parents[2]


class TestMQCBandCarry:
    """The bands run as the gate runs them, and the second adopts the first's outcomes."""

    @story("A band adopts what the band before carried")
    def MQC_CAS_UNI_115757_a_band_adopts_the_outcomes_the_band_before_carried(self) -> None:
        """The P0 band and then the P1 band, sharing one carry record, both run.

        Replayed against gemini, as ``.github/actions/band`` runs them. The
        record lives under ``reports/`` because a path outside the repository
        moves pytest's rootdir.

        Design: ``consumer_ci.md`` section 3.12.1, harness
        ``cmn_verdict_and_cli.md`` section 7.6.2.

        Returns:
            None
        """
        carry = _ROOT / "reports" / "band_carry_case" / "carry.json"
        carry.parent.mkdir(parents=True, exist_ok=True)
        carry.unlink(missing_ok=True)

        outputs: list[str] = []
        for priority in ("0", "1"):
            finished = subprocess.run(
                [sys.executable, "-m", "pytest", "-m", "evaluator or tool or sec",
                 "--engine", "gemini", "--mode", "replay", "--priority", priority,
                 "--carry-outcomes", carry.relative_to(_ROOT).as_posix(),
                 "-q", "-p", "no:randomly", "--no-header", "--tb=no"],
                cwd=_ROOT, capture_output=True, text=True, check=False, timeout=600,
                stdin=subprocess.DEVNULL,
            )
            output = finished.stdout + finished.stderr
            outputs.append(output)
            assert "QC_HARNESS_PREREQUISITE_MISMATCH" not in output, (
                f"band {priority} refused the outcomes the band before it carried:\n"
                f"{output[-1500:]}"
            )
            assert finished.returncode in (0, 1), (
                f"band {priority} exited {finished.returncode}, so it measured nothing:\n"
                f"{output[-1500:]}"
            )
        assert carry.is_file(), "the first band published no carry record"
        assert "Test results for Band P1" in outputs[1], outputs[1][-1500:]
