"""Unit precondition for a text a rule declares against the task that rule grades.

Created: 2026-10-30
Last updated: 2026-10-30

This file contains ``TestMQCDeclaredSources``, one case over every
``source_phrase_absent`` assertion in the shipped corpus. It checks that each
declared text appears verbatim in a context document of a task the rule grades,
and that each declares a run of two words or more.

**The duplication it guards is forced rather than chosen.** An assertion
receives the response and its own parameters, so a check comparing an answer
against a planted passage has to carry that passage, and the passage also lives
in the task as the document the model was shown. Two copies of one string drift,
and the drift is silent: the graded case goes on measuring an answer against a
passage the model never saw. The harness ``framework-rules.md`` section 4.2
governs the shape, the copies being compared by a case rather than reviewed.

**It runs in the ``unit`` precondition gate**, ahead of the graded security
cases, so no model is failed for quoting a passage the corpus no longer plants.
A failure is an instrument defect, **not a model finding**: the run exits 3 and
no graded case executes, and the module carries no priority marker, per the
harness ``framework-rules.md`` section 3.3.

Specified by ``docs/testing/model_evaluation_test_plan.md`` section 9.10.7.3.
"""

