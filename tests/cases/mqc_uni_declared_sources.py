import pytest

from cmn.case_steps import step
from cmn.grouping import story

from tests.cases.graded_support import shipped_cases

pytestmark = pytest.mark.unit

_KIND = "source_phrase_absent"


class TestMQCDeclaredSources:
    """A rule declaring a text to compare against declares the one the task plants."""

    @story("Two copies of a planted passage")
    def MQC_CAS_UNI_115798_a_declared_source_absent_from_the_task_it_grades_is_reported(
        self,
    ) -> None:
        """Every declared text is in a document of its task, and runs are two or more.

        Design: ``model_evaluation_test_plan.md`` section 9.10.7.3.

        Returns:
            None
        """
        step(1, "collect every declared source in the shipped corpus")
        declared = [
            (case_id, assertion)
            for case_id, case in sorted(shipped_cases().items())
            for assertion in case.golden_rules.assertions
            if assertion.kind == _KIND
        ]
        # NOT VACUOUS, AND THE COUNT SAYS SO. A corpus that stopped declaring
        # any source would pass every check below by having nothing to check,
        # which is the shape this repository has corrected before.
        assert declared, f"no {_KIND} assertion is declared anywhere in the corpus"

        step(2, "read whether each declared text is planted in the task it grades")
        cases = shipped_cases()
        missing = [
            f"{case_id} declares {assertion.assertion_id} against a text no "
            f"document of its task contains"
            for case_id, assertion in declared
            if not any(
                str(assertion.parameters.get("source", "")) in document.content
                for document in cases[case_id].task.context_documents
            )
        ]
        assert not missing, (
            f"{len(missing)} declared source(s) are not in the task they grade: "
            f"{missing}"
        )

        step(3, "read whether each declares a run of two words or more")
        short = [
            f"{case_id} declares {assertion.assertion_id} with min_words "
            f"{assertion.parameters.get('min_words')!r}"
            for case_id, assertion in declared
            if not isinstance(assertion.parameters.get("min_words"), int)
            or assertion.parameters.get("min_words") < 2
        ]
        assert not short, (
            f"{len(short)} declared source(s) ask for a run below two words, which "
            f"the harness refuses at run time rather than measuring: {short}"
        )
