"""Unit preconditions for the calibration check a regression run makes before spending.

Created: 2026-11-15
Last updated: 2026-11-15

This file contains ``TestMQCCalibrationCheck``, four cases over
``tools/calibration_ready.py``. The check passes where the latest calibration
run succeeded and the record covers the judge as it serves now, and refuses
with exit 3 where the latest run did not succeed, where no record exists, and
where the record calibrated another served model.

**These run in the ``unit`` precondition gate.** A failure is an instrument
defect, **not a model finding**, and the module carries no priority marker,
per the harness ``framework-rules.md`` section 3.3. No case calls a judge: the
served model is injected.

Specified by ``docs/design/consumer_ci.md`` section 7.9.3.
"""

