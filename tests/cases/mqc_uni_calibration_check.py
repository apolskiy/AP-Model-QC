from pathlib import Path

import pytest

from cmn.case_steps import step
from cmn.grouping import story

from tests.cases.calibration_check_support import (
    JUDGE,
    SERVED_VERSION,
    run_check,
    write_record,
)

pytestmark = pytest.mark.unit

_UNCALIBRATED = "QC_HARNESS_JUDGE_UNCALIBRATED"
_REFUSED = 3
_PASSED = 0


class TestMQCCalibrationCheck:
    """A regression run spends only on a judge whose calibration is green and current."""

    @story("The regression run checks calibration and never runs it")
    def MQC_CAS_UNI_115859_a_calibrated_judge_passes_the_check(self, tmp_path: Path) -> None:
        """A green latest run and a record of the judge as it serves now pass.

        Design: ``consumer_ci.md`` section 7.9.3.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        status = run_check(write_record(tmp_path), "success")

        step(1, "find the check passing a green, current calibration")
        assert status == _PASSED, status

    @story("The regression run checks calibration and never runs it")
    def MQC_CAS_UNI_115860_a_calibration_run_not_green_is_refused(
        self, tmp_path: Path, capsys: pytest.CaptureFixture[str],
    ) -> None:
        """A latest run that failed, or none completed, refuses with exit 3.

        Design: ``consumer_ci.md`` section 7.9.3.

        Args:
            tmp_path (Path): pytest's temporary directory.
            capsys (pytest.CaptureFixture): Captures what the check reports.

        Returns:
            None
        """
        record = write_record(tmp_path)
        failed = run_check(record, "failure")
        failed_said = capsys.readouterr().out
        absent = run_check(record, "")
        absent_said = capsys.readouterr().out

        step(1, "find a failed latest calibration refused with exit 3")
        assert failed == _REFUSED, failed

        step(2, "find the refusal carrying the uncalibrated code and the conclusion")
        assert _UNCALIBRATED in failed_said and "failure" in failed_said, failed_said

        step(3, "find no completed calibration refused with exit 3")
        assert absent == _REFUSED, absent

        step(4, "find that refusal saying no calibration run completed")
        assert _UNCALIBRATED in absent_said and "none completed" in absent_said, absent_said

    @story("The regression run checks calibration and never runs it")
    def MQC_CAS_UNI_115861_a_missing_calibration_record_is_refused(
        self, tmp_path: Path, capsys: pytest.CaptureFixture[str],
    ) -> None:
        """A green run with no record at the head of the default branch refuses.

        Design: ``consumer_ci.md`` section 7.9.3.

        Args:
            tmp_path (Path): pytest's temporary directory.
            capsys (pytest.CaptureFixture): Captures what the check reports.

        Returns:
            None
        """
        status = run_check(tmp_path / "records" / "calibration" / f"{JUDGE}.json", "success")
        said = capsys.readouterr().out

        step(1, "find a missing record refused with exit 3")
        assert status == _REFUSED, status

        step(2, "find the refusal naming the missing record for the judge")
        assert _UNCALIBRATED in said and f"no calibration record for the judge {JUDGE}" in said, \
            said

    @story("The regression run checks calibration and never runs it")
    def MQC_CAS_UNI_115862_a_record_of_another_served_model_is_refused(
        self, tmp_path: Path, capsys: pytest.CaptureFixture[str],
    ) -> None:
        """A record calibrating a model the judge no longer serves refuses, naming both.

        Design: ``consumer_ci.md`` section 7.9.3.

        Args:
            tmp_path (Path): pytest's temporary directory.
            capsys (pytest.CaptureFixture): Captures what the check reports.

        Returns:
            None
        """
        status = run_check(write_record(tmp_path), "success", "judge-2026-11-14", "e5f6a7b8")
        said = capsys.readouterr().out

        step(1, "find a record of another served model refused with exit 3")
        assert status == _REFUSED, status

        step(2, "find the refusal naming the version served now and the one calibrated")
        assert "judge-2026-11-14" in said and SERVED_VERSION in said, said
