import ast
from datetime import date, timedelta
from pathlib import Path

import pytest

from cmn.case_steps import step
from cmn.grouping import story
from cmn.quarantine import QUARANTINE_WINDOW_DAYS, QuarantineEntry
from cmn.quarantine_file import load_quarantine_for
from ingestion.cases import build_case_id

from tests.cases.graded_support import held_cases
from tests.cases.quarantine_support import dropped_names, file_entry, write_quarantine_file
from tests.cases.workflow_support import repository_root
from tools.quarantine import render

pytestmark = pytest.mark.unit

_ENGINE = "gemini"
_MODEL = "model-under-test"
_NEWER = "newer-model"
_AS_OF = date(2026, 11, 15)
_FIRST_HELD = _AS_OF - timedelta(days=60)
_HELD = build_case_id("MQC_TASK_A", "MQC_RULE_A")
_OTHER = build_case_id("MQC_TASK_B", "MQC_RULE_B")
_HELD_NAME = "MQC_CAS_EVAL_134000_held"
_PAIRS = {_HELD_NAME: ("MQC_TASK_A", "MQC_RULE_A")}


class TestMQCQuarantineSelection:
    """Only an entry in force holds its case out of a run."""

    @story("An extended hold")
    def MQC_CAS_UNI_115865_an_extended_quarantine_case_is_deselected(
        self, tmp_path: Path,
    ) -> None:
        """A hold begun sixty days ago and extended today is in force, and its case is dropped.

        Design: ``consumer_ci.md`` section 3.12.2.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        write_quarantine_file(tmp_path, _ENGINE, [file_entry(
            _HELD, _AS_OF, _MODEL, originally_quarantined_on=_FIRST_HELD.isoformat(),
        )])
        held = held_cases(tmp_path, _ENGINE, _AS_OF, _MODEL)

        step(1, "find the extended entry in force")
        assert held == frozenset({_HELD}), held

        step(2, "find its case dropped at collection")
        assert dropped_names(_PAIRS, held) == [_HELD_NAME], dropped_names(_PAIRS, held)

    @story("An expired hold")
    def MQC_CAS_UNI_115866_an_expired_quarantine_case_is_collected(
        self, tmp_path: Path,
    ) -> None:
        """An entry on the first day past its window holds nothing; a day earlier it holds.

        Design: ``consumer_ci.md`` section 3.12.2.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        lapsed = _AS_OF - timedelta(days=QUARANTINE_WINDOW_DAYS)
        write_quarantine_file(tmp_path / "lapsed", _ENGINE, [file_entry(_HELD, lapsed, _MODEL)])
        write_quarantine_file(
            tmp_path / "within", _ENGINE,
            [file_entry(_HELD, lapsed + timedelta(days=1), _MODEL)],
        )
        expired = held_cases(tmp_path / "lapsed", _ENGINE, _AS_OF, _MODEL)
        within = held_cases(tmp_path / "within", _ENGINE, _AS_OF, _MODEL)
        source = ast.parse(
            (repository_root() / "tests/cases/graded_support.py").read_text(encoding="utf-8")
        )
        reader = next(
            node for node in source.body
            if isinstance(node, ast.FunctionDef) and node.name == "_quarantine_for"
        )
        called = {
            getattr(node.func, "id", None) for node in ast.walk(reader)
            if isinstance(node, ast.Call)
        }

        step(1, "find the entry on its first expired day holding nothing")
        assert expired == frozenset(), expired

        step(2, "find its case collected")
        assert not dropped_names(_PAIRS, expired), dropped_names(_PAIRS, expired)

        step(3, "find the entry a day inside its window still held")
        assert within == frozenset({_HELD}), within

        step(4, "find the run reading today's UTC date and the rostered model")
        assert {"held_cases", "project_today", "rostered_model"} <= called, sorted(
            name for name in called if name
        )

    @story("A model change")
    def MQC_CAS_UNI_115867_a_case_whose_model_changed_is_collected(
        self, tmp_path: Path,
    ) -> None:
        """An entry observed on an older model holds nothing, unless it outlives a model change.

        Design: ``consumer_ci.md`` section 3.12.2.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        write_quarantine_file(tmp_path / "ends", _ENGINE, [file_entry(_HELD, _AS_OF, _MODEL)])
        write_quarantine_file(
            tmp_path / "stays", _ENGINE,
            [file_entry(_HELD, _AS_OF, _MODEL, ends_on_model_change=False)],
        )
        ended = held_cases(tmp_path / "ends", _ENGINE, _AS_OF, _NEWER)
        stays = held_cases(tmp_path / "stays", _ENGINE, _AS_OF, _NEWER)

        step(1, "find an entry observed on another model holding nothing")
        assert ended == frozenset(), ended

        step(2, "find its case collected")
        assert not dropped_names(_PAIRS, ended), dropped_names(_PAIRS, ended)

        step(3, "find an entry that a model change does not end still held")
        assert stays == frozenset({_HELD}), stays

    @story("A removed hold")
    def MQC_CAS_UNI_115868_a_case_removed_from_quarantine_is_collected(
        self, tmp_path: Path,
    ) -> None:
        """A case whose entry was removed is collected while another entry stays in force.

        Design: ``consumer_ci.md`` section 3.12.2.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        write_quarantine_file(tmp_path, _ENGINE, [file_entry(_OTHER, _AS_OF, _MODEL)])
        held = held_cases(tmp_path, _ENGINE, _AS_OF, _MODEL)

        step(1, "find only the remaining entry in force")
        assert held == frozenset({_OTHER}), held

        step(2, "find the removed case collected")
        assert not dropped_names(_PAIRS, held), dropped_names(_PAIRS, held)

    @story("The tool keeps the day a hold began")
    def MQC_CAS_UNI_115869_the_quarantine_tool_writes_the_original_date(
        self, tmp_path: Path,
    ) -> None:
        """A rendered entry carries its first day, model-change flag and ticket, and reads back.

        Design: ``consumer_ci.md`` section 3.12.2.

        Args:
            tmp_path (Path): pytest's temporary directory.

        Returns:
            None
        """
        entry = QuarantineEntry(
            case_id=_HELD, reason="known failure", quarantined_on=_AS_OF,
            observed_model=_MODEL, ticket="MQC-41",
            originally_quarantined_on=_FIRST_HELD, ends_on_model_change=False,
        )
        target = tmp_path / "quarantine" / f"{_ENGINE}.yaml"
        target.parent.mkdir(parents=True)
        target.write_text(render([entry]), encoding="utf-8", newline="\n")
        written = target.read_text(encoding="utf-8")
        read_back = load_quarantine_for(tmp_path, _ENGINE)

        step(1, "find the rendered file naming the day the hold began and the flag")
        assert "originally_quarantined_on" in written and "ends_on_model_change" in written, (
            written
        )

        step(2, "find the entry reading back unchanged")
        assert read_back == [entry], read_back
