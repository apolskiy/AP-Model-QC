    def MQC_CAS_UNI_115122_the_summary_score_decides_at_three(
        self, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """With every check met the judge decides: 1 and 2 fail, 3, 4 and 5 pass.

        Design: ``model_evaluation_test_plan.md`` section 9.4.3.

        Args:
            monkeypatch (pytest.MonkeyPatch): pytest's patcher.

        Returns:
            None
        """
        for number, score in enumerate(SCORES, start=1):
            step(number, f"observe the right answer, summary judged {score}")
            result, _ = observed(monkeypatch, answered(RIGHT), scores={SUMMARY: score})
            assert result.passed == (score >= _THRESHOLD), (
                f"summary {score} {'passed' if result.passed else 'failed'}, against a "
                f"threshold of {_THRESHOLD}"
            )

