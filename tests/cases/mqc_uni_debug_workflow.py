class TestMQCDebugSpending:
    """A debug run spends only after approval, little, and keeps what it recorded."""

    @story("Approval before spending")
    def MQC_CAS_UNI_115853_a_debug_job_reaching_keys_without_approval_is_reported(
        self,
    ) -> None:
        """A replay reaches no key, and a live run reaches them through debug_live.

        Design: ``consumer_ci.md`` section 6.5.

        Returns:
            None
        """
        step(1, f"find {DEBUG_REPLAY} and {DEBUG_LIVE} in {DEBUG_WORKFLOW}")
        found = debug_jobs()
        assert {DEBUG_REPLAY, DEBUG_LIVE} <= set(found), sorted(found)

        step(2, f"read whether {DEBUG_REPLAY} runs on replay alone, with no environment or key")
        replay = found[DEBUG_REPLAY]
        problems = [
            problem for problem, present in (
                (f"runs when {replay.get('if')!r}", "inputs.mode == 'replay'" not in
                 str(replay.get("if") or "")),
                (f"names {environment_of(replay)!r}", bool(environment_of(replay))),
                (f"references {sorted(provider_secrets(replay))}", bool(provider_secrets(replay))),
            ) if present
        ]
        assert not problems, f"{DEBUG_REPLAY} {problems}"

        step(3, f"read whether {DEBUG_LIVE} runs on live alone, in {DEBUG_ENVIRONMENT!r}")
        live = found[DEBUG_LIVE]
        assert ("inputs.mode == 'live'" in str(live.get("if") or "")
                and environment_of(live) == DEBUG_ENVIRONMENT), (
            f"{DEBUG_LIVE} runs when {live.get('if')!r} in {environment_of(live)!r}"
        )

        step(4, f"find every job naming {DEBUG_ENVIRONMENT!r}, and debug jobs naming "
                f"{LIVE_ENVIRONMENT!r}")
        strays = [
            name for name in jobs_naming(DEBUG_ENVIRONMENT)
            if name != f"{DEBUG_WORKFLOW}:{DEBUG_LIVE}"
        ] + [
            name for name in jobs_naming(LIVE_ENVIRONMENT)
            if name.startswith(f"{DEBUG_WORKFLOW}:")
        ]
        assert not strays, f"jobs reaching keys outside their environment: {strays}"

    @story("At most 20 tests")
    def MQC_CAS_UNI_115854_a_live_debug_past_twenty_tests_is_refused(
        self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path,
    ) -> None:
        """A live debug run defaults to $0.50 and runs at most 20 requested tests.

        Design: ``consumer_ci.md`` section 6.5.

        Args:
            monkeypatch (pytest.MonkeyPatch): Supplies the requested tests.
            tmp_path (Path): Where the list is written.

        Returns:
            None
        """
        inputs = dispatch_inputs()
        step(1, "read the ceiling's default")
        assert str((inputs.get("max_spend") or {}).get("default")) == DEFAULT_LIVE_CEILING, (
            inputs.get("max_spend")
        )

        step(2, f"read whether {DEBUG_LIVE} alone writes the list with the limit")
        limited = {
            name: any(_WRITER in body and f"--max-entries {MAX_LIVE_TESTS}" in body
                      for _, body in step_bodies(job))
            for name, job in debug_jobs().items()
        }
        assert limited == {DEBUG_REPLAY: False, DEBUG_LIVE: True}, limited

        out = tmp_path / "requested.txt"
        step(3, f"write {MAX_LIVE_TESTS} requested tests under the limit")
        monkeypatch.setenv("REQUESTED", ",".join(str(115000 + index)
                                                 for index in range(MAX_LIVE_TESTS)))
        written = write_test_list(["--out", str(out), "--max-entries", str(MAX_LIVE_TESTS)])
        assert (written, len(out.read_text(encoding="utf-8").split())) == (0, MAX_LIVE_TESTS)

        step(4, f"write {MAX_LIVE_TESTS + 1} requested tests, one past the limit")
        out.unlink()
        monkeypatch.setenv("REQUESTED", ",".join(str(115000 + index)
                                                 for index in range(MAX_LIVE_TESTS + 1)))
        refused = write_test_list(["--out", str(out), "--max-entries", str(MAX_LIVE_TESTS)])
        assert (refused, out.exists()) == (1, False), (refused, out.exists())

        step(5, "read whether the dispatch form and the live summary state the limit")
        stated = f"at most {MAX_LIVE_TESTS}"
        summary = " ".join(
            body for _, body in step_bodies(debug_jobs().get(DEBUG_LIVE) or {})
            if "GITHUB_STEP_SUMMARY" in body
        )
        description = str((inputs.get("tests") or {}).get("description") or "")
        assert stated in description.lower() and stated in summary.lower(), (
            f"tests input says {description!r}; the summary states the limit: "
            f"{stated in summary.lower()}"
        )

    @story("Keeping the recordings")
    def MQC_CAS_UNI_115855_a_live_debug_discarding_its_recordings_is_reported(
        self,
    ) -> None:
        """A live debug run copies what it recorded into its artifact, whatever the outcome.

        Design: ``consumer_ci.md`` section 6.5.

        Returns:
            None
        """
        live = debug_jobs().get(DEBUG_LIVE) or {}
        step(1, f"find the step copying {RECORDINGS} into {ARTIFACT_RECORDINGS}, run always")
        copying = [
            (position, condition)
            for position, (condition, body) in enumerate(step_bodies(live))
            if RECORDINGS in body and ARTIFACT_RECORDINGS in body
        ]
        assert copying and all("always()" in condition for _, condition in copying), (
            f"{DEBUG_LIVE} copies its recordings in {len(copying)} step(s), "
            f"conditions {[condition for _, condition in copying]}"
        )

        step(2, "read whether the copy comes before the artifact is uploaded")
        uploads = [
            position for position, entry in enumerate(live.get("steps") or [])
            if str((entry or {}).get("uses", "")).startswith("actions/upload-artifact")
        ]
        assert uploads and copying[0][0] < min(uploads), (
            f"copy at step {copying[0][0]}, uploads at {uploads}"
        )
