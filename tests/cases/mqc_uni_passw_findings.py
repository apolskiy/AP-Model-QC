    """An answer that corrected itself is a pass, counted and filed as a warning."""

    @story("A corrected answer is a pass with a warning")
    def MQC_CAS_UNI_115817_a_corrected_answer_is_recorded_passw_and_counts_as_a_pass(
        self, tmp_path: Path, capsys: pytest.CaptureFixture[str]
    ) -> None:
        """A passing result carrying a warning code is recorded passw; the band report counts it.

        Design: ``consumer_ci.md`` section 6.4.6.

        Args:
            tmp_path (Path): Where the constructed report is written.
            capsys (pytest.CaptureFixture): The band report's printed lines.

        Returns:
            None
        """
        step(1, "record a passing result that carries a warning code")
        corrected = SimpleNamespace(
            passed=True, warning_codes=[_CODE], taxonomy_codes=[], judge_skipped_reason="",
        )
        recorded = measured_fields(
            case_for(_TASK, _RULE), dispatch_outcome("gemini-4-argon", mode="replay"), corrected, 0
        )
        assert (recorded["outcome"], recorded["taxonomy_code"]) == ("passw", _CODE), recorded

        step(2, "count a report holding a passw case, a pass and a failure")
        report = tmp_path / "junit.xml"
        report.write_text(_REPORT, encoding="utf-8")
        passed, failed, skips, warned = counts_from(report)
        assert (passed, failed, skips, warned) == (1, 1, [], 1), (passed, failed, skips, warned)

        step(3, "print the band line")
        band_main([str(report), "--priority", "2"])
        printed = capsys.readouterr().out
        assert "passed: 1" in printed and "passw: 1" in printed, printed

    @story("A corrected answer is filed as a warning")
    def MQC_CAS_UNI_115818_a_passw_case_is_a_warning_finding_filed_apart(
        self, tmp_path: Path
    ) -> None:
        """The JUnit mark becomes a warning finding, ticketed, and listed apart on the sheet.

        Design: ``consumer_ci.md`` section 6.4.6.

        Args:
            tmp_path (Path): Where the constructed report is written.

        Returns:
            None
        """
        step(1, "read the warnings out of a report")
        report = tmp_path / "junit.xml"
        report.write_text(_REPORT, encoding="utf-8")
        warnings = parse_warnings(report)
        assert [(case, found["taxonomy_code"], found["severity"])
                for case, found in warnings.items()] == [(_WARNED, _CODE, "warning")], warnings

        step(2, "record them in an empty register")
        run = RunContext(
            engine="gemini", mode="replay", models={}, expected={},
            today=date(2026, 11, 6), resolve=False,
        )
        merged, _ = merge({}, warnings, run)
        assert merged[_WARNED].get("severity") == "warning", merged[_WARNED]

        step(3, "write the filing sheet with one failure and the warning")
        failure = {"case": _FAILED, "taxonomy_code": "QC_LLM_SOURCE_ALTERATION",
                   "observed_model": "gemini-4-argon"}
        sheet = filing_sheet("2026-11-06", {"gemini": [failure, merged[_WARNED]]})
        warned_at = sheet.find("### Warnings")
        assert (
            0 < warned_at < sheet.index(_WARNED) and _WARNED not in sheet[:warned_at]
            and "1 finding(s) to file" in sheet and "1 warning(s)" in sheet
        ), sheet

        step(4, "write the warning's ticket")
        ticket = "\n".join(finding_section(
            _ROOT, "gemini", merged[_WARNED], case_rules_from_suite(_ROOT), load_tasks(_ROOT)
        ))
        assert "passed with a warning" in ticket, ticket[:2000]

    @story("A corrected answer is a pass with a warning")
    def MQC_CAS_UNI_115819_the_ceiling_claim_declares_its_correction_and_anchor(self) -> None:
        """134206's claim declares corrected_by, and its level 5 anchor names a contrary statement.

        Design: ``consumer_ci.md`` section 6.4.6.

        Returns:
            None
        """
        rules = case_for(_TASK, _RULE).golden_rules
        claim = next(assertion for assertion in rules.assertions
                     if assertion.assertion_id == "A_GND_CEILING_NOT_MISCOMPARED")
        step(1, "run the claim over every recorded gemini response")
        outcomes = [
            run_assertion(claim, str(response.get("text") or "")).outcome
            for response in recorded_responses(_ROOT, "gemini", _TASK, _RULE)
        ]
        assert outcomes and set(outcomes) == {"passw"}, outcomes

        step(2, "read the level 5 anchor")
        anchor = rules.rubric.criteria[0].anchors[5].description
        assert "contrary statement" in anchor, anchor

    @story("A corrected answer is a pass with a warning")
    def MQC_CAS_UNI_115825_passw_beside_pass_or_fail_is_inconsistent(self) -> None:
        """passw beside pass or beside fail is inconsistent; the same outcome throughout agrees.

        Design: ``consumer_ci.md`` section 6.4.6.

        Returns:
            None
        """
        clean, warned, failing = (
            SimpleNamespace(passed=passed, warning_codes=codes, judge_skipped_reason="",
                            assertion_results=[])
            for passed, codes in ((True, []), (True, [_CODE]), (False, []))
        )

        step(1, "compare a passw observation with two clean passes")
        beside_pass = consistent([clean, warned, clean])
        assert beside_pass is not None and beside_pass.startswith("QC_LLM_INCONSISTENT") and (
            "3 of 3 observations passed, 1 of them with a warning" in beside_pass
        ), beside_pass

        step(2, "compare a passw observation with two failures")
        beside_fail = consistent([warned, failing, failing])
        assert beside_fail is not None and beside_fail.startswith("QC_LLM_INCONSISTENT"), (
            beside_fail
        )

        step(3, "compare observations sharing one outcome")
        agreeing = [consistent([warned, warned, warned]), consistent([clean, clean, clean])]
        assert agreeing == [None, None], agreeing
