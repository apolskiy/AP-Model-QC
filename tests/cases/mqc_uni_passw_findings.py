"""Unit preconditions for an answer that corrected itself, from record to filing sheet.

Created: 2026-11-06
Last updated: 2026-11-06

This file contains four cases on ``passw``, a pass with a warning. The record
an evaluated case writes, the band report and the findings tooling each read
it, the grounding rule whose finding prompted it declares the correction, and
repeat observations disagree when it stands beside another outcome.

``TestMQCPasswFindings`` checks that a passing result carrying a warning code
is recorded ``passw`` and counted apart in the band report, that a case
carrying the JUnit mark becomes a warning finding listed apart from the
failures on the filing sheet, and that ``134206``'s claim declares
``corrected_by`` and its level 5 anchor names the contrary statement, and
that ``passw`` beside ``pass`` or beside ``fail`` is inconsistent.

**These run in the ``unit`` precondition gate.** A failure is an instrument
defect, **not a model finding**, and the module carries no priority marker, per
the harness ``framework-rules.md`` section 3.3.

Specified by ``docs/design/consumer_ci.md`` section 6.4.6.
"""

